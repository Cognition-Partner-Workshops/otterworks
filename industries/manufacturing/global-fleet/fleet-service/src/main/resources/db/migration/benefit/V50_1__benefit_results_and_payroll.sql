CREATE TABLE benefit_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefit_period_id BIGINT NOT NULL REFERENCES benefit_period(id),
    employment_id BIGINT NOT NULL REFERENCES employment(id),
    employee_no VARCHAR(64) NOT NULL,
    vehicle_id BIGINT REFERENCES vehicle(id),
    car_days INTEGER NOT NULL,
    taxable_benefit NUMERIC(12, 2) NOT NULL,
    distance INTEGER NOT NULL,
    mileage_amount NUMERIC(12, 2) NOT NULL,
    leaver_flag VARCHAR(1),
    CONSTRAINT benefit_result_period_employment_key UNIQUE (benefit_period_id, employment_id)
);

CREATE TABLE benefit_result_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefit_result_id BIGINT NOT NULL REFERENCES benefit_result(id) ON DELETE CASCADE,
    assignment_id BIGINT NOT NULL REFERENCES assignment(id),
    vehicle_id BIGINT NOT NULL REFERENCES vehicle(id),
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    days INTEGER NOT NULL,
    monthly_benefit NUMERIC(14, 4) NOT NULL,
    benefit NUMERIC(12, 2) NOT NULL
);

CREATE TABLE benefit_payroll_file (
    benefit_period_id BIGINT PRIMARY KEY REFERENCES benefit_period(id),
    content BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
