CREATE TABLE person (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_no VARCHAR(64) NOT NULL,
    name VARCHAR(255)
);

CREATE TABLE employment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES person(id),
    grade INTEGER,
    status VARCHAR(64),
    hire_date DATE NOT NULL,
    leave_date DATE,
    monthly_contribution NUMERIC(10, 2)
);

CREATE TABLE vehicle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration VARCHAR(64) NOT NULL UNIQUE,
    list_price NUMERIC(12, 2),
    benefit_percent NUMERIC(5, 2),
    status VARCHAR(64)
);

CREATE TABLE benefit_period (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period CHAR(6) NOT NULL UNIQUE,
    start_date DATE,
    end_date DATE,
    mileage_rate NUMERIC(6, 3)
);

CREATE TABLE assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employment_id BIGINT NOT NULL REFERENCES employment(id),
    vehicle_id BIGINT NOT NULL REFERENCES vehicle(id),
    start_date DATE NOT NULL,
    end_date DATE,
    reason VARCHAR(255)
);

CREATE TABLE car_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employment_id BIGINT NOT NULL REFERENCES employment(id),
    requested_on DATE NOT NULL,
    status VARCHAR(64)
);

CREATE TABLE mileage_claim (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employment_id BIGINT NOT NULL REFERENCES employment(id),
    benefit_period_id BIGINT REFERENCES benefit_period(id),
    claim_date DATE NOT NULL,
    distance INTEGER NOT NULL,
    status VARCHAR(64) NOT NULL
);
