#!/usr/bin/env python3
"""Build sql/02_seed.sql and seed/RECONCILIATION.md from the BizTalk claims hub corpus.

The corpus lives on the fixture branch (read-only here):
    industries/insurance/biztalk-claims-intake/corpus/inputs/{fnol,payment,assignment}/
Every corpus field is loaded as-is. The FNOL messages carry no date of birth,
no street line and no bank account, so those three claimant fields are
synthetic: derived deterministically from the claim number, and listed in
claimant.synthetic_fields so nobody mistakes them for corpus data.

    python3 seed/build_seed.py                       # extract from the fixture branch
    python3 seed/build_seed.py --corpus <inputs dir> # use a checked-out corpus
"""
import argparse
import hashlib
import pathlib
import subprocess
import sys
import tarfile
import tempfile
import xml.etree.ElementTree as ET
from datetime import date, timedelta

FIXTURE_BRANCH = "origin/devin/1792473658-insurance-biztalk-fixture"
CORPUS_PATH = "industries/insurance/biztalk-claims-intake/corpus/inputs"
HERE = pathlib.Path(__file__).resolve().parent
MODULE = HERE.parent
SYNTHETIC_STREETS = ["Wharf Lane", "Chandler Row", "Ropewalk Street", "Lighthouse Road",
                     "Tidewater Court", "Mooring Way", "Breakwater Drive", "Saltmarsh Terrace"]


def text(el, tag):
    found = el.find(f".//{{*}}{tag}")
    if found is None:
        found = el.find(f".//{tag}")
    return None if found is None or found.text is None else found.text.strip()


def sql(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (list, tuple)):
        return "ARRAY[" + ", ".join(sql(v) for v in value) + "]::text[]"
    return "'" + str(value).replace("'", "''") + "'"


def synthetic(claim_number):
    seed = int(hashlib.sha256(claim_number.encode()).hexdigest(), 16)
    dob = date(1950, 1, 1) + timedelta(days=seed % 18250)
    street = f"{10 + seed % 890} {SYNTHETIC_STREETS[(seed >> 20) % len(SYNTHETIC_STREETS)]}"
    account = f"SYN{(seed >> 40) % 1000000000:09d}-{(seed >> 80) % 10**10:010d}"
    return dob.isoformat(), street, account


def extract_corpus():
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="claims-corpus-"))
    repo = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], cwd=MODULE, text=True).strip()
    rev = subprocess.check_output(["git", "rev-parse", FIXTURE_BRANCH], cwd=repo, text=True).strip()
    archive = subprocess.run(["git", "archive", rev, CORPUS_PATH], cwd=repo, check=True, capture_output=True).stdout
    tar_path = tmp / "corpus.tar"
    tar_path.write_bytes(archive)
    with tarfile.open(tar_path) as tar:
        tar.extractall(tmp, filter="data")
    return tmp / CORPUS_PATH, rev


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", type=pathlib.Path)
    ap.add_argument("--fixture-rev", default=None)
    args = ap.parse_args()
    if args.corpus:
        corpus, rev = args.corpus, args.fixture_rev or "unknown"
    else:
        corpus, rev = extract_corpus()

    fnol = sorted((corpus / "fnol").glob("*.xml"))
    payments = sorted((corpus / "payment").glob("*.xml"))
    assignments = sorted((corpus / "assignment").glob("*.xml"))

    out = [f"-- Generated by seed/build_seed.py from {FIXTURE_BRANCH} @ {rev}.",
           "-- Do not edit; rerun the generator.",
           f"-- {len(fnol)} FNOL, {len(payments)} payment, {len(assignments)} assignment messages.",
           ""]
    recon = []
    claims = set()
    for i, path in enumerate(fnol, start=1):
        root = ET.parse(path).getroot()
        claim = text(root, "ClaimNumber")
        claims.add(claim)
        dob, street, account = synthetic(claim)
        given, surname = text(root, "GivenName"), text(root, "Surname")
        out.append(
            "INSERT INTO claims.claimant (claimant_id, given_name, surname, tax_id, date_of_birth, phone, email,"
            " street, city, state, postal_code, bank_account, synthetic_fields, source_message) VALUES ("
            + ", ".join(sql(v) for v in [i, given, surname, text(root, "TaxId"), dob, text(root, "PhoneNumber"),
                                         text(root, "EmailAddr"), street, text(root, "City"),
                                         text(root, "StateProvCd"), text(root, "PostalCode"), account,
                                         ["date_of_birth", "street", "bank_account"], f"fnol/{path.name}"])
            + ");")
        police = text(root, "PoliceReportInd")
        out.append(
            "INSERT INTO claims.claim (claim_number, claimant_id, policy_number, lob, producer_id, loss_cause,"
            " loss_date, reported_date, loss_city, loss_state, loss_postal_code, estimated_loss, injury,"
            " police_report, incident_desc, source_message) VALUES ("
            + ", ".join(sql(v) for v in [claim, i, text(root, "PolicyNumber"), text(root, "LOBCd"),
                                         text(root, "ProducerId"), text(root, "LossCauseCd"), text(root, "LossDt"),
                                         text(root, "ReportedDt"), text(root, "City"), text(root, "StateProvCd"),
                                         text(root, "PostalCode"), text(root, "EstimatedLossAmt"),
                                         text(root, "InjuryInd") == "true",
                                         None if police is None else police == "true",
                                         text(root, "IncidentDesc"), f"fnol/{path.name}"])
            + ");")
        recon.append((f"fnol/{path.name}", f"claims.claimant #{i} + claims.claim {claim}", f"{given} {surname}"))

    for path in payments:
        root = ET.parse(path).getroot()
        claim = text(root, "ClaimNumber")
        if claim not in claims:
            sys.exit(f"{path.name}: claim {claim} has no FNOL message")
        payee = root.find(".//{*}Payee")
        iid = text(root, "InstructionId")
        out.append(
            "INSERT INTO claims.payment (instruction_id, claim_number, payee_name, payee_type, bank_account_masked,"
            " value_date, currency, source_message) VALUES ("
            + ", ".join(sql(v) for v in [iid, claim, text(payee, "Name"), text(payee, "PayeeType"),
                                         text(payee, "BankAccountMasked"), text(root, "ValueDate"),
                                         text(root, "CurrencyCd"), f"payment/{path.name}"])
            + ");")
        for line in root.findall(".//{*}Line"):
            out.append(
                "INSERT INTO claims.payment_line (instruction_id, line_no, line_type, amount, gl_account, memo) VALUES ("
                + ", ".join(sql(v) for v in [iid, text(line, "LineNo"), text(line, "LineType"), text(line, "Amount"),
                                             text(line, "GLAccount"), text(line, "Memo")])
                + ");")
        recon.append((f"payment/{path.name}", f"claims.payment {iid} -> {claim}", f"{text(payee, 'Name')} ({text(payee, 'PayeeType')})"))

    for path in assignments:
        root = ET.parse(path).getroot()
        claim = text(root, "ClaimNumber")
        if claim not in claims:
            sys.exit(f"{path.name}: claim {claim} has no FNOL message")
        rid = text(root, "RequestId")
        out.append(
            "INSERT INTO claims.assignment (request_id, claim_number, claimant_name, lob, loss_cause, region, severity,"
            " required_skill, requested_date, estimated_amount, source_message) VALUES ("
            + ", ".join(sql(v) for v in [rid, claim, text(root, "ClaimantName"), text(root, "LineOfBusiness"),
                                         text(root, "LossCause"), text(root, "Region"), text(root, "Severity"),
                                         text(root, "RequiredSkill"), text(root, "RequestedDt"),
                                         text(root, "EstimatedAmount"), f"assignment/{path.name}"])
            + ");")
        recon.append((f"assignment/{path.name}", f"claims.assignment {rid} -> {claim}", text(root, "ClaimantName")))

    (MODULE / "sql" / "02_seed.sql").write_text("\n".join(out) + "\n")
    lines = [f"# Corpus to table reconciliation",
             "",
             f"Generated by `seed/build_seed.py` from `{FIXTURE_BRANCH}` @ `{rev}`. One row per corpus message.",
             "",
             "| # | Corpus message | Loaded as | Party named |",
             "|---|---|---|---|"]
    for n, (src, dst, party) in enumerate(recon, start=1):
        lines.append(f"| {n} | `{src}` | {dst} | {party} |")
    lines += ["", f"Total: {len(recon)} messages, {len(recon)} loaded, 0 skipped."]
    (HERE / "RECONCILIATION.md").write_text("\n".join(lines) + "\n")
    print(f"fnol={len(fnol)} payment={len(payments)} assignment={len(assignments)} rev={rev}")


if __name__ == "__main__":
    main()
