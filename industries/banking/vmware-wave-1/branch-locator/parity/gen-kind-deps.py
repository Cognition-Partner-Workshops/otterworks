#!/usr/bin/env python3
"""Regenerate deploy/kind-deps/*-configmap.yaml from the shared wave data.

The kind Postgres loads data/seed.sql byte for byte (same rows as wave1-db) and the
geocoder stub runs vm/geo-stub/geo_stub.py unchanged. Run after either file changes.
"""
import hashlib
import json
import pathlib

here = pathlib.Path(__file__).resolve().parent
app = here.parent
wave = app.parent
out = app / "deploy" / "kind-deps"

ROLES = ("-- kind only: same grant as vm/db-roles.sql, synthetic password from deploy/kind-secrets.env\n"
         "CREATE ROLE branch_app LOGIN PASSWORD 'kind-only-branch-locator';\n"
         "GRANT SELECT ON branches TO branch_app;\n")


def configmap(name, files, note):
    lines = ["# Generated by parity/gen-kind-deps.py - do not edit. " + note,
             "apiVersion: v1", "kind: ConfigMap", "metadata:", "  name: " + name, "data:"]
    for key, text in files.items():
        lines.append("  %s: %s" % (key, json.dumps(text)))
    return "\n".join(lines) + "\n"


seed = (wave / "data" / "seed.sql").read_text()
stub = (app / "vm" / "geo-stub" / "geo_stub.py").read_text()
(out / "postgres-seed-configmap.yaml").write_text(configmap(
    "postgres-seed", {"01-seed.sql": seed, "02-roles.sql": ROLES},
    "data/seed.sql sha256 " + hashlib.sha256(seed.encode()).hexdigest()))
(out / "geo-stub-configmap.yaml").write_text(configmap(
    "geo-stub", {"geo_stub.py": stub},
    "vm/geo-stub/geo_stub.py sha256 " + hashlib.sha256(stub.encode()).hexdigest()))
print("wrote", out)
