-- OtterShops analytics platform. Run once as ACCOUNTADMIN (idempotent).
-- The service user RSA public key is set by bootstrap.py and never committed.
USE ROLE ACCOUNTADMIN;

CREATE RESOURCE MONITOR IF NOT EXISTS OTTERSHOPS_RM
  WITH CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS OTTERSHOPS_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE OTTERSHOPS_WH SET RESOURCE_MONITOR = OTTERSHOPS_RM;

CREATE DATABASE IF NOT EXISTS OTTERSHOPS;
CREATE SCHEMA IF NOT EXISTS OTTERSHOPS.RAW;
CREATE SCHEMA IF NOT EXISTS OTTERSHOPS.STAGING;
CREATE SCHEMA IF NOT EXISTS OTTERSHOPS.MARTS;

CREATE ROLE IF NOT EXISTS OTTERSHOPS_PIPELINE;
GRANT USAGE, OPERATE ON WAREHOUSE OTTERSHOPS_WH TO ROLE OTTERSHOPS_PIPELINE;
GRANT USAGE ON DATABASE OTTERSHOPS TO ROLE OTTERSHOPS_PIPELINE;
GRANT ALL ON SCHEMA OTTERSHOPS.RAW TO ROLE OTTERSHOPS_PIPELINE;
GRANT ALL ON SCHEMA OTTERSHOPS.STAGING TO ROLE OTTERSHOPS_PIPELINE;
GRANT ALL ON SCHEMA OTTERSHOPS.MARTS TO ROLE OTTERSHOPS_PIPELINE;
GRANT ROLE OTTERSHOPS_PIPELINE TO ROLE SYSADMIN;

CREATE USER IF NOT EXISTS OTTERSHOPS_SVC TYPE = SERVICE
  DEFAULT_ROLE = OTTERSHOPS_PIPELINE DEFAULT_WAREHOUSE = OTTERSHOPS_WH DEFAULT_NAMESPACE = OTTERSHOPS.RAW;
GRANT ROLE OTTERSHOPS_PIPELINE TO USER OTTERSHOPS_SVC;
