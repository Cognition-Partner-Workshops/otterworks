WITH invoice_base AS (
  SELECT i.INVOICE_ID
  FROM SFX_D1110_AFTER.COMPAT.CUSTOMER_ACCOUNT a
  JOIN SFX_D1110_AFTER.COMPAT.INVOICE_HDR i ON a.CUSTOMER_ID = i.CUSTOMER_ID
), invoices AS (
  SELECT h.INVOICE_NUMBER, a.ACCOUNT_NUMBER, h.INVOICE_DT, h.CURRENCY_CD, h.TOTAL_AMOUNT,
    ZEROIFNULL(h.TAX_AMOUNT) AS TAX_AMOUNT, h.TOTAL_AMOUNT - ZEROIFNULL(p.PAID) AS OPEN_BALANCE
  FROM invoice_base b
  JOIN SFX_D1110_AFTER.COMPAT.INVOICE_HDR h ON h.INVOICE_ID = b.INVOICE_ID
  JOIN SFX_D1110_AFTER.COMPAT.CUSTOMER_ACCOUNT a ON a.CUSTOMER_ID = h.CUSTOMER_ID
  LEFT JOIN (SELECT INVOICE_ID, SUM(AMOUNT) AS PAID FROM SFX_D1110_AFTER.COMPAT.PAYMENT GROUP BY INVOICE_ID) p ON p.INVOICE_ID = h.INVOICE_ID
  WHERE h.BILL_DT = TO_DATE(%(extract_date)s)
    AND h.INVOICE_DT >= DATE '2020-01-01'
    AND h.BILL_DT <= DATEADD(day, -1, CURRENT_DATE())
)
SELECT TRIM(INVOICE_NUMBER) || ',' || TRIM(ACCOUNT_NUMBER) || ',' || TO_CHAR(INVOICE_DT, 'YYYY-MM-DD') || ',' ||
  TO_CHAR(TOTAL_AMOUNT, 'FM9999999999990.00') || ',' || TO_CHAR(TAX_AMOUNT, 'FM9999999999990.00') || ',' ||
  TO_CHAR(OPEN_BALANCE, 'FM9999999999990.00') || ',' || TRIM(CURRENCY_CD) AS REPORT_ROW
FROM invoices ORDER BY UPPER(INVOICE_NUMBER), INVOICE_NUMBER
