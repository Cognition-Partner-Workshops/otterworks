WITH billed AS (
  SEL CAST(CAST(INVOICE_DT AS FORMAT 'YYYY-MM') AS CHAR(7)) AS MONTH_LABEL,
    SUM(TOTAL_AMOUNT) AS BILLED
  FROM SFX_BILLING.INVOICE_HDR WHERE INVOICE_DT >= ADD_MONTHS(CURRENT_DATE, -12)
    AND INVOICE_DT >= 1200101 GROUP BY 1
), open_ar AS (
  SEL b.MONTH_LABEL, SUM(i.TOTAL_AMOUNT - ZEROIFNULL(p.PAID)) AS OPEN_AR
  FROM billed b JOIN SFX_BILLING.INVOICE_HDR i
    ON i.INVOICE_DT <= LAST_DAY(CAST(b.MONTH_LABEL || '-01' AS DATE FORMAT 'YYYY-MM-DD'))
  LEFT JOIN (
    SEL b.MONTH_LABEL, p.INVOICE_ID, SUM(p.AMOUNT) AS PAID
    FROM billed b JOIN SFX_BILLING.PAYMENT p
      ON p.PAYMENT_DT <= LAST_DAY(CAST(b.MONTH_LABEL || '-01' AS DATE FORMAT 'YYYY-MM-DD'))
    GROUP BY 1, 2
  ) p ON p.INVOICE_ID = i.INVOICE_ID AND p.MONTH_LABEL = b.MONTH_LABEL
  WHERE i.INVOICE_DT >= 1200101 GROUP BY 1
), ratios AS (
  SEL b.MONTH_LABEL, a.OPEN_AR / NULLIFZERO(b.BILLED) * 30 AS DSO
  FROM billed b JOIN open_ar a ON a.MONTH_LABEL = b.MONTH_LABEL
)
SEL MONTH_LABEL, ZEROIFNULL(DSO) AS DSO FROM ratios ORDER BY 1
