WITH balances AS (
  SEL i.CUSTOMER_ID, i.INVOICE_DT + 30 AS DUE_DT, i.TOTAL_AMOUNT - ZEROIFNULL(p.PAID) AS OPEN_BALANCE
  FROM SFX_BILLING.INVOICE_HDR i
  LEFT JOIN (SEL INVOICE_ID, SUM(AMOUNT) AS PAID FROM SFX_BILLING.PAYMENT GROUP BY INVOICE_ID) p
    ON p.INVOICE_ID = i.INVOICE_ID
  WHERE i.INVOICE_DT >= 1200101 AND (i.INVOICE_DT + 30) < CURRENT_DATE - 30
)
SEL TOP 10 a.ACCOUNT_NUMBER AS ACCOUNT_NO, a.ACCOUNT_NAME AS CUSTOMER_NAME,
  CAST(MIN(b.DUE_DT) AS DATE FORMAT 'YYYY-MM-DD') AS OLDEST_DUE_DATE,
  SUM(b.OPEN_BALANCE) AS OVERDUE_BALANCE
FROM balances b JOIN SFX_BILLING.CUSTOMER_ACCOUNT a ON a.CUSTOMER_ID = b.CUSTOMER_ID
WHERE b.OPEN_BALANCE > 0 GROUP BY a.ACCOUNT_NUMBER, a.ACCOUNT_NAME
ORDER BY OVERDUE_BALANCE DESC, a.ACCOUNT_NUMBER
