WITH billed AS (
  SEL CAST(CAST(INVOICE_DT AS FORMAT 'YYYY-MM') AS CHAR(7)) AS MONTH_LABEL,
    SUM(TOTAL_AMOUNT) AS BILLED
  FROM SFX_BILLING.INVOICE_HDR WHERE INVOICE_DT >= CURRENT_DATE - 90
    AND INVOICE_DT >= 1200101 GROUP BY 1
), cash AS (
  SEL CAST(CAST(PAYMENT_DT AS FORMAT 'YYYY-MM') AS CHAR(7)) AS MONTH_LABEL,
    SUM(AMOUNT) AS COLLECTED
  FROM SFX_BILLING.PAYMENT WHERE PAYMENT_DT >= CURRENT_DATE - 90 GROUP BY 1
)
SEL COALESCE(b.MONTH_LABEL, c.MONTH_LABEL) AS MONTH_LABEL,
  ZEROIFNULL(b.BILLED) AS BILLED, ZEROIFNULL(c.COLLECTED) AS COLLECTED
FROM billed b FULL OUTER JOIN cash c ON c.MONTH_LABEL = b.MONTH_LABEL ORDER BY 1
