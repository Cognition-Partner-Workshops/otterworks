SELECT TO_CHAR(invoices.INVOICE_DATE, 'YYYY-MM') AS LABEL,
  SUM(COALESCE(invoices.TOTAL_AMOUNT, 0)) AS AMOUNT
FROM SFX_D1110_AFTER.COMPAT.INVOICE AS invoices
LEFT JOIN SFX_D1110_AFTER.COMPAT.ACCOUNT AS accounts ON invoices.CUSTOMER_ID = accounts.CUSTOMER_ID
LEFT JOIN SFX_D1110_AFTER.RAW_BILLING.CUSTOMER_ACCOUNT AS customers ON accounts.CUSTOMER_ID = customers.CUSTOMER_ID
GROUP BY 1
ORDER BY 1
