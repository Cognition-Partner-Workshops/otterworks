SEL CAST(CAST(invoices.INVOICE_DT AS FORMAT 'YYYY-MM') AS CHAR(7)) AS LABEL,
  SUM(ZEROIFNULL(invoices.TOTAL_AMOUNT)) AS AMOUNT
FROM SFX_BILLING.INVOICE_HDR AS invoices
LEFT JOIN SFX_BILLING.CUSTOMER_ACCOUNT AS accounts ON invoices.CUSTOMER_ID = accounts.CUSTOMER_ID
LEFT JOIN SFX_BILLING.CUSTOMER_ACCOUNT AS customers ON accounts.CUSTOMER_ID = customers.CUSTOMER_ID
GROUP BY 1
ORDER BY 1
