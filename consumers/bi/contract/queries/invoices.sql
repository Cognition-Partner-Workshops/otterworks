SEL (invoices.INVOICE_DT (FORMAT 'YYYY-MM') (CHAR(7))) AS LABEL,
  SUM(ZEROIFNULL(invoices.AMOUNT_DUE)) AS AMOUNT
FROM FIN_DW.INVOICE AS invoices
LEFT JOIN FIN_DW.ACCOUNT AS accounts ON invoices.ACCOUNT_ID = accounts.ACCOUNT_ID
LEFT JOIN FIN_DW.CUSTOMER AS customers ON accounts.CUSTOMER_ID = customers.CUSTOMER_ID
GROUP BY 1
ORDER BY 1
