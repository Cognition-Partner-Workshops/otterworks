SELECT EXTRACT(YEAR FROM gl_journal.POSTING_DATE) * 100 + EXTRACT(MONTH FROM gl_journal.POSTING_DATE) AS LABEL,
  SUM(COALESCE(gl_journal.DEBIT_AMOUNT, 0) - COALESCE(gl_journal.CREDIT_AMOUNT, 0)) AS AMOUNT
FROM SFX_D1110_AFTER.COMPAT.GL_JOURNAL_LINE AS gl_journal
LEFT JOIN SFX_D1110_AFTER.RAW_BILLING.GL_ACCOUNT AS gl_accounts ON gl_journal.GL_ACCOUNT_ID = gl_accounts.GL_ACCOUNT_ID
GROUP BY 1
ORDER BY 1
