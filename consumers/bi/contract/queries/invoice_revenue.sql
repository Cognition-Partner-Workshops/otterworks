SELECT invoice_revenue.INVOICE_PERIOD AS LABEL,
  SUM(COALESCE(invoice_revenue.TOTAL_AMOUNT, 0)) AS AMOUNT
FROM (SELECT a.CURRENCY_CODE AS CURRENCY_CD,
        TO_CHAR(i.INVOICE_DATE, 'YYYY-MM') AS INVOICE_PERIOD,
        COUNT(*) AS INVOICE_COUNT, SUM(i.TOTAL_AMOUNT) AS TOTAL_AMOUNT
      FROM SFX_D1110_AFTER.COMPAT.INVOICE i
      INNER JOIN SFX_D1110_AFTER.COMPAT.ACCOUNT a ON a.CUSTOMER_ID = i.CUSTOMER_ID
      GROUP BY a.CURRENCY_CODE, TO_CHAR(i.INVOICE_DATE, 'YYYY-MM')) AS invoice_revenue
GROUP BY 1
ORDER BY 1
