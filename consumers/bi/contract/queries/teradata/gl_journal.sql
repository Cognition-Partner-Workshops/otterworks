SEL EXTRACT(YEAR FROM gl_journal.POSTING_DT) * 100 + EXTRACT(MONTH FROM gl_journal.POSTING_DT) AS LABEL,
  SUM(ZEROIFNULL(gl_journal.DEBIT_AMOUNT) - ZEROIFNULL(gl_journal.CREDIT_AMOUNT)) AS AMOUNT
FROM SFX_BILLING.GL_JOURNAL_LINE AS gl_journal
LEFT JOIN SFX_BILLING.GL_ACCOUNT AS gl_accounts ON gl_journal.GL_ACCOUNT_ID = gl_accounts.GL_ACCOUNT_ID
GROUP BY 1
ORDER BY 1
