-- Landing tables that carry customer email (workloads/index.yaml source_tables).
-- Credentials (auth users.password_hash, mfa_secret) are not landed.
CREATE TABLE IF NOT EXISTS {{ db_churn_model }}.RAW.AUTH_USERS (
  ID VARCHAR(36) NOT NULL,
  EMAIL VARCHAR(255) NOT NULL,
  DISPLAY_NAME VARCHAR(100) NOT NULL,
  AVATAR_URL VARCHAR(500),
  EMAIL_VERIFIED BOOLEAN NOT NULL,
  MFA_ENABLED BOOLEAN NOT NULL,
  CREATED_AT TIMESTAMP_TZ NOT NULL,
  UPDATED_AT TIMESTAMP_TZ NOT NULL,
  LAST_LOGIN_AT TIMESTAMP_TZ
) COMMENT = 'auth-service users, landed for churn_model';

CREATE TABLE IF NOT EXISTS {{ db_churn_model }}.RAW.ADMIN_ADMIN_USERS (
  ID VARCHAR(36) NOT NULL,
  EMAIL VARCHAR(255) NOT NULL,
  DISPLAY_NAME VARCHAR(255) NOT NULL,
  ROLE VARCHAR(255) NOT NULL,
  STATUS VARCHAR(255) NOT NULL,
  AVATAR_URL VARCHAR(255),
  METADATA VARIANT,
  LAST_LOGIN_AT TIMESTAMP_NTZ,
  SUSPENDED_AT TIMESTAMP_NTZ,
  SUSPENDED_REASON VARCHAR(255),
  CREATED_AT TIMESTAMP_NTZ NOT NULL,
  UPDATED_AT TIMESTAMP_NTZ NOT NULL
) COMMENT = 'admin-service admin_users, landed for churn_model';

