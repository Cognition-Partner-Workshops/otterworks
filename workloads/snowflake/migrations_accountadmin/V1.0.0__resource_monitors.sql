-- Needs ACCOUNTADMIN: creating resource monitors and assigning them to warehouses.
-- README rule 6: monthly, 10 credits, notify at 75%, suspend at 100%, suspend immediately at 110%.
CREATE RESOURCE MONITOR IF NOT EXISTS {{ rm_doc_usage_dashboard }} WITH
  CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;
CREATE RESOURCE MONITOR IF NOT EXISTS {{ rm_doc_search_api }} WITH
  CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;
CREATE RESOURCE MONITOR IF NOT EXISTS {{ rm_churn_model }} WITH
  CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;
CREATE RESOURCE MONITOR IF NOT EXISTS {{ migrations_rm }} WITH
  CREDIT_QUOTA = 2 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE {{ wh_doc_usage_dashboard }} SET RESOURCE_MONITOR = {{ rm_doc_usage_dashboard }};
ALTER WAREHOUSE {{ wh_doc_search_api }} SET RESOURCE_MONITOR = {{ rm_doc_search_api }};
ALTER WAREHOUSE {{ wh_churn_model }} SET RESOURCE_MONITOR = {{ rm_churn_model }};
ALTER WAREHOUSE {{ migrations_wh }} SET RESOURCE_MONITOR = {{ migrations_rm }};

-- Lets the run's builder role see the monitors (SHOW RESOURCE MONITORS) without changing them.
GRANT MONITOR ON RESOURCE MONITOR {{ rm_doc_usage_dashboard }} TO ROLE SFNFR_20261104_BUILDER;
GRANT MONITOR ON RESOURCE MONITOR {{ rm_doc_search_api }} TO ROLE SFNFR_20261104_BUILDER;
GRANT MONITOR ON RESOURCE MONITOR {{ rm_churn_model }} TO ROLE SFNFR_20261104_BUILDER;
GRANT MONITOR ON RESOURCE MONITOR {{ migrations_rm }} TO ROLE SFNFR_20261104_BUILDER;
