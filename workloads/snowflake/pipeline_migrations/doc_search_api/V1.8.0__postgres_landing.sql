ALTER WAREHOUSE {{ wh_doc_search_api }} SET WAREHOUSE_SIZE = 'XSMALL';
CREATE FILE FORMAT IF NOT EXISTS {{ format_doc_search_api }} TYPE = CSV COMPRESSION = GZIP
 SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = ('\\N')
 EMPTY_FIELD_AS_NULL = FALSE TIMESTAMP_FORMAT = AUTO;
CREATE STAGE IF NOT EXISTS {{ stage_doc_search_api }} FILE_FORMAT = {{ format_doc_search_api }};
CREATE TABLE {{ db_doc_search_api }}.RAW.ANALYTICS_ANALYTICS_EVENTS (
 ID NUMBER(19,0),EVENT_ID VARCHAR(64),EVENT_TYPE VARCHAR(64),USER_ID VARCHAR(128),RESOURCE_ID VARCHAR(128),RESOURCE_TYPE VARCHAR(64),METADATA VARCHAR,OCCURRED_AT NUMBER(19,0),
 _EXPORT_ID VARCHAR(36), _EXPORTED_AT TIMESTAMP_TZ, _FILE_NAME VARCHAR, _FILE_ROW_NUMBER NUMBER, _LOADED_AT TIMESTAMP_TZ
);
GRANT SELECT ON TABLE {{ db_doc_search_api }}.RAW.ANALYTICS_ANALYTICS_EVENTS TO ROLE {{ analyst_role }};
CREATE TABLE {{ db_doc_search_api }}.RAW.DOCUMENT_DOCUMENTS (
 ID VARCHAR(36),TITLE VARCHAR(500),CONTENT VARCHAR,CONTENT_TYPE VARCHAR(50),OWNER_ID VARCHAR(36),FOLDER_ID VARCHAR(36),IS_DELETED BOOLEAN,IS_TEMPLATE BOOLEAN,WORD_COUNT INTEGER,VERSION INTEGER,CREATED_AT TIMESTAMP_TZ,UPDATED_AT TIMESTAMP_TZ,
 _EXPORT_ID VARCHAR(36), _EXPORTED_AT TIMESTAMP_TZ, _FILE_NAME VARCHAR, _FILE_ROW_NUMBER NUMBER, _LOADED_AT TIMESTAMP_TZ
);
GRANT SELECT ON TABLE {{ db_doc_search_api }}.RAW.DOCUMENT_DOCUMENTS TO ROLE {{ analyst_role }};
CREATE OR REPLACE PROCEDURE {{ db_doc_search_api }}.RAW.LOAD_RAW()
 RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
 COPY INTO {{ db_doc_search_api }}.RAW.ANALYTICS_ANALYTICS_EVENTS (ID, EVENT_ID, EVENT_TYPE, USER_ID, RESOURCE_ID, RESOURCE_TYPE, METADATA, OCCURRED_AT, _EXPORT_ID, _EXPORTED_AT, _FILE_NAME, _FILE_ROW_NUMBER, _LOADED_AT)
 FROM (SELECT t.$1, t.$2, t.$3, t.$4, t.$5, t.$6, t.$7, t.$8, t.$9, t.$10, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
 FROM @{{ stage_doc_search_api }}/analytics_events/ t)
 FILE_FORMAT = (FORMAT_NAME = '{{ format_doc_search_api }}') ON_ERROR = ABORT_STATEMENT;
 COPY INTO {{ db_doc_search_api }}.RAW.DOCUMENT_DOCUMENTS (ID, TITLE, CONTENT, CONTENT_TYPE, OWNER_ID, FOLDER_ID, IS_DELETED, IS_TEMPLATE, WORD_COUNT, VERSION, CREATED_AT, UPDATED_AT, _EXPORT_ID, _EXPORTED_AT, _FILE_NAME, _FILE_ROW_NUMBER, _LOADED_AT)
 FROM (SELECT t.$1, t.$2, t.$3, t.$4, t.$5, t.$6, t.$7, t.$8, t.$9, t.$10, t.$11, t.$12, t.$13, t.$14, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
 FROM @{{ stage_doc_search_api }}/documents/ t)
 FILE_FORMAT = (FORMAT_NAME = '{{ format_doc_search_api }}') ON_ERROR = ABORT_STATEMENT;
 RETURN 'RAW load complete';
END;
$$;
