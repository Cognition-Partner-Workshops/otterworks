CREATE FILE FORMAT IF NOT EXISTS {{ format_churn_model }} TYPE = CSV COMPRESSION = GZIP
 SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = ('\\N')
 EMPTY_FIELD_AS_NULL = FALSE TIMESTAMP_FORMAT = AUTO;
CREATE STAGE IF NOT EXISTS {{ stage_churn_model }} FILE_FORMAT = {{ format_churn_model }};
ALTER TABLE {{ db_churn_model }}.RAW.AUTH_USERS ADD COLUMN _EXPORT_ID VARCHAR(36), _EXPORTED_AT TIMESTAMP_TZ, _FILE_NAME VARCHAR, _FILE_ROW_NUMBER NUMBER, _LOADED_AT TIMESTAMP_TZ;
GRANT SELECT ON TABLE {{ db_churn_model }}.RAW.AUTH_USERS TO ROLE {{ analyst_role }};
ALTER TABLE {{ db_churn_model }}.RAW.ADMIN_ADMIN_USERS ADD COLUMN _EXPORT_ID VARCHAR(36), _EXPORTED_AT TIMESTAMP_TZ, _FILE_NAME VARCHAR, _FILE_ROW_NUMBER NUMBER, _LOADED_AT TIMESTAMP_TZ;
GRANT SELECT ON TABLE {{ db_churn_model }}.RAW.ADMIN_ADMIN_USERS TO ROLE {{ analyst_role }};
CREATE TABLE {{ db_churn_model }}.RAW.DOCUMENT_DOCUMENT_VERSIONS (
 ID VARCHAR(36),DOCUMENT_ID VARCHAR(36),VERSION_NUMBER INTEGER,TITLE VARCHAR(500),CONTENT VARCHAR,CREATED_BY VARCHAR(36),CREATED_AT TIMESTAMP_TZ,
 _EXPORT_ID VARCHAR(36), _EXPORTED_AT TIMESTAMP_TZ, _FILE_NAME VARCHAR, _FILE_ROW_NUMBER NUMBER, _LOADED_AT TIMESTAMP_TZ
);
GRANT SELECT ON TABLE {{ db_churn_model }}.RAW.DOCUMENT_DOCUMENT_VERSIONS TO ROLE {{ analyst_role }};
CREATE OR REPLACE PROCEDURE {{ db_churn_model }}.RAW.LOAD_RAW()
 RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
 COPY INTO {{ db_churn_model }}.RAW.AUTH_USERS (ID, EMAIL, DISPLAY_NAME, AVATAR_URL, EMAIL_VERIFIED, MFA_ENABLED, CREATED_AT, UPDATED_AT, LAST_LOGIN_AT, _EXPORT_ID, _EXPORTED_AT, _FILE_NAME, _FILE_ROW_NUMBER, _LOADED_AT)
 FROM (SELECT t.$1, t.$2, t.$3, t.$4, t.$5, t.$6, t.$7, t.$8, t.$9, t.$10, t.$11, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
 FROM @{{ stage_churn_model }}/users/ t)
 FILE_FORMAT = (FORMAT_NAME = '{{ format_churn_model }}') ON_ERROR = ABORT_STATEMENT;
 COPY INTO {{ db_churn_model }}.RAW.ADMIN_ADMIN_USERS (ID, EMAIL, DISPLAY_NAME, ROLE, STATUS, AVATAR_URL, METADATA, LAST_LOGIN_AT, SUSPENDED_AT, SUSPENDED_REASON, CREATED_AT, UPDATED_AT, _EXPORT_ID, _EXPORTED_AT, _FILE_NAME, _FILE_ROW_NUMBER, _LOADED_AT)
 FROM (SELECT t.$1, t.$2, t.$3, t.$4, t.$5, t.$6, PARSE_JSON(t.$7), t.$8, t.$9, t.$10, t.$11, t.$12, t.$13, t.$14, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
 FROM @{{ stage_churn_model }}/admin_users/ t)
 FILE_FORMAT = (FORMAT_NAME = '{{ format_churn_model }}') ON_ERROR = ABORT_STATEMENT;
 COPY INTO {{ db_churn_model }}.RAW.DOCUMENT_DOCUMENT_VERSIONS (ID, DOCUMENT_ID, VERSION_NUMBER, TITLE, CONTENT, CREATED_BY, CREATED_AT, _EXPORT_ID, _EXPORTED_AT, _FILE_NAME, _FILE_ROW_NUMBER, _LOADED_AT)
 FROM (SELECT t.$1, t.$2, t.$3, t.$4, t.$5, t.$6, t.$7, t.$8, t.$9, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
 FROM @{{ stage_churn_model }}/document_versions/ t)
 FILE_FORMAT = (FORMAT_NAME = '{{ format_churn_model }}') ON_ERROR = ABORT_STATEMENT;
 RETURN 'RAW load complete';
END;
$$;
