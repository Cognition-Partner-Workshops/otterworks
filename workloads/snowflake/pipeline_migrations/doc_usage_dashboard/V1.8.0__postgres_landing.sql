CREATE FILE FORMAT IF NOT EXISTS {{ format_doc_usage_dashboard }} TYPE = CSV COMPRESSION = GZIP
 SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = ('\\N')
 EMPTY_FIELD_AS_NULL = FALSE TIMESTAMP_FORMAT = AUTO;
CREATE STAGE IF NOT EXISTS {{ stage_doc_usage_dashboard }} FILE_FORMAT = {{ format_doc_usage_dashboard }};
CREATE TABLE {{ db_doc_usage_dashboard }}.RAW.ADMIN_STORAGE_QUOTAS (
 ID VARCHAR(36),USER_ID VARCHAR(36),QUOTA_BYTES NUMBER(19,0),USED_BYTES NUMBER(19,0),TIER VARCHAR(255),CREATED_AT TIMESTAMP_NTZ,UPDATED_AT TIMESTAMP_NTZ,
 _EXPORT_ID VARCHAR(36), _EXPORTED_AT TIMESTAMP_TZ, _FILE_NAME VARCHAR, _FILE_ROW_NUMBER NUMBER, _LOADED_AT TIMESTAMP_TZ
);
GRANT SELECT ON TABLE {{ db_doc_usage_dashboard }}.RAW.ADMIN_STORAGE_QUOTAS TO ROLE {{ analyst_role }};
ALTER TABLE {{ db_doc_usage_dashboard }}.RAW.ADMIN_ADMIN_USERS ADD COLUMN _EXPORT_ID VARCHAR(36), _EXPORTED_AT TIMESTAMP_TZ, _FILE_NAME VARCHAR, _FILE_ROW_NUMBER NUMBER, _LOADED_AT TIMESTAMP_TZ;
GRANT SELECT ON TABLE {{ db_doc_usage_dashboard }}.RAW.ADMIN_ADMIN_USERS TO ROLE {{ analyst_role }};
CREATE TABLE {{ db_doc_usage_dashboard }}.RAW.DOCUMENT_DOCUMENTS (
 ID VARCHAR(36),TITLE VARCHAR(500),CONTENT VARCHAR,CONTENT_TYPE VARCHAR(50),OWNER_ID VARCHAR(36),FOLDER_ID VARCHAR(36),IS_DELETED BOOLEAN,IS_TEMPLATE BOOLEAN,WORD_COUNT INTEGER,VERSION INTEGER,CREATED_AT TIMESTAMP_TZ,UPDATED_AT TIMESTAMP_TZ,
 _EXPORT_ID VARCHAR(36), _EXPORTED_AT TIMESTAMP_TZ, _FILE_NAME VARCHAR, _FILE_ROW_NUMBER NUMBER, _LOADED_AT TIMESTAMP_TZ
);
GRANT SELECT ON TABLE {{ db_doc_usage_dashboard }}.RAW.DOCUMENT_DOCUMENTS TO ROLE {{ analyst_role }};
CREATE OR REPLACE PROCEDURE {{ db_doc_usage_dashboard }}.RAW.LOAD_RAW()
 RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
 COPY INTO {{ db_doc_usage_dashboard }}.RAW.ADMIN_STORAGE_QUOTAS (ID, USER_ID, QUOTA_BYTES, USED_BYTES, TIER, CREATED_AT, UPDATED_AT, _EXPORT_ID, _EXPORTED_AT, _FILE_NAME, _FILE_ROW_NUMBER, _LOADED_AT)
 FROM (SELECT t.$1, t.$2, t.$3, t.$4, t.$5, t.$6, t.$7, t.$8, t.$9, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
 FROM @{{ stage_doc_usage_dashboard }}/storage_quotas/ t)
 FILE_FORMAT = (FORMAT_NAME = '{{ format_doc_usage_dashboard }}') ON_ERROR = ABORT_STATEMENT;
 COPY INTO {{ db_doc_usage_dashboard }}.RAW.ADMIN_ADMIN_USERS (ID, EMAIL, DISPLAY_NAME, ROLE, STATUS, AVATAR_URL, METADATA, LAST_LOGIN_AT, SUSPENDED_AT, SUSPENDED_REASON, CREATED_AT, UPDATED_AT, _EXPORT_ID, _EXPORTED_AT, _FILE_NAME, _FILE_ROW_NUMBER, _LOADED_AT)
 FROM (SELECT t.$1, t.$2, t.$3, t.$4, t.$5, t.$6, PARSE_JSON(t.$7), t.$8, t.$9, t.$10, t.$11, t.$12, t.$13, t.$14, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
 FROM @{{ stage_doc_usage_dashboard }}/admin_users/ t)
 FILE_FORMAT = (FORMAT_NAME = '{{ format_doc_usage_dashboard }}') ON_ERROR = ABORT_STATEMENT;
 COPY INTO {{ db_doc_usage_dashboard }}.RAW.DOCUMENT_DOCUMENTS (ID, TITLE, CONTENT, CONTENT_TYPE, OWNER_ID, FOLDER_ID, IS_DELETED, IS_TEMPLATE, WORD_COUNT, VERSION, CREATED_AT, UPDATED_AT, _EXPORT_ID, _EXPORTED_AT, _FILE_NAME, _FILE_ROW_NUMBER, _LOADED_AT)
 FROM (SELECT t.$1, t.$2, t.$3, t.$4, t.$5, t.$6, t.$7, t.$8, t.$9, t.$10, t.$11, t.$12, t.$13, t.$14, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP()
 FROM @{{ stage_doc_usage_dashboard }}/documents/ t)
 FILE_FORMAT = (FORMAT_NAME = '{{ format_doc_usage_dashboard }}') ON_ERROR = ABORT_STATEMENT;
 RETURN 'RAW load complete';
END;
$$;
