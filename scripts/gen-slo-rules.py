#!/usr/bin/env python3
"""Generate Prometheus SLO rules and identical Helm assets. Requires PyYAML."""

import argparse
import json
from pathlib import Path
import re

import yaml

ROOT = Path(__file__).resolve().parents[1]
WINDOWS = ("5m", "30m", "1h", "2h", "6h", "1d", "3d", "30d")
BURNS = ((14.4, "1h", "5m", "page"), (6, "6h", "30m", "page"),
         (3, "1d", "2h", "ticket"), (1, "3d", "6h", "ticket"))


def selector(metric, service):
    if not re.fullmatch(r'[a-zA-Z_:][a-zA-Z0-9_:]*(?:\{[^{}]*\})?', metric):
        raise ValueError(f"Expected metric selector, got {metric!r}")
    name, _, matchers = metric.partition("{")
    extra = "," + matchers[:-1] if matchers else ""
    return f'{name}{{job={json.dumps(service)},namespace=~"otterworks-.*|"{extra}}}'


def generate(spec):
    if spec.get("version") != 1 or spec.get("period") != "30d":
        raise ValueError("Expected version 1 and period 30d")
    if not spec.get("services") or not spec.get("runbook_url"):
        raise ValueError("At least one service and a runbook_url are required")
    groups = []
    for service, config in spec["services"].items():
        if not re.fullmatch(r"[a-z][a-z0-9-]*", service):
            raise ValueError(f"Invalid service name: {service}")
        rules = []
        for slo in ("availability", "latency"):
            definition = config[slo]
            objective = definition["objective"]
            if not 0 < objective < 1:
                raise ValueError(f"Invalid objective for {service}/{slo}")
            labels = {"service": service, "slo": slo}
            budget = format(1 - objective, ".10g")
            total = selector(definition["total"], service)
            component = selector(definition["bad" if slo == "availability" else "good"], service)
            for window in WINDOWS:
                denominator = f"sum by (namespace) (rate({total}[{window}]))"
                numerator = f"sum by (namespace) (rate({component}[{window}]))"
                # A counter vector may not have emitted an error series yet.
                fraction = f"(({numerator} or 0 * {denominator}) / {denominator})"
                error = fraction if slo == "availability" else f"(1 - {fraction})"
                error = f"clamp_max(clamp_min({error}, 0), 1) and ({denominator} > 0)"
                rules.extend([
                    {"record": f"slo:error_ratio:rate{window}", "expr": error, "labels": labels},
                    {"record": f"slo:success_ratio:rate{window}",
                     "expr": f'1 - slo:error_ratio:rate{window}{{service="{service}",slo="{slo}"}}', "labels": labels},
                    {"record": f"slo:burn_rate:rate{window}",
                     "expr": f'slo:error_ratio:rate{window}{{service="{service}",slo="{slo}"}} / {budget}', "labels": labels},
                ])
            rules.append({"record": "slo:error_budget_remaining:ratio",
                          "expr": f'1 - slo:burn_rate:rate30d{{service="{service}",slo="{slo}"}}',
                          "labels": labels})
            for burn, long, short, severity in BURNS:
                match = f'{{service="{service}",slo="{slo}"}}'
                alert_labels = {**labels, "severity": severity, "window": long}
                if severity == "page":
                    alert_labels["page"] = "devin"
                rules.append({
                    "alert": "SLOBurnRateHigh",
                    "expr": f"(slo:burn_rate:rate{long}{match} > {burn}) and "
                            f"(slo:burn_rate:rate{short}{match} > {burn})",
                    "labels": alert_labels,
                    "annotations": {
                        "summary": f"{service} {slo} budget burning above {burn}x ({long} and {short})",
                        "description": f"30d objective {objective:.1%}. Both windows must exceed the threshold; check traffic and telemetry before mitigation.",
                        "runbook_url": spec["runbook_url"],
                    },
                })
        groups.append({"name": f"otterworks.slo.{service}", "interval": "30s", "rules": rules})
    return {"groups": groups}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", type=Path, default=ROOT / "observability/slo/slos.yaml")
    args = parser.parse_args()
    rules = generate(yaml.safe_load(args.spec.read_text()))
    output = ROOT / "observability/prometheus/slo_rules.yml"
    output.write_text("# Generated by scripts/gen-slo-rules.py; edit observability/slo/slos.yaml.\n" +
                      yaml.safe_dump(rules, sort_keys=False, width=120))
    files = ROOT / "infrastructure/helm/observability-rules/files"
    files.mkdir(parents=True, exist_ok=True)
    for name in ("slo_rules.yml", "alerts.yml", "recording_rules.yml"):
        (files / name).write_bytes((output.parent / name).read_bytes())
    (files / "slo-overview.json").write_bytes(
        (ROOT / "observability/grafana/dashboards/slo-overview.json").read_bytes())
    print("Generated SLO rules and synchronized observability-rules Helm assets")


if __name__ == "__main__":
    main()
