"""Print the reproducible SQL macro patch for Python's Unicode conversion tables."""
import json
import sys
import unicodedata


def macro():
    upper = {chr(i): chr(i).upper() for i in range(sys.maxunicode + 1)
             if chr(i).upper() != chr(i)}
    digits = [chr(i) for i in range(sys.maxunicode + 1) if chr(i).isdecimal()]
    whitespace = [i for i in range(sys.maxunicode + 1) if chr(i).isspace()]
    digit_source = ''.join(digits).replace("'", "''")
    digit_target = ''.join(str(unicodedata.decimal(c)) for c in digits)
    trim = ' || '.join(f'chr({i})' for i in whitespace)
    return (
        '{# Generated by parity/fixtures/unt8/generate_unicode.py; Unicode ' + unicodedata.unidata_version + '. #}\n'
        '{% macro unt8_integer_prefix(expression) %}\n'
        "regexp_substr(translate(trim({{ expression }}, " + trim + "), '" + digit_source + "', '" + digit_target + "'), '^[+-]?[0-9]+')\n"
        '{% endmacro %}\n'
        '{% macro unt8_decimal_digits(expression) %}\n'
        "translate({{ expression }}, '" + digit_source + "', '" + digit_target + "')\n"
        '{% endmacro %}\n'
        '{% macro unt8_python_upper(expression) %}\n'
        'array_to_string(transform(regexp_substr_all({{ expression }},\'.\',1,1,\'s\'), c -> '
        'coalesce(get(parse_json($$' + json.dumps(upper, ensure_ascii=True, separators=(',', ':')) +
        "$$), c::varchar)::varchar,c::varchar)), '')\n"
        '{% endmacro %}\n'
    )


if __name__ == '__main__':
    print('*** Begin Patch')
    print('*** Add File: /home/ubuntu/repos/otterworks/warehouse/dbt/macros/unt8_python_unicode.sql')
    print('\n'.join('+' + line for line in macro().splitlines()))
    print('*** End Patch')
