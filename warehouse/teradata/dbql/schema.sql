/* <sc-database> DBC </sc-database> */
CREATE DATABASE DBC FROM DBC AS PERM = 100000000;

/* <sc-table> DBC.DBC_QRYLOG </sc-table> */
CREATE MULTISET TABLE DBC.DBC_QRYLOG, NO FALLBACK (
    ProcID INTEGER,
    CollectTimeStamp TIMESTAMP(6),
    QueryID BIGINT NOT NULL,
    UserName VARCHAR(64) NOT CASESPECIFIC,
    DefaultDatabase VARCHAR(64) NOT CASESPECIFIC,
    AppID VARCHAR(64) CASESPECIFIC,
    ClientID VARCHAR(100) CASESPECIFIC,
    StartTime TIMESTAMP(6),
    FirstRespTime TIMESTAMP(6),
    StatementType VARCHAR(20) NOT CASESPECIFIC,
    StatementGroup VARCHAR(20) NOT CASESPECIFIC,
    QueryText VARCHAR(16000) CASESPECIFIC,
    NumResultRows BIGINT,
    AMPCPUTime DECIMAL(14,6),
    TotalIOCount BIGINT,
    ErrorCode INTEGER
) UNIQUE PRIMARY INDEX (QueryID);

/* <sc-table> DBC.DBC_QRYLOGOBJECTS </sc-table> */
CREATE MULTISET TABLE DBC.DBC_QRYLOGOBJECTS, NO FALLBACK (
    QueryID BIGINT,
    ObjectDatabaseName VARCHAR(64) NOT CASESPECIFIC,
    ObjectTableName VARCHAR(64) NOT CASESPECIFIC,
    ObjectType CHAR(1) NOT CASESPECIFIC,
    UsageType VARCHAR(12) NOT CASESPECIFIC
) PRIMARY INDEX (QueryID);

/* <sc-table> DBC.DBC_TABLESV </sc-table> */
CREATE MULTISET TABLE DBC.DBC_TABLESV, NO FALLBACK (
    DatabaseName VARCHAR(64) NOT CASESPECIFIC,
    TableName VARCHAR(64) NOT CASESPECIFIC,
    TableKind CHAR(1) NOT CASESPECIFIC,
    CreateTimeStamp TIMESTAMP(6),
    LastAccessTimeStamp TIMESTAMP(6),
    AccessCount BIGINT
) UNIQUE PRIMARY INDEX (DatabaseName, TableName);

/* <sc-view> DBC.QryLogV </sc-view> */
CREATE VIEW DBC.QryLogV AS LOCKING ROW FOR ACCESS
SELECT * FROM DBC.DBC_QRYLOG;

/* <sc-view> DBC.QryLogObjectsV </sc-view> */
CREATE VIEW DBC.QryLogObjectsV AS LOCKING ROW FOR ACCESS
SELECT * FROM DBC.DBC_QRYLOGOBJECTS;

/* <sc-view> DBC.TablesV </sc-view> */
CREATE VIEW DBC.TablesV AS LOCKING ROW FOR ACCESS
SELECT * FROM DBC.DBC_TABLESV;
