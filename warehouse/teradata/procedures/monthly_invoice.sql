/* <sc-procedure> SFX_BILLING.P_MONTHLY_INVOICE </sc-procedure> */
REPLACE PROCEDURE SFX_BILLING.P_MONTHLY_INVOICE (IN p_day VARCHAR(8), OUT n BIGINT)
BEGIN
DECLARE run_day DATE;
SET run_day=CAST(p_day AS DATE FORMAT 'YYYYMMDD');
DELETE FROM SFX_BILLING.INVOICE_LINE WHERE DESCRIPTION IN ('Monthly subscription', 'Billing adjustment');
INSERT INTO SFX_BILLING.INVOICE_LINE
(INVOICE_LINE_ID, INVOICE_ID, LINE_NO, DESCRIPTION, QUANTITY, UNIT_PRICE, LINE_AMOUNT)
SELECT 300000000000+h.INVOICE_ID, h.INVOICE_ID, 100, 'Monthly subscription', 1, p.MONTHLY_FEE, p.MONTHLY_FEE
FROM SFX_BILLING.INVOICE_HDR h
JOIN SFX_BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID=s.SUBSCRIPTION_ID
JOIN SFX_BILLING.PLAN_CATALOG p ON s.PLAN_CODE=p.PLAN_CODE
WHERE h.INVOICE_DT <= run_day;
INSERT INTO SFX_BILLING.INVOICE_LINE
(INVOICE_LINE_ID, INVOICE_ID, LINE_NO, DESCRIPTION, QUANTITY, UNIT_PRICE, LINE_AMOUNT)
SELECT 400000000000+a.ADJUSTMENT_ID, a.INVOICE_ID, 200, 'Billing adjustment', 1, a.AMOUNT, a.AMOUNT
FROM SFX_BILLING.BILLING_ADJ a
JOIN SFX_BILLING.INVOICE_HDR h ON a.INVOICE_ID=h.INVOICE_ID
JOIN SFX_BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID=s.SUBSCRIPTION_ID
JOIN SFX_BILLING.PLAN_CATALOG p ON s.PLAN_CODE=p.PLAN_CODE
WHERE h.INVOICE_DT <= run_day;
MERGE INTO SFX_BILLING.INVOICE_HDR i
USING (
SELECT h.INVOICE_ID, ZEROIFNULL(SUM(l.LINE_AMOUNT)) AS SUBTOTAL_AMOUNT,
ROUND(ZEROIFNULL(SUM(l.LINE_AMOUNT))*MAX(t.RATE), 2) AS TAX_AMOUNT
FROM SFX_BILLING.INVOICE_HDR h
JOIN SFX_BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID=s.SUBSCRIPTION_ID
JOIN SFX_BILLING.PLAN_CATALOG p ON s.PLAN_CODE=p.PLAN_CODE
JOIN SFX_BILLING.TAX_RATE t ON h.TAX_RATE_ID=t.TAX_RATE_ID
LEFT JOIN SFX_BILLING.INVOICE_LINE l ON h.INVOICE_ID=l.INVOICE_ID
WHERE h.INVOICE_DT <= run_day
GROUP BY h.INVOICE_ID
) x ON i.INVOICE_ID=x.INVOICE_ID
WHEN MATCHED THEN UPDATE SET SUBTOTAL_AMOUNT=x.SUBTOTAL_AMOUNT, TAX_AMOUNT=x.TAX_AMOUNT,
TOTAL_AMOUNT=x.SUBTOTAL_AMOUNT+x.TAX_AMOUNT;
SET n=ACTIVITY_COUNT;
MERGE INTO SFX_BILLING.INVOICE_HDR i
USING (
SELECT INVOICE_ID, SUM(TOTAL_AMOUNT) OVER (PARTITION BY CURRENCY_CD) AS CONTROL_TOTAL
FROM SFX_BILLING.INVOICE_HDR
) c ON i.INVOICE_ID=c.INVOICE_ID
WHEN MATCHED THEN UPDATE SET CURRENCY_CONTROL_TOTAL=c.CONTROL_TOTAL;
END;
