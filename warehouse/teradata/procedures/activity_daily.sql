/* <sc-procedure> SFX_USERS.P_ACTIVITY_DAILY </sc-procedure> */
REPLACE PROCEDURE SFX_USERS.P_ACTIVITY_DAILY (IN p_day VARCHAR(8), OUT n BIGINT)
BEGIN
DECLARE run_day DATE;
SET run_day=CAST(p_day AS DATE FORMAT 'YYYYMMDD');
DELETE FROM SFX_USERS.USER_ACTIVITY_DAILY WHERE ACTIVITY_ID>=10000000000;
INSERT INTO SFX_USERS.USER_ACTIVITY_DAILY (ACTIVITY_ID, USER_ID, ACTIVITY_DT, LOGIN_COUNT, DOCUMENT_COUNT)
SELECT 10000000000+USER_ID, USER_ID, run_day, COUNT(*), 0
FROM SFX_USERS.LOGIN_EVENT WHERE CAST(LOGIN_TS AS DATE)=run_day GROUP BY USER_ID;
SET n=ACTIVITY_COUNT;
END;
