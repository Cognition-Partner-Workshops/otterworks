CREATE DATABASE SFX_AUDIT FROM DBC AS PERM = 1000000000;

CREATE MULTISET TABLE SFX_AUDIT.AUDIT_EVENT, FALLBACK (
    EVENT_ID BIGINT NOT NULL,
    ACTOR_USER_ID BIGINT,
    DOCUMENT_ID BIGINT,
    CUSTOMER_ID BIGINT,
    EVENT_TS TIMESTAMP(0),
    EVENT_TYPE CHAR(12) CHARACTER SET LATIN NOT CASESPECIFIC,
    DETAILS VARCHAR(160) CHARACTER SET UNICODE CASESPECIFIC
) UNIQUE PRIMARY INDEX (EVENT_ID);

CREATE MULTISET TABLE SFX_AUDIT.STG_AUDIT_EVENT, NO FALLBACK (
    EVENT_ID BIGINT,
    ACTOR_USER_ID BIGINT,
    DOCUMENT_ID BIGINT,
