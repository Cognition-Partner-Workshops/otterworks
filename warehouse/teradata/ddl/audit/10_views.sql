/* <sc-view> SFX_AUDIT.V_EVENT_ACTORS </sc-view> */
CREATE VIEW SFX_AUDIT.V_EVENT_ACTORS AS LOCKING ROW FOR ACCESS
SELECT e.EVENT_ID, e.EVENT_TS, e.EVENT_TYPE, u.USER_ID, u.DISPLAY_NAME FROM SFX_AUDIT.AUDIT_EVENT e JOIN SFX_USERS.APP_USER u ON e.ACTOR_USER_ID=u.USER_ID;

/* <sc-view> SFX_AUDIT.V_CUSTOMER_RECON </sc-view> */
CREATE VIEW SFX_AUDIT.V_CUSTOMER_RECON AS LOCKING ROW FOR ACCESS
SELECT CUSTOMER_ID, BUSINESS_DT, SOURCE_COUNT, TARGET_COUNT, DIFFERENCE_COUNT FROM SFX_AUDIT.AUDIT_RECON;
