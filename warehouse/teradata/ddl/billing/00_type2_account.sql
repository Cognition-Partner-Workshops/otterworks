/* <sc-table> SFX_BILLING.CUSTOMER_ACCOUNT_HIST </sc-table> */
CREATE MULTISET TABLE SFX_BILLING.CUSTOMER_ACCOUNT_HIST, NO FALLBACK (
    CUSTOMER_ID BIGINT NOT NULL,
    VALID_FROM_DT DATE NOT NULL,
    VALID_TO_DT DATE NOT NULL,
    STATUS_CD CHAR(12) CHARACTER SET LATIN NOT CASESPECIFIC,
    CURRENCY_CD CHAR(3) CHARACTER SET LATIN NOT CASESPECIFIC
