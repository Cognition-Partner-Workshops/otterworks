/* <sc-view> SFX_BILLING.V_ACCOUNT_INVOICES </sc-view> */
CREATE VIEW SFX_BILLING.V_ACCOUNT_INVOICES AS LOCKING ROW FOR ACCESS
SELECT a.CUSTOMER_ID, a.ACCOUNT_NAME, i.INVOICE_ID, i.INVOICE_DT, i.CURRENCY_CD, i.TOTAL_AMOUNT FROM SFX_BILLING.CUSTOMER_ACCOUNT a JOIN SFX_BILLING.INVOICE_HDR i ON a.CUSTOMER_ID=i.CUSTOMER_ID;

/* <sc-view> SFX_BILLING.V_SUBSCRIPTION_PLANS </sc-view> */
CREATE VIEW SFX_BILLING.V_SUBSCRIPTION_PLANS AS LOCKING ROW FOR ACCESS
SELECT s.SUBSCRIPTION_ID, s.CUSTOMER_ID, p.PLAN_CODE, p.MONTHLY_FEE FROM SFX_BILLING.SUBSCRIPTION s JOIN SFX_BILLING.PLAN_CATALOG p ON s.PLAN_CODE=p.PLAN_CODE;
