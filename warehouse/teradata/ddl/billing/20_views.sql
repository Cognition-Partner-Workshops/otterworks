CREATE VIEW SFX_BILLING.V_INVOICE_BASE AS LOCKING ROW FOR ACCESS
SELECT CUSTOMER_ID, ACCOUNT_NAME, INVOICE_ID, INVOICE_DT, CURRENCY_CD, TOTAL_AMOUNT
FROM SFX_BILLING.V_ACCOUNT_INVOICES;

CREATE VIEW SFX_BILLING.V_INVOICE_REVENUE AS LOCKING ROW FOR ACCESS
SELECT CURRENCY_CD, CAST(CAST(INVOICE_DT AS FORMAT 'YYYY-MM') AS CHAR(7)) AS INVOICE_PERIOD,
COUNT(*) AS INVOICE_COUNT, SUM(TOTAL_AMOUNT) AS TOTAL_AMOUNT
FROM SFX_BILLING.V_INVOICE_BASE
GROUP BY CURRENCY_CD, CAST(CAST(INVOICE_DT AS FORMAT 'YYYY-MM') AS CHAR(7));
