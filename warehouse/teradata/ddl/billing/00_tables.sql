CREATE DATABASE SFX_BILLING FROM DBC AS PERM = 1000000000;

CREATE MULTISET TABLE SFX_BILLING.CUSTOMER_ACCOUNT, NO FALLBACK (
    CUSTOMER_ID BIGINT NOT NULL,
    OWNER_USER_ID BIGINT,
    ACCOUNT_NAME VARCHAR(100) CHARACTER SET UNICODE CASESPECIFIC,
    STATUS_CD CHAR(12) CHARACTER SET LATIN NOT CASESPECIFIC COMPRESS ('ACTIVE', 'PENDING', 'CLOSED'),
    CURRENCY_CD CHAR(3) CHARACTER SET LATIN NOT CASESPECIFIC,
    CREATED_DT DATE FORMAT 'YYYY-MM-DD'
) UNIQUE PRIMARY INDEX (CUSTOMER_ID);

