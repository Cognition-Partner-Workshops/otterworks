/* <sc-view> SFX_DOCUMENTS.V_DOCUMENT_VERSIONS </sc-view> */
CREATE VIEW SFX_DOCUMENTS.V_DOCUMENT_VERSIONS AS LOCKING ROW FOR ACCESS
SELECT d.DOCUMENT_ID, d.OWNER_USER_ID, v.VERSION_ID, v.VERSION_TS, v.FILE_SIZE FROM SFX_DOCUMENTS.DOCUMENT d JOIN SFX_DOCUMENTS.DOC_VERSION v ON d.DOCUMENT_ID=v.DOCUMENT_ID;

/* <sc-view> SFX_DOCUMENTS.V_SEARCH_HISTORY </sc-view> */
CREATE VIEW SFX_DOCUMENTS.V_SEARCH_HISTORY AS LOCKING ROW FOR ACCESS
SELECT DOCUMENT_ID, INDEXED_TS, STATUS_CD, TOKEN_COUNT FROM SFX_DOCUMENTS.SEARCH_INDEX_LOG;
