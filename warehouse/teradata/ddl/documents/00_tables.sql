/* <sc-database> SFX_DOCUMENTS </sc-database> */
CREATE DATABASE SFX_DOCUMENTS FROM DBC AS PERM = 1000000000;

/* <sc-table> SFX_DOCUMENTS.FOLDER </sc-table> */
CREATE MULTISET TABLE SFX_DOCUMENTS.FOLDER, NO FALLBACK (
    FOLDER_ID BIGINT NOT NULL,
    OWNER_USER_ID BIGINT,
    CUSTOMER_ID BIGINT,
    FOLDER_NAME VARCHAR(100) CHARACTER SET UNICODE CASESPECIFIC,
    CREATED_DT DATE FORMAT 'YYYY-MM-DD'
) UNIQUE PRIMARY INDEX (FOLDER_ID);

