/* <sc-database> SFX_USERS </sc-database> */
CREATE DATABASE SFX_USERS FROM DBC AS PERM = 1000000000;

/* <sc-table> SFX_USERS.APP_USER </sc-table> */
CREATE MULTISET TABLE SFX_USERS.APP_USER, NO FALLBACK (
    USER_ID BIGINT NOT NULL,
    DISPLAY_NAME VARCHAR(60) CHARACTER SET UNICODE CASESPECIFIC,
    EMAIL VARCHAR(120) CHARACTER SET UNICODE CASESPECIFIC,
    STATUS_CD CHAR(12) CHARACTER SET LATIN NOT CASESPECIFIC COMPRESS ('ACTIVE', 'PENDING', 'CLOSED'),
    CREATED_DT DATE FORMAT 'YYYY-MM-DD'
) UNIQUE PRIMARY INDEX (USER_ID);

/* <sc-table> SFX_USERS.STG_APP_USER </sc-table> */
CREATE MULTISET TABLE SFX_USERS.STG_APP_USER, NO FALLBACK (
