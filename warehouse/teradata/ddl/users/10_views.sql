/* <sc-view> SFX_USERS.V_TEAM_MEMBERS </sc-view> */
CREATE VIEW SFX_USERS.V_TEAM_MEMBERS AS LOCKING ROW FOR ACCESS
SELECT t.TEAM_ID, t.TEAM_NAME, u.USER_ID, u.DISPLAY_NAME FROM SFX_USERS.TEAM t JOIN SFX_USERS.TEAM_MEMBER m ON t.TEAM_ID=m.TEAM_ID JOIN SFX_USERS.APP_USER u ON m.USER_ID=u.USER_ID;

/* <sc-view> SFX_USERS.V_USER_SETTINGS </sc-view> */
CREATE VIEW SFX_USERS.V_USER_SETTINGS AS LOCKING ROW FOR ACCESS
SELECT u.USER_ID, u.DISPLAY_NAME, p.PREF_NAME, p.PREF_VALUE FROM SFX_USERS.APP_USER u JOIN SFX_USERS.USER_PREF p ON u.USER_ID=p.USER_ID;
