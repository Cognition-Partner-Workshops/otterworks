/* <sc-macro> SFX_USERS.M_TEAM_COUNTS </sc-macro> */
REPLACE MACRO SFX_USERS.M_TEAM_COUNTS (p_day VARCHAR(8)) AS (
SELECT t.TEAM_ID, t.TEAM_NAME, COUNT(m.TEAM_MEMBER_ID) AS MEMBER_COUNT
FROM SFX_USERS.TEAM t LEFT JOIN SFX_USERS.TEAM_MEMBER m ON t.TEAM_ID=m.TEAM_ID
GROUP BY t.TEAM_ID, t.TEAM_NAME;
);
