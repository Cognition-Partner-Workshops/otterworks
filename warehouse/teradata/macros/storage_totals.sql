/* <sc-macro> SFX_DOCUMENTS.M_STORAGE_TOTALS </sc-macro> */
REPLACE MACRO SFX_DOCUMENTS.M_STORAGE_TOTALS (p_start DATE, p_end DATE) AS (
SELECT CUSTOMER_ID, SUM(BYTES_USED) AS BYTES_USED, SUM(OBJECT_COUNT) AS OBJECT_COUNT
FROM SFX_DOCUMENTS.STORAGE_USAGE_DAILY
WHERE USAGE_DT >= :p_start AND USAGE_DT < :p_end
GROUP BY CUSTOMER_ID;
);
