CREATE OR REPLACE VIEW COMPAT.CUSTOMER COMMENT='sfx-d1110 seed compatibility projection'
AS SELECT
    COALESCE(r.CUSTOMER_ACCOUNT_ID, r.CUSTOMER_ID) AS CUSTOMER_ACCOUNT_ID,
    r.CUSTOMER_ID,
    r.OWNER_USER_ID,
    r.ACCOUNT_NUMBER,
    COALESCE(r.LEGAL_NAME, r.ACCOUNT_NAME) AS LEGAL_NAME,
    COALESCE(r.BILLING_COUNTRY, r.COUNTRY_CD) AS BILLING_COUNTRY,
    COALESCE(r.CURRENCY_CODE, r.CURRENCY_CD) AS CURRENCY_CODE,
    r.PAYMENT_TERMS_DAYS,
    COALESCE(r.CREATED_AT, r.CREATED_DT) AS CREATED_AT,
    r.IS_ACTIVE,
    r.ACCOUNT_NAME,
    r.STATUS_CD,
    r.CURRENCY_CD,
    r.CREATED_DT,
    r.COUNTRY_CD,
    r.REGION_CD,
    u.FIRST_NAME AS OWNER_FIRST_NAME,
    u.LAST_NAME AS OWNER_LAST_NAME,
    u.EMAIL AS OWNER_EMAIL,
    u.DISPLAY_NAME AS OWNER_DISPLAY_NAME
FROM RAW_BILLING.CUSTOMER_ACCOUNT r
LEFT JOIN RAW_USERS.APP_USER u ON r.OWNER_USER_ID = u.USER_ID;

