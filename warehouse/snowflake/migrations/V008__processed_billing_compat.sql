ALTER VIEW COMPAT.CUSTOMER_ACCOUNT SET TAG GOVERNANCE.SFX_RUN = 'sfx-d1110';
ALTER VIEW COMPAT.GL_ACCOUNT SET TAG GOVERNANCE.SFX_RUN = 'sfx-d1110';
ALTER VIEW COMPAT.CREDIT_NOTE SET TAG GOVERNANCE.SFX_RUN = 'sfx-d1110';
ALTER VIEW COMPAT.V_INVOICE_REVENUE SET TAG GOVERNANCE.SFX_RUN = 'sfx-d1110';
