CREATE OR REPLACE VIEW COMPAT.INVOICE COMMENT='sfx-d1110 processed billing compatibility'
AS SELECT
    COALESCE(r.INVOICE_HDR_ID, r.INVOICE_ID) AS INVOICE_HDR_ID,
    r.CUSTOMER_ID,
    r.INVOICE_NUMBER,
    COALESCE(r.INVOICE_DATE, r.INVOICE_DT) AS INVOICE_DATE,
    COALESCE(r.DUE_DATE, DATEADD(day, COALESCE(c.PAYMENT_TERMS_DAYS, 30),
        COALESCE(r.INVOICE_DATE, r.INVOICE_DT))) AS DUE_DATE,
    r.SUBTOTAL_AMOUNT,
    r.TAX_AMOUNT,
    r.TOTAL_AMOUNT,
    COALESCE(r.CURRENCY_CODE, r.CURRENCY_CD) AS CURRENCY_CODE,
    r.STATUS,
    r.INVOICE_ID,
    r.SUBSCRIPTION_ID,
    r.INVOICE_DT,
    r.BILL_DT,
    r.PERIOD_START_DT,
    r.CURRENCY_CD,
    r.TAX_RATE_ID,
    r.INVOICE_PERIOD,
    r.PERIOD_KEY,
    r.PRIOR_PERIOD_END_DT,
    r.INVOICE_MONTH,
    r.PERIOD_CLOSED_CD,
    r.CURRENCY_CONTROL_TOTAL
FROM RAW_BILLING.INVOICE_HDR r
LEFT JOIN (
    SELECT CUSTOMER_ID, MAX(PAYMENT_TERMS_DAYS) AS PAYMENT_TERMS_DAYS
    FROM RAW_BILLING.CUSTOMER_ACCOUNT GROUP BY CUSTOMER_ID
) c ON r.CUSTOMER_ID = c.CUSTOMER_ID;

CREATE OR REPLACE VIEW COMPAT.INVOICE_HDR COMMENT='sfx-d1110 processed invoice alias'
AS SELECT * FROM COMPAT.INVOICE;

CREATE OR REPLACE VIEW COMPAT.CUSTOMER_ACCOUNT COMMENT='sfx-d1110 customer account alias'
AS SELECT * FROM COMPAT.ACCOUNT;

CREATE OR REPLACE VIEW COMPAT.GL_ACCOUNT COMMENT='sfx-d1110 chart compatibility'
AS SELECT r.GL_ACCOUNT_ID, COALESCE(r.ACCOUNT_CODE, r.ACCOUNT_NUMBER) AS ACCOUNT_CODE,
    r.ACCOUNT_NAME, r.ACCOUNT_TYPE, r.CURRENCY_CODE, r.NORMAL_BALANCE,
    r.CREATED_AT, r.IS_ACTIVE, r.ACCOUNT_NUMBER
FROM RAW_BILLING.GL_ACCOUNT r;

CREATE OR REPLACE VIEW COMPAT.CREDIT_NOTE COMMENT='sfx-d1110 credit compatibility'
AS SELECT CREDIT_NOTE_ID, COALESCE(INVOICE_ID, INVOICE_HDR_ID) AS INVOICE_ID,
    CUSTOMER_ID, CREDIT_DT, AMOUNT, REASON_CD, CREDIT_NUMBER, REASON_TEXT,
    COALESCE(ISSUE_DATE, CREDIT_DT) AS ISSUE_DATE
FROM RAW_BILLING.CREDIT_NOTE;

CREATE OR REPLACE VIEW COMPAT.V_INVOICE_REVENUE COMMENT='sfx-d1110 revenue compatibility'
AS SELECT RTRIM(i.CURRENCY_CODE) AS CURRENCY_CD,
    TO_CHAR(i.INVOICE_DATE, 'YYYY-MM') AS INVOICE_PERIOD,
    COUNT(*) AS INVOICE_COUNT, SUM(i.TOTAL_AMOUNT) AS TOTAL_AMOUNT
FROM COMPAT.INVOICE i
JOIN COMPAT.ACCOUNT a ON i.CUSTOMER_ID = a.CUSTOMER_ID
GROUP BY RTRIM(i.CURRENCY_CODE), TO_CHAR(i.INVOICE_DATE, 'YYYY-MM');

CREATE OR REPLACE VIEW COMPAT.INVOICE_REVENUE COMMENT='sfx-d1110 revenue alias'
AS SELECT * FROM COMPAT.V_INVOICE_REVENUE;

