CREATE SCHEMA IF NOT EXISTS COMPAT COMMENT='sfx-d1110 consumer compatibility';

CREATE OR REPLACE VIEW COMPAT.CUSTOMER COMMENT='sfx-d1110 compatibility projection'
AS SELECT
    r.CUSTOMER_ACCOUNT_ID,
    r.CUSTOMER_ID,
    r.OWNER_USER_ID,
    r.ACCOUNT_NUMBER,
    r.LEGAL_NAME,
    r.BILLING_COUNTRY,
    r.CURRENCY_CODE,
    r.PAYMENT_TERMS_DAYS,
    r.CREATED_AT,
    r.IS_ACTIVE,
    u.FIRST_NAME AS OWNER_FIRST_NAME,
    u.LAST_NAME AS OWNER_LAST_NAME,
    u.EMAIL AS OWNER_EMAIL
FROM RAW_BILLING.CUSTOMER_ACCOUNT r
LEFT JOIN RAW_USERS.APP_USER u ON r.OWNER_USER_ID = u.USER_ID;

CREATE OR REPLACE VIEW COMPAT.ACCOUNT COMMENT='sfx-d1110 compatibility projection'
AS SELECT
    r.CUSTOMER_ACCOUNT_ID,
    r.CUSTOMER_ID,
    r.OWNER_USER_ID,
    r.ACCOUNT_NUMBER,
    r.LEGAL_NAME,
    r.BILLING_COUNTRY,
    r.CURRENCY_CODE,
    r.PAYMENT_TERMS_DAYS,
    r.CREATED_AT,
    r.IS_ACTIVE
FROM RAW_BILLING.CUSTOMER_ACCOUNT r;

CREATE OR REPLACE VIEW COMPAT.INVOICE COMMENT='sfx-d1110 compatibility projection'
AS SELECT
    r.INVOICE_HDR_ID,
    r.CUSTOMER_ID,
    r.INVOICE_NUMBER,
    r.INVOICE_DATE,
    r.DUE_DATE,
    r.SUBTOTAL_AMOUNT,
    r.TAX_AMOUNT,
    r.TOTAL_AMOUNT,
    r.CURRENCY_CODE,
    r.STATUS
FROM RAW_BILLING.INVOICE_HDR r;

CREATE OR REPLACE VIEW COMPAT.INVOICE_LINE COMMENT='sfx-d1110 compatibility projection'
AS SELECT
    r.INVOICE_LINE_ID,
    r.INVOICE_HDR_ID,
    r.CUSTOMER_ID,
    r.DESCRIPTION,
    r.QUANTITY,
    r.UNIT_PRICE,
    r.LINE_AMOUNT,
    r.TAX_AMOUNT,
    r.CURRENCY_CODE,
    r.SERVICE_DATE
FROM RAW_BILLING.INVOICE_LINE r;

CREATE OR REPLACE VIEW COMPAT.PAYMENT COMMENT='sfx-d1110 compatibility projection'
AS SELECT
    r.PAYMENT_ID,
    r.CUSTOMER_ID,
    r.INVOICE_HDR_ID,
    r.PAYMENT_NUMBER,
    r.PAYMENT_DATE,
    r.AMOUNT,
    r.CURRENCY_CODE,
    r.METHOD,
    r.STATUS,
    r.CREATED_AT
FROM RAW_BILLING.PAYMENT r;

CREATE OR REPLACE VIEW COMPAT.GL_JOURNAL_LINE COMMENT='sfx-d1110 compatibility projection'
AS SELECT
    r.GL_JOURNAL_LINE_ID,
    r.JOURNAL_ID,
    r.GL_ACCOUNT_ID,
    r.SOURCE_BATCH_NUMBER,
    r.DESCRIPTION,
    r.POSTING_DATE,
    r.DEBIT_AMOUNT,
    r.CREDIT_AMOUNT,
    r.CURRENCY_CODE
FROM RAW_BILLING.GL_JOURNAL_LINE r;

CREATE OR REPLACE VIEW COMPAT.GL_ACCOUNT COMMENT='sfx-d1110 compatibility projection'
AS SELECT r.*, r.ACCOUNT_CODE AS ACCOUNT_NUMBER
FROM RAW_BILLING.GL_ACCOUNT r;

CREATE OR REPLACE VIEW COMPAT.CUSTOMER_ACCOUNT COMMENT='sfx-d1110 compatibility alias'
AS SELECT * FROM COMPAT.ACCOUNT;

CREATE OR REPLACE VIEW COMPAT.INVOICE_HDR COMMENT='sfx-d1110 compatibility alias'
AS SELECT * FROM COMPAT.INVOICE;

CREATE OR REPLACE VIEW COMPAT.CREDIT_NOTE COMMENT='sfx-d1110 credit compatibility projection'
AS SELECT CREDIT_NOTE_ID, INVOICE_HDR_ID AS INVOICE_ID, CUSTOMER_ID,
    ISSUE_DATE AS CREDIT_DT, AMOUNT, CAST(NULL AS VARCHAR(12)) AS REASON_CD,
    CREDIT_NUMBER, REASON AS REASON_TEXT, ISSUE_DATE
FROM RAW_BILLING.CREDIT_NOTE;

CREATE OR REPLACE VIEW COMPAT.V_INVOICE_REVENUE COMMENT='sfx-d1110 revenue compatibility projection'
AS SELECT RTRIM(i.CURRENCY_CODE) AS CURRENCY_CD, TO_CHAR(i.INVOICE_DATE, 'YYYY-MM') AS INVOICE_PERIOD,
    COUNT(*) AS INVOICE_COUNT, SUM(i.TOTAL_AMOUNT) AS TOTAL_AMOUNT
FROM COMPAT.INVOICE i
JOIN COMPAT.ACCOUNT a ON i.CUSTOMER_ID = a.CUSTOMER_ID
GROUP BY RTRIM(i.CURRENCY_CODE), TO_CHAR(i.INVOICE_DATE, 'YYYY-MM');

CREATE OR REPLACE VIEW COMPAT.INVOICE_REVENUE COMMENT='sfx-d1110 revenue compatibility alias'
AS SELECT * FROM COMPAT.V_INVOICE_REVENUE;

CREATE OR REPLACE VIEW COMPAT.DAILY_USAGE COMMENT='sfx-d1110 daily usage rollup'
AS SELECT CUSTOMER_ID, USAGE_DATE, CURRENCY_CODE,
    SUM(QUANTITY) AS QUANTITY, SUM(AMOUNT) AS AMOUNT
FROM RAW_BILLING.USAGE_DAILY
GROUP BY CUSTOMER_ID, USAGE_DATE, CURRENCY_CODE;

GRANT USAGE ON SCHEMA COMPAT TO ROLE SFX_D1110_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA COMPAT TO ROLE SFX_D1110_ROLE;
