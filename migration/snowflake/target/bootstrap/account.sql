-- Snowflake objects for one run of the Usage & Billing Warehouse fixture.
-- bootstrap.py fills in the placeholders from the run token; run it as ACCOUNTADMIN.
-- Every statement is safe to re-run: creates are IF NOT EXISTS and settings are re-applied.

-- The two tags live in a small shared database so they outlive any one run's teardown.
CREATE DATABASE IF NOT EXISTS OW_UBW COMMENT = 'Shared tags for Usage & Billing Warehouse runs';
CREATE SCHEMA IF NOT EXISTS OW_UBW.TAGS;
CREATE TAG IF NOT EXISTS OW_UBW.TAGS.RUN COMMENT = 'Run token that created the object';
CREATE TAG IF NOT EXISTS OW_UBW.TAGS.EXPIRES COMMENT = 'Date after which the run may be torn down';

CREATE DATABASE IF NOT EXISTS ${PREFIX} COMMENT = 'Usage & Billing Warehouse, run ${RUN}, expires ${EXPIRES}';
CREATE SCHEMA IF NOT EXISTS ${PREFIX}.RAW COMMENT = 'Service extracts, loaded with PUT and COPY INTO';
CREATE SCHEMA IF NOT EXISTS ${PREFIX}.STAGING COMMENT = 'dbt staging and dimension models';
CREATE SCHEMA IF NOT EXISTS ${PREFIX}.MARTS COMMENT = 'dbt fact and mart models';
CREATE SCHEMA IF NOT EXISTS ${PREFIX}.OPS COMMENT = 'Run log, parity ledger and task history';

CREATE WAREHOUSE IF NOT EXISTS ${PREFIX}_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Usage & Billing Warehouse, run ${RUN}';
ALTER WAREHOUSE ${PREFIX}_WH SET WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE RESOURCE MONITOR IF NOT EXISTS ${PREFIX}_RM
  WITH CREDIT_QUOTA = ${CREDIT_QUOTA} FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 100 PERCENT DO SUSPEND;
ALTER RESOURCE MONITOR ${PREFIX}_RM SET CREDIT_QUOTA = ${CREDIT_QUOTA};
ALTER WAREHOUSE ${PREFIX}_WH SET RESOURCE_MONITOR = ${PREFIX}_RM;

CREATE ROLE IF NOT EXISTS ${PREFIX}_ENGINEER COMMENT = 'Builds and runs everything inside ${PREFIX}';
CREATE ROLE IF NOT EXISTS ${PREFIX}_READER COMMENT = 'Reads ${PREFIX} and watches its warehouse and tasks';

-- ENGINEER creates and runs inside the database and uses the warehouse.
GRANT USAGE, MONITOR, CREATE SCHEMA ON DATABASE ${PREFIX} TO ROLE ${PREFIX}_ENGINEER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE TASK,
  CREATE PROCEDURE, CREATE FUNCTION, CREATE SEQUENCE
  ON SCHEMA ${PREFIX}.RAW TO ROLE ${PREFIX}_ENGINEER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE TASK,
  CREATE PROCEDURE, CREATE FUNCTION, CREATE SEQUENCE
  ON SCHEMA ${PREFIX}.STAGING TO ROLE ${PREFIX}_ENGINEER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE TASK,
  CREATE PROCEDURE, CREATE FUNCTION, CREATE SEQUENCE
  ON SCHEMA ${PREFIX}.MARTS TO ROLE ${PREFIX}_ENGINEER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE TASK,
  CREATE PROCEDURE, CREATE FUNCTION, CREATE SEQUENCE
  ON SCHEMA ${PREFIX}.OPS TO ROLE ${PREFIX}_ENGINEER;
GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE ${PREFIX}_WH TO ROLE ${PREFIX}_ENGINEER;
-- Needed to resume the task graph; it lets the role run tasks it owns and nothing more.
GRANT EXECUTE TASK ON ACCOUNT TO ROLE ${PREFIX}_ENGINEER;

-- READER selects on every schema, monitors the warehouse (which shows its query history)
-- and monitors the tasks (which shows their task history). USAGE on the warehouse is what
-- lets a Snowsight session run those selects at all.
GRANT USAGE ON DATABASE ${PREFIX} TO ROLE ${PREFIX}_READER;
GRANT USAGE ON SCHEMA ${PREFIX}.RAW TO ROLE ${PREFIX}_READER;
GRANT USAGE ON SCHEMA ${PREFIX}.STAGING TO ROLE ${PREFIX}_READER;
GRANT USAGE ON SCHEMA ${PREFIX}.MARTS TO ROLE ${PREFIX}_READER;
GRANT USAGE ON SCHEMA ${PREFIX}.OPS TO ROLE ${PREFIX}_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA ${PREFIX}.RAW TO ROLE ${PREFIX}_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA ${PREFIX}.STAGING TO ROLE ${PREFIX}_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA ${PREFIX}.MARTS TO ROLE ${PREFIX}_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA ${PREFIX}.OPS TO ROLE ${PREFIX}_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA ${PREFIX}.RAW TO ROLE ${PREFIX}_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA ${PREFIX}.STAGING TO ROLE ${PREFIX}_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA ${PREFIX}.MARTS TO ROLE ${PREFIX}_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA ${PREFIX}.OPS TO ROLE ${PREFIX}_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ${PREFIX}.RAW TO ROLE ${PREFIX}_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ${PREFIX}.STAGING TO ROLE ${PREFIX}_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ${PREFIX}.MARTS TO ROLE ${PREFIX}_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ${PREFIX}.OPS TO ROLE ${PREFIX}_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ${PREFIX}.RAW TO ROLE ${PREFIX}_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ${PREFIX}.STAGING TO ROLE ${PREFIX}_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ${PREFIX}.MARTS TO ROLE ${PREFIX}_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ${PREFIX}.OPS TO ROLE ${PREFIX}_READER;
GRANT MONITOR ON ALL TASKS IN SCHEMA ${PREFIX}.OPS TO ROLE ${PREFIX}_READER;
GRANT MONITOR ON FUTURE TASKS IN SCHEMA ${PREFIX}.OPS TO ROLE ${PREFIX}_READER;
GRANT USAGE, MONITOR ON WAREHOUSE ${PREFIX}_WH TO ROLE ${PREFIX}_READER;

CREATE USER IF NOT EXISTS ${PREFIX}_DBT
  TYPE = SERVICE
  DEFAULT_ROLE = ${PREFIX}_ENGINEER DEFAULT_WAREHOUSE = ${PREFIX}_WH
  DEFAULT_NAMESPACE = '${PREFIX}.RAW' DEFAULT_SECONDARY_ROLES = ()
  COMMENT = 'dbt, loader and gate service user, run ${RUN}';
ALTER USER ${PREFIX}_DBT SET RSA_PUBLIC_KEY = '${DBT_PUBLIC_KEY}'
  DEFAULT_ROLE = ${PREFIX}_ENGINEER DEFAULT_WAREHOUSE = ${PREFIX}_WH;
GRANT ROLE ${PREFIX}_ENGINEER TO USER ${PREFIX}_DBT;

-- The password here only applies when the user is first created; bootstrap.py rotates it
-- when UBW_VIEWER_PASSWORD is set and otherwise uses a random one it never prints.
CREATE USER IF NOT EXISTS ${PREFIX}_VIEWER
  TYPE = PERSON PASSWORD = '${VIEWER_PASSWORD}' MUST_CHANGE_PASSWORD = FALSE
  DEFAULT_ROLE = ${PREFIX}_READER DEFAULT_WAREHOUSE = ${PREFIX}_WH
  DEFAULT_SECONDARY_ROLES = ()
  COMMENT = 'Snowsight login for screen recordings, run ${RUN}';
GRANT ROLE ${PREFIX}_READER TO USER ${PREFIX}_VIEWER;

ALTER DATABASE ${PREFIX} SET TAG OW_UBW.TAGS.RUN = '${RUN}', OW_UBW.TAGS.EXPIRES = '${EXPIRES}';
ALTER SCHEMA ${PREFIX}.RAW SET TAG OW_UBW.TAGS.RUN = '${RUN}', OW_UBW.TAGS.EXPIRES = '${EXPIRES}';
ALTER SCHEMA ${PREFIX}.STAGING SET TAG OW_UBW.TAGS.RUN = '${RUN}', OW_UBW.TAGS.EXPIRES = '${EXPIRES}';
ALTER SCHEMA ${PREFIX}.MARTS SET TAG OW_UBW.TAGS.RUN = '${RUN}', OW_UBW.TAGS.EXPIRES = '${EXPIRES}';
ALTER SCHEMA ${PREFIX}.OPS SET TAG OW_UBW.TAGS.RUN = '${RUN}', OW_UBW.TAGS.EXPIRES = '${EXPIRES}';
ALTER WAREHOUSE ${PREFIX}_WH SET TAG OW_UBW.TAGS.RUN = '${RUN}', OW_UBW.TAGS.EXPIRES = '${EXPIRES}';
ALTER ROLE ${PREFIX}_ENGINEER SET TAG OW_UBW.TAGS.RUN = '${RUN}', OW_UBW.TAGS.EXPIRES = '${EXPIRES}';
ALTER ROLE ${PREFIX}_READER SET TAG OW_UBW.TAGS.RUN = '${RUN}', OW_UBW.TAGS.EXPIRES = '${EXPIRES}';
ALTER USER ${PREFIX}_DBT SET TAG OW_UBW.TAGS.RUN = '${RUN}', OW_UBW.TAGS.EXPIRES = '${EXPIRES}';
ALTER USER ${PREFIX}_VIEWER SET TAG OW_UBW.TAGS.RUN = '${RUN}', OW_UBW.TAGS.EXPIRES = '${EXPIRES}';
