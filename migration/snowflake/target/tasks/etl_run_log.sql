CREATE TABLE IF NOT EXISTS ${PREFIX}.OPS.ETL_RUN_LOG (
    RUN_TOKEN VARCHAR,
    BUSINESS_DATE DATE,
    JOB_NAME VARCHAR,
    STEP_NAME VARCHAR,
    STATUS VARCHAR,
    ROW_COUNT NUMBER,
    MESSAGE VARCHAR,
    STARTED_AT TIMESTAMP_NTZ,
    COMPLETED_AT TIMESTAMP_NTZ,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
