CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.RAW_DOCUMENTS.LOAD_DOCUMENTS()
RETURNS VARCHAR
LANGUAGE SQL
AS $$
BEGIN
BEGIN TRANSACTION;
DELETE FROM __RUN_DATABASE__.DOCUMENTS.STG_COLLAB_SESSION;
COPY INTO __RUN_DATABASE__.DOCUMENTS.STG_COLLAB_SESSION
FROM (SELECT CAST(NULLIF($1, '') AS BIGINT), CAST(NULLIF($2, '') AS BIGINT), CAST(NULLIF($3, '') AS BIGINT), CAST(NULLIF($4, '') AS TIMESTAMP_NTZ(0)), CAST(NULLIF($5, '') AS TIMESTAMP_NTZ(0))
      FROM @__RUN_DATABASE__.RAW_DOCUMENTS.DOCUMENTS_LANDING/documents/COLLAB_SESSION/)
FILES = ('${BUSINESS_DATE}.psv')
FILE_FORMAT = (TYPE=CSV FIELD_DELIMITER='|' FIELD_OPTIONALLY_ENCLOSED_BY='"' SKIP_HEADER=0 EMPTY_FIELD_AS_NULL=FALSE NULL_IF=())
FORCE=TRUE ON_ERROR='ABORT_STATEMENT';
COMMIT;
BEGIN TRANSACTION;
DELETE FROM __RUN_DATABASE__.DOCUMENTS.STG_DOCUMENT;
COPY INTO __RUN_DATABASE__.DOCUMENTS.STG_DOCUMENT
FROM (SELECT CAST(NULLIF($1, '') AS BIGINT), CAST(NULLIF($2, '') AS BIGINT), CAST(NULLIF($3, '') AS BIGINT), CAST(NULLIF($4, '') AS BIGINT), COALESCE($5, ''), CAST(NULLIF($6, '') AS DATE), COALESCE($7, ''), COALESCE($8, '')
      FROM @__RUN_DATABASE__.RAW_DOCUMENTS.DOCUMENTS_LANDING/documents/DOCUMENT/)
FILES = ('${BUSINESS_DATE}.psv')
FILE_FORMAT = (TYPE=CSV FIELD_DELIMITER='|' FIELD_OPTIONALLY_ENCLOSED_BY='"' SKIP_HEADER=0 EMPTY_FIELD_AS_NULL=FALSE NULL_IF=())
