FORCE=TRUE ON_ERROR='ABORT_STATEMENT';
COMMIT;
BEGIN TRANSACTION;
DELETE FROM __RUN_DATABASE__.DOCUMENTS.STG_DOC_TAG;
COPY INTO __RUN_DATABASE__.DOCUMENTS.STG_DOC_TAG
FROM (SELECT CAST(NULLIF($1, '') AS BIGINT), CAST(NULLIF($2, '') AS BIGINT), COALESCE($3, ''), CAST(NULLIF($4, '') AS DATE)
      FROM @__RUN_DATABASE__.RAW_DOCUMENTS.DOCUMENTS_LANDING/documents/DOC_TAG/)
FILES = ('${BUSINESS_DATE}.psv')
FILE_FORMAT = (TYPE=CSV FIELD_DELIMITER='|' FIELD_OPTIONALLY_ENCLOSED_BY='"' SKIP_HEADER=0 EMPTY_FIELD_AS_NULL=FALSE NULL_IF=())
FORCE=TRUE ON_ERROR='ABORT_STATEMENT';
COMMIT;
BEGIN TRANSACTION;
DELETE FROM __RUN_DATABASE__.DOCUMENTS.STG_DOC_VERSION;
