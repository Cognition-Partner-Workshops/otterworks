FROM (SELECT CAST(NULLIF($1, '') AS BIGINT), CAST(NULLIF($2, '') AS BIGINT), CAST(NULLIF($3, '') AS INT), CAST(NULLIF($4, '') AS TIMESTAMP_NTZ(0)), CAST(NULLIF($5, '') AS BIGINT), COALESCE($6, '')
      FROM @__RUN_DATABASE__.RAW_DOCUMENTS.DOCUMENTS_LANDING/documents/DOC_VERSION/)
FILES = ('${BUSINESS_DATE}.psv')
FILE_FORMAT = (TYPE=CSV FIELD_DELIMITER='|' FIELD_OPTIONALLY_ENCLOSED_BY='"' SKIP_HEADER=0 EMPTY_FIELD_AS_NULL=FALSE NULL_IF=())
