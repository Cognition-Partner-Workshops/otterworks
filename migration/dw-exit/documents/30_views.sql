CREATE OR REPLACE VIEW __RUN_DATABASE__.COMPAT.SFX_DOCUMENTS__V_DOCUMENT_VERSIONS
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS
SELECT d.DOCUMENT_ID, d.OWNER_USER_ID, v.VERSION_ID, v.VERSION_TS, v.FILE_SIZE
FROM __RUN_DATABASE__.DOCUMENTS.DOCUMENT d
JOIN __RUN_DATABASE__.DOCUMENTS.DOC_VERSION v ON d.DOCUMENT_ID = v.DOCUMENT_ID;

-- warehouse/teradata/ddl/documents/20_views.sql
CREATE OR REPLACE VIEW __RUN_DATABASE__.COMPAT.SFX_DOCUMENTS__V_WORKSPACE_STORAGE
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS
SELECT OWNER_USER_ID, COUNT(*) AS DOCUMENT_COUNT, SUM(FILE_SIZE) AS TOTAL_BYTES
FROM __RUN_DATABASE__.COMPAT.SFX_DOCUMENTS__V_DOCUMENT_VERSIONS
GROUP BY OWNER_USER_ID;
