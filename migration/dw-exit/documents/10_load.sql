-- 01_load_folders.bteq
-- BTEQ committed each request and quit 8 on the first error; an unhandled exception fails the CALL the same way.
CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.OPS."01_LOAD_FOLDERS"()
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
EXECUTE AS CALLER
AS
$$
BEGIN
    DELETE FROM __RUN_DATABASE__.DOCUMENTS.FOLDER;
    INSERT INTO __RUN_DATABASE__.DOCUMENTS.FOLDER SELECT * FROM __RUN_DATABASE__.DOCUMENTS.STG_FOLDER;
    DELETE FROM __RUN_DATABASE__.DOCUMENTS.DOCUMENT;
    INSERT INTO __RUN_DATABASE__.DOCUMENTS.DOCUMENT SELECT * FROM __RUN_DATABASE__.DOCUMENTS.STG_DOCUMENT;
    RETURN 'OK';
END;
$$;

-- 02_current_versions.bteq
-- OPEN OWNER DECISION: the source orders by VERSION_TS only, so equal latest timestamps pick an arbitrary row.
-- The ORDER BY is carried over unchanged; no tie-break is added until the owner names one.
-- BTEQ committed each request and quit 8 on the first error; an unhandled exception fails the CALL the same way.
CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.OPS."02_CURRENT_VERSIONS"()
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
EXECUTE AS CALLER
AS
$$
BEGIN
    DELETE FROM __RUN_DATABASE__.DOCUMENTS.DOC_VERSION;
    INSERT INTO __RUN_DATABASE__.DOCUMENTS.DOC_VERSION
    SELECT VERSION_ID, DOCUMENT_ID, VERSION_NO, VERSION_TS, FILE_SIZE, CONTENT_HASH
    FROM __RUN_DATABASE__.DOCUMENTS.STG_DOC_VERSION
    QUALIFY ROW_NUMBER() OVER (PARTITION BY DOCUMENT_ID ORDER BY VERSION_TS DESC) = 1;
    RETURN 'OK';
END;
$$;

