CREATE OR REPLACE VIEW __RUN_DATABASE__.DOCUMENTS.V_DOCUMENT_VERSIONS AS
SELECT d.DOCUMENT_ID, d.OWNER_USER_ID, v.VERSION_ID, v.VERSION_TS, v.FILE_SIZE
FROM __RUN_DATABASE__.DOCUMENTS.DOCUMENT d
JOIN __RUN_DATABASE__.DOCUMENTS.DOC_VERSION v ON d.DOCUMENT_ID=v.DOCUMENT_ID;

CREATE OR REPLACE VIEW __RUN_DATABASE__.DOCUMENTS.V_WORKSPACE_STORAGE AS
SELECT OWNER_USER_ID, COUNT(*) AS DOCUMENT_COUNT, CAST(SUM(FILE_SIZE) AS NUMBER(38,0)) AS TOTAL_BYTES
FROM __RUN_DATABASE__.DOCUMENTS.V_DOCUMENT_VERSIONS GROUP BY OWNER_USER_ID;

CREATE OR REPLACE VIEW __RUN_DATABASE__.COMPAT.SFX_DOCUMENTS__V_DOCUMENT_VERSIONS AS
SELECT * FROM __RUN_DATABASE__.DOCUMENTS.V_DOCUMENT_VERSIONS;
CREATE OR REPLACE VIEW __RUN_DATABASE__.COMPAT.SFX_DOCUMENTS__V_WORKSPACE_STORAGE AS
SELECT * FROM __RUN_DATABASE__.DOCUMENTS.V_WORKSPACE_STORAGE;
