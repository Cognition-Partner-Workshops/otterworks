CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.OPS.STG_DOCUMENTS__S_M_SFX_STG_DOCUMENT()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
BEGIN
TRUNCATE TABLE __RUN_DATABASE__.DOCUMENTS.STG_DOCUMENT;
INSERT INTO __RUN_DATABASE__.DOCUMENTS.STG_DOCUMENT
-- m_SFX_STG_DOCUMENT: FF_DOCUMENT -> EXP_DOCUMENT -> STG_DOCUMENT (truncate and load).

select
    cast(DOCUMENT_ID as bigint) as DOCUMENT_ID,
    cast(FOLDER_ID as bigint) as FOLDER_ID,
    cast(OWNER_USER_ID as bigint) as OWNER_USER_ID,
    cast(CUSTOMER_ID as bigint) as CUSTOMER_ID,
    cast(left(trim(DOCUMENT_NAME, ' '), 200) as varchar(200)) as DOCUMENT_NAME,
    cast(CREATED_DT as date) as CREATED_DT,
    cast(left(upper(trim(STATUS_CD, ' ')), 200) as varchar(200)) as STATUS_CD,
    cast(left(trim(FILE_TYPE, ' '), 200) as varchar(200)) as FILE_TYPE
from __RUN_DATABASE__.PC_SRC.DOCUMENT;
RETURN 'SUCCEEDED';
END;
$$;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.OPS.CORE_DOCUMENTS__S_M_SFX_DOCUMENT()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
BEGIN
MERGE INTO __RUN_DATABASE__.DOCUMENTS.DOCUMENT t USING (
with owner_status as (
    select USER_ID, STATUS_CD
    from __RUN_DATABASE__.USERS.APP_USER
    qualify row_number() over (partition by USER_ID order by USER_ID) = 1
)
select
    s.DOCUMENT_ID,
    s.FOLDER_ID,
    s.OWNER_USER_ID,
    s.CUSTOMER_ID,
    cast(left(s.DOCUMENT_NAME, 120) as varchar(120)) as DOCUMENT_NAME,
    s.CREATED_DT,
    cast(left(s.STATUS_CD, 12) as varchar(12)) as STATUS_CD,
    cast(left(s.FILE_TYPE, 8) as varchar(8)) as FILE_TYPE
from __RUN_DATABASE__.DOCUMENTS.STG_DOCUMENT s
join owner_status o on o.USER_ID = s.OWNER_USER_ID
where o.STATUS_CD is not null
) s ON t.DOCUMENT_ID = s.DOCUMENT_ID
WHEN MATCHED THEN UPDATE SET FOLDER_ID = s.FOLDER_ID, OWNER_USER_ID = s.OWNER_USER_ID, CUSTOMER_ID = s.CUSTOMER_ID, DOCUMENT_NAME = s.DOCUMENT_NAME, CREATED_DT = s.CREATED_DT, STATUS_CD = s.STATUS_CD, FILE_TYPE = s.FILE_TYPE
WHEN NOT MATCHED THEN INSERT (DOCUMENT_ID, FOLDER_ID, OWNER_USER_ID, CUSTOMER_ID, DOCUMENT_NAME, CREATED_DT, STATUS_CD, FILE_TYPE) VALUES (s.DOCUMENT_ID, s.FOLDER_ID, s.OWNER_USER_ID, s.CUSTOMER_ID, s.DOCUMENT_NAME, s.CREATED_DT, s.STATUS_CD, s.FILE_TYPE);
RETURN 'SUCCEEDED';
END;
$$;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.OPS.CORE_DOCUMENTS__S_M_SFX_DOC_SHARE()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
BEGIN
MERGE INTO __RUN_DATABASE__.DOCUMENTS.DOC_SHARE t USING (
with src as (
    select
        cast(SHARE_ID as bigint) as SHARE_ID,
        cast(DOCUMENT_ID as bigint) as DOCUMENT_ID,
        cast(USER_ID as bigint) as USER_ID,
        upper(trim(ACCESS_LEVEL, ' ')) as ACCESS_LEVEL,
        cast(SHARED_DT as date) as SHARED_DT
    from __RUN_DATABASE__.PC_SRC.DOC_SHARE
),
role_grant as (
    select
        cast(USER_ID as bigint) as USER_ID,
        left(upper(trim(ROLE_CD, ' ')), 12) as ROLE_CD
    from __RUN_DATABASE__.PC_SRC.ROLE_GRANT
    qualify row_number() over (
        partition by USER_ID
        order by case left(upper(trim(ROLE_CD, ' ')), 12)
            when 'ADMIN' then 2 when 'EDITOR' then 1 else 0 end desc
    ) = 1
)
select
    s.SHARE_ID,
    s.DOCUMENT_ID,
    s.USER_ID,
    cast(left(case
        when r.ROLE_CD = 'ADMIN' then 'OWNER'
        when r.ROLE_CD = 'EDITOR' and s.ACCESS_LEVEL = 'VIEW' then 'EDIT'
        else s.ACCESS_LEVEL
    end, 12) as varchar(12)) as ACCESS_LEVEL,
    s.SHARED_DT
from src s
left join role_grant r on r.USER_ID = s.USER_ID
) s ON t.SHARE_ID = s.SHARE_ID
WHEN MATCHED THEN UPDATE SET DOCUMENT_ID = s.DOCUMENT_ID, USER_ID = s.USER_ID, ACCESS_LEVEL = s.ACCESS_LEVEL, SHARED_DT = s.SHARED_DT
WHEN NOT MATCHED THEN INSERT (SHARE_ID, DOCUMENT_ID, USER_ID, ACCESS_LEVEL, SHARED_DT) VALUES (s.SHARE_ID, s.DOCUMENT_ID, s.USER_ID, s.ACCESS_LEVEL, s.SHARED_DT);
RETURN 'SUCCEEDED';
END;
$$;
