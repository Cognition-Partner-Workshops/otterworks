CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.OPS."10_STORAGE_MONTHLY"(p_day DATE)
RETURNS TABLE (CUSTOMER_ID BIGINT, BYTES_USED NUMBER(38,0), OBJECT_COUNT NUMBER(38,0))
LANGUAGE SQL
EXECUTE AS CALLER
AS $$
DECLARE
    res RESULTSET;
BEGIN
    DELETE FROM __RUN_DATABASE__.BILLING.USAGE_DAILY WHERE UPPER(RTRIM(USAGE_TYPE)) = 'STORAGE';
    INSERT INTO __RUN_DATABASE__.BILLING.USAGE_DAILY
        (USAGE_ID, CUSTOMER_ID, SUBSCRIPTION_ID, USAGE_DT, UNITS, USAGE_TYPE)
    SELECT 10000000000 + u.CUSTOMER_ID, u.CUSTOMER_ID, s.SUBSCRIPTION_ID,
        :p_day, u.BYTES_USED, 'STORAGE'
    FROM (
        SELECT CUSTOMER_ID, SUM(BYTES_USED) AS BYTES_USED
        FROM __RUN_DATABASE__.DOCUMENTS.STORAGE_USAGE_DAILY
        WHERE USAGE_DT >= DATE_TRUNC(month, :p_day)
          AND USAGE_DT < DATEADD(month, 1, DATE_TRUNC(month, :p_day))
        GROUP BY CUSTOMER_ID
    ) u JOIN (
        SELECT CUSTOMER_ID, MIN(SUBSCRIPTION_ID) AS SUBSCRIPTION_ID
        FROM __RUN_DATABASE__.BILLING.SUBSCRIPTION GROUP BY CUSTOMER_ID
    ) s ON u.CUSTOMER_ID = s.CUSTOMER_ID;

    DELETE FROM __RUN_DATABASE__.BILLING.INVOICE_LINE WHERE DESCRIPTION = 'Monthly storage';
    INSERT INTO __RUN_DATABASE__.BILLING.INVOICE_LINE
        (INVOICE_LINE_ID, INVOICE_ID, LINE_NO, DESCRIPTION, QUANTITY, UNIT_PRICE, LINE_AMOUNT)
    SELECT 11000000000 + u.CUSTOMER_ID, i.INVOICE_ID, 900, 'Monthly storage', 1,
        ROUND(CAST(u.UNITS AS DECIMAL(20,4)) / 1073741824 * 0.25, 2),
        ROUND(CAST(u.UNITS AS DECIMAL(20,4)) / 1073741824 * 0.25, 2)
    FROM __RUN_DATABASE__.BILLING.USAGE_DAILY u JOIN (
        SELECT CUSTOMER_ID, MIN(INVOICE_ID) AS INVOICE_ID
        FROM __RUN_DATABASE__.BILLING.INVOICE_HDR GROUP BY CUSTOMER_ID
    ) i ON u.CUSTOMER_ID = i.CUSTOMER_ID
    WHERE UPPER(RTRIM(u.USAGE_TYPE)) = 'STORAGE';
    res := (CALL __RUN_DATABASE__.OPS.SFX_DOCUMENTS_M_STORAGE_TOTALS(
        DATE_TRUNC(month, :p_day), DATEADD(month, 1, DATE_TRUNC(month, :p_day))));
    RETURN TABLE(res);
END;
$$;
