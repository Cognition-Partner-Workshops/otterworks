CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.OPS.SFX_DOCUMENTS_M_STORAGE_TOTALS(p_start DATE, p_end DATE)
RETURNS TABLE (CUSTOMER_ID BIGINT, BYTES_USED NUMBER(38,0), OBJECT_COUNT NUMBER(38,0))
LANGUAGE SQL
AS $$
DECLARE
    res RESULTSET;
BEGIN
    res := (SELECT CUSTOMER_ID, SUM(BYTES_USED) AS BYTES_USED, SUM(OBJECT_COUNT) AS OBJECT_COUNT
            FROM __RUN_DATABASE__.DOCUMENTS.STORAGE_USAGE_DAILY
            WHERE USAGE_DT >= :p_start AND USAGE_DT < :p_end
            GROUP BY CUSTOMER_ID);
    RETURN TABLE(res);
END;
$$;
