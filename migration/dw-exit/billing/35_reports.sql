CREATE OR REPLACE VIEW __RUN_DATABASE__.BILLING.GL_TRIAL_BALANCE_OUTPUT AS
SELECT CAST(a.ACCOUNT_NUMBER AS VARCHAR(20)) AS ACCOUNT_NUMBER, a.ACCOUNT_NAME,
COALESCE(SUM(j.DEBIT_AMOUNT), 0) AS DEBIT_AMOUNT,
COALESCE(SUM(j.CREDIT_AMOUNT), 0) AS CREDIT_AMOUNT
FROM __RUN_DATABASE__.BILLING.GL_ACCOUNT a
LEFT JOIN __RUN_DATABASE__.BILLING.GL_JOURNAL_LINE j ON a.GL_ACCOUNT_ID=j.GL_ACCOUNT_ID
GROUP BY a.ACCOUNT_NUMBER, a.ACCOUNT_NAME
UNION ALL
SELECT 'TOTAL', 'All accounts', COALESCE(SUM(DEBIT_AMOUNT), 0), COALESCE(SUM(CREDIT_AMOUNT), 0)
FROM __RUN_DATABASE__.BILLING.GL_JOURNAL_LINE;

CREATE OR REPLACE VIEW __RUN_DATABASE__.BILLING.INVOICE_PERIODS_OUTPUT AS
SELECT INVOICE_ID, INVOICE_DT - 1 AS PRIOR_DT,
MONTH(INVOICE_DT) AS MONTH_NO,
YEAR(PERIOD_START_DT)*10000+MONTH(PERIOD_START_DT)*100+DAY(PERIOD_START_DT) AS PERIOD_KEY,
TO_CHAR(INVOICE_DT, 'YYYY-MM') AS INVOICE_PERIOD,
TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD') AS RUN_DT
FROM __RUN_DATABASE__.BILLING.INVOICE_HDR;

CREATE OR REPLACE VIEW __RUN_DATABASE__.BILLING.PERIOD_CLOSE_OUTPUT AS
SELECT CURRENCY_CD, COUNT(*) AS INVOICE_COUNT, SUM(TOTAL_AMOUNT) AS TOTAL_AMOUNT
FROM __RUN_DATABASE__.BILLING.INVOICE_HDR
WHERE BILL_DT >= DATEADD(month, -1, DATE_TRUNC('MONTH', TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD')))
AND BILL_DT < DATE_TRUNC('MONTH', TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD'))
GROUP BY CURRENCY_CD;
