CREATE OR REPLACE VIEW __RUN_DATABASE__.BILLING.V_ACCOUNT_INVOICES
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS
SELECT
a.CUSTOMER_ID,
a.ACCOUNT_NAME,
i.INVOICE_ID,
i.INVOICE_DT,
i.CURRENCY_CD,
i.TOTAL_AMOUNT FROM
__RUN_DATABASE__.BILLING.CUSTOMER_ACCOUNT a JOIN
__RUN_DATABASE__.BILLING.INVOICE_HDR i ON a.CUSTOMER_ID = i.CUSTOMER_ID;

CREATE OR REPLACE VIEW __RUN_DATABASE__.BILLING.V_SUBSCRIPTION_PLANS
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS
SELECT
s.SUBSCRIPTION_ID,
s.CUSTOMER_ID,
p.PLAN_CODE,
p.MONTHLY_FEE FROM
__RUN_DATABASE__.BILLING.SUBSCRIPTION s JOIN
__RUN_DATABASE__.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE));

CREATE OR REPLACE VIEW __RUN_DATABASE__.BILLING.V_INVOICE_BASE
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS
SELECT
CUSTOMER_ID,
ACCOUNT_NAME,
INVOICE_ID,
INVOICE_DT,
CURRENCY_CD,
TOTAL_AMOUNT
FROM
__RUN_DATABASE__.BILLING.V_ACCOUNT_INVOICES;

CREATE OR REPLACE VIEW __RUN_DATABASE__.BILLING.V_INVOICE_REVENUE
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS
SELECT
CURRENCY_CD,
TO_CHAR(INVOICE_DT, 'YYYY-MM') AS INVOICE_PERIOD,
COUNT(*) AS INVOICE_COUNT,
SUM(TOTAL_AMOUNT) AS TOTAL_AMOUNT
FROM
__RUN_DATABASE__.BILLING.V_INVOICE_BASE
GROUP BY CURRENCY_CD,
TO_CHAR(INVOICE_DT, 'YYYY-MM');
