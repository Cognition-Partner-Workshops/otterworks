CREATE OR REPLACE TABLE __RUN_DATABASE__.BILLING_PROBES.SET_ROWS
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS SELECT DISTINCT ID, VALUE FROM __RUN_DATABASE__.BILLING_PROBES.FEED;
CREATE OR REPLACE VIEW __RUN_DATABASE__.BILLING_PROBES.SET_DUPLICATE_QUARANTINE
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS SELECT ID, VALUE, COUNT(*) AS INPUT_COUNT,
1 AS RETAINED_COUNT, COUNT(*) - 1 AS SUPPRESSED_COUNT
FROM __RUN_DATABASE__.BILLING_PROBES.FEED
GROUP BY ID, VALUE
HAVING COUNT(*) > 1;
CREATE OR REPLACE TABLE __RUN_DATABASE__.BILLING_PROBES.MULTISET_ROWS
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS SELECT * FROM __RUN_DATABASE__.BILLING_PROBES.FEED;
CREATE OR REPLACE TABLE __RUN_DATABASE__.BILLING_PROBES.TRUNCATION
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS SELECT ID, LEFT(VALUE, 3) AS VALUE FROM __RUN_DATABASE__.BILLING_PROBES.FEED;
CREATE OR REPLACE TABLE __RUN_DATABASE__.BILLING_PROBES.QUALIFY_TIES
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
AS SELECT ID, VERSION_ID, VERSION_TS FROM __RUN_DATABASE__.BILLING_PROBES.VERSIONS
QUALIFY ROW_NUMBER() OVER (PARTITION BY ID ORDER BY VERSION_TS DESC, VERSION_ID DESC) = 1;
