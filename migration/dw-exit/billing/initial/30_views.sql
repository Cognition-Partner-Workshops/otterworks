CREATE OR REPLACE VIEW SFX_D1110_AFTER.BILLING.V_ACCOUNT_INVOICES
COMMENT = 'run_token=sfx-d1110 expires=2026-11-24'
AS
SELECT
a.CUSTOMER_ID,
a.ACCOUNT_NAME,
i.INVOICE_ID,
i.INVOICE_DT,
i.CURRENCY_CD,
i.TOTAL_AMOUNT FROM
SFX_D1110_AFTER.BILLING.CUSTOMER_ACCOUNT a JOIN
SFX_D1110_AFTER.BILLING.INVOICE_HDR i ON a.CUSTOMER_ID = i.CUSTOMER_ID;

CREATE OR REPLACE VIEW SFX_D1110_AFTER.BILLING.V_SUBSCRIPTION_PLANS
COMMENT = 'run_token=sfx-d1110 expires=2026-11-24'
AS
SELECT
s.SUBSCRIPTION_ID,
s.CUSTOMER_ID,
p.PLAN_CODE,
p.MONTHLY_FEE FROM
SFX_D1110_AFTER.BILLING.SUBSCRIPTION s JOIN
SFX_D1110_AFTER.BILLING.PLAN_CATALOG p ON RTRIM( s.PLAN_CODE) = RTRIM(p.PLAN_CODE);

CREATE OR REPLACE VIEW SFX_D1110_AFTER.BILLING.V_INVOICE_BASE
COMMENT = 'run_token=sfx-d1110 expires=2026-11-24'
AS
SELECT
CUSTOMER_ID,
ACCOUNT_NAME,
INVOICE_ID,
INVOICE_DT,
CURRENCY_CD,
TOTAL_AMOUNT
FROM
SFX_D1110_AFTER.BILLING.V_ACCOUNT_INVOICES;

CREATE OR REPLACE VIEW SFX_D1110_AFTER.BILLING.V_INVOICE_REVENUE
COMMENT = 'run_token=sfx-d1110 expires=2026-11-24'
AS
SELECT
CURRENCY_CD,
LEFT(TO_CHAR(INVOICE_DT), 7) AS INVOICE_PERIOD,
COUNT(*) AS INVOICE_COUNT,
SUM(TOTAL_AMOUNT) AS TOTAL_AMOUNT
FROM
SFX_D1110_AFTER.BILLING.V_INVOICE_BASE
GROUP BY CURRENCY_CD,
LEFT(TO_CHAR(INVOICE_DT), 7);
