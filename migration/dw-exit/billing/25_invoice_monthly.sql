-- 12_invoice_monthly.bteq: invoice the month, then repost this month's journal lines.
CALL __RUN_DATABASE__.BILLING.P_MONTHLY_INVOICE('${BUSINESS_DATE}');
DELETE FROM __RUN_DATABASE__.BILLING.GL_JOURNAL_LINE
WHERE POSTING_DT >= TO_DATE('${MONTH_START}', 'YYYYMMDD')
AND POSTING_DT < TO_DATE('${MONTH_END}', 'YYYYMMDD');
INSERT INTO __RUN_DATABASE__.BILLING.GL_JOURNAL_LINE
 (JOURNAL_LINE_ID, INVOICE_ID, CREDIT_NOTE_ID, GL_ACCOUNT_ID, POSTING_DT, CURRENCY_CD, DEBIT_AMOUNT, CREDIT_AMOUNT, DESCRIPTION) SELECT
CAST(LEFT('${BUSINESS_DATE}', 6) AS BIGINT)*1000000000000+x.INVOICE_ID*10+x.LINE_NO,
x.INVOICE_ID,
CAST(NULL AS BIGINT),
x.GL_ACCOUNT_ID,
TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD'),
x.CURRENCY_CD,
CASE
WHEN x.SIGNED_AMOUNT >= 0
THEN x.SIGNED_AMOUNT ELSE 0
END,
CASE
WHEN x.SIGNED_AMOUNT < 0
THEN -x.SIGNED_AMOUNT ELSE 0
END,
'Monthly invoice posting'
 FROM (
SELECT
h.INVOICE_ID,
a.LINE_NO,
a.GL_ACCOUNT_ID,
c.CURRENCY_CD,
CASE
WHEN a.GL_ACCOUNT_ID = 1200
THEN h.TOTAL_AMOUNT
WHEN a.GL_ACCOUNT_ID = 4000
THEN -p.MONTHLY_FEE
WHEN a.GL_ACCOUNT_ID = 4100
THEN -(h.SUBTOTAL_AMOUNT-p.MONTHLY_FEE)
 ELSE -h.TAX_AMOUNT
END AS SIGNED_AMOUNT
 FROM
__RUN_DATABASE__.BILLING.INVOICE_HDR h
 JOIN
__RUN_DATABASE__.BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID = s.SUBSCRIPTION_ID
 JOIN
__RUN_DATABASE__.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
 JOIN (
SELECT
MIN(CURRENCY_CD) AS CURRENCY_CD FROM
__RUN_DATABASE__.BILLING.INVOICE_HDR
GROUP BY UPPER(RTRIM(CURRENCY_CD))) c ON UPPER(RTRIM(h.CURRENCY_CD)) = UPPER(RTRIM(c.CURRENCY_CD))
 CROSS JOIN (
SELECT
1 AS LINE_NO,
1200 AS GL_ACCOUNT_ID UNION ALL
SELECT
2,
4000 UNION ALL
SELECT
3,
4100 UNION ALL
SELECT
4,
2200
 ) a WHERE h.INVOICE_DT <= TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD')
 ) x;
INSERT INTO __RUN_DATABASE__.BILLING.GL_JOURNAL_LINE
 (JOURNAL_LINE_ID, INVOICE_ID, CREDIT_NOTE_ID, GL_ACCOUNT_ID, POSTING_DT, CURRENCY_CD, DEBIT_AMOUNT, CREDIT_AMOUNT, DESCRIPTION) SELECT
CAST(LEFT('${BUSINESS_DATE}', 6) AS BIGINT)*1000000000000+500000000000+x.CREDIT_NOTE_ID*10+x.LINE_NO,
x.INVOICE_ID,
x.CREDIT_NOTE_ID,
x.GL_ACCOUNT_ID,
TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD'),
x.CURRENCY_CD,
CASE
WHEN x.SIGNED_AMOUNT >= 0
THEN x.SIGNED_AMOUNT ELSE 0
END,
CASE
WHEN x.SIGNED_AMOUNT < 0
THEN -x.SIGNED_AMOUNT ELSE 0
END,
'Credit note reversal'
 FROM (
SELECT
h.INVOICE_ID,
cr.CREDIT_NOTE_ID,
a.LINE_NO,
a.GL_ACCOUNT_ID,
c.CURRENCY_CD,
CASE
WHEN a.GL_ACCOUNT_ID = 1200
THEN -cr.AMOUNT
WHEN a.GL_ACCOUNT_ID = 4100
THEN ROUND(cr.AMOUNT/(1+t.RATE), 2)
 ELSE cr.AMOUNT- ROUND(cr.AMOUNT/(1+t.RATE), 2)
END AS SIGNED_AMOUNT
 FROM
__RUN_DATABASE__.BILLING.CREDIT_NOTE cr
 JOIN
__RUN_DATABASE__.BILLING.INVOICE_HDR h ON cr.INVOICE_ID = h.INVOICE_ID
 JOIN
__RUN_DATABASE__.BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID = s.SUBSCRIPTION_ID
 JOIN
__RUN_DATABASE__.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
 JOIN
__RUN_DATABASE__.BILLING.TAX_RATE t ON h.TAX_RATE_ID = t.TAX_RATE_ID
 JOIN (
SELECT
MIN(CURRENCY_CD) AS CURRENCY_CD FROM
__RUN_DATABASE__.BILLING.INVOICE_HDR
GROUP BY UPPER(RTRIM(CURRENCY_CD))) c ON UPPER(RTRIM(h.CURRENCY_CD)) = UPPER(RTRIM(c.CURRENCY_CD))
 CROSS JOIN (
SELECT
1 AS LINE_NO,
1200 AS GL_ACCOUNT_ID UNION ALL
SELECT
2,
4100 UNION ALL
SELECT
3,
2200
 ) a WHERE h.INVOICE_DT <= TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD') AND cr.CREDIT_DT <= TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD')
 ) x;
