-- Billing-boundary portion of documents/10_storage_monthly.bteq.
DELETE FROM SFX_D1110_AFTER.BILLING.USAGE_DAILY WHERE UPPER(RTRIM(USAGE_TYPE))='STORAGE';
INSERT INTO SFX_D1110_AFTER.BILLING.USAGE_DAILY
    (USAGE_ID, CUSTOMER_ID, SUBSCRIPTION_ID, USAGE_DT, UNITS, USAGE_TYPE)
SELECT 10000000000+u.CUSTOMER_ID, u.CUSTOMER_ID, s.SUBSCRIPTION_ID,
    TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD'), u.BYTES_USED, RPAD('STORAGE', 12)
FROM (
    SELECT CUSTOMER_ID, SUM(BYTES_USED) AS BYTES_USED
    FROM SFX_D1110_AFTER.BILLING.STORAGE_USAGE_INPUT
    WHERE USAGE_DT >= DATE_TRUNC(month, TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD'))
      AND USAGE_DT < DATEADD(month, 1, DATE_TRUNC(month, TO_DATE('${BUSINESS_DATE}', 'YYYYMMDD')))
    GROUP BY CUSTOMER_ID
) u JOIN (
    SELECT CUSTOMER_ID, MIN(SUBSCRIPTION_ID) AS SUBSCRIPTION_ID
    FROM SFX_D1110_AFTER.BILLING.SUBSCRIPTION GROUP BY CUSTOMER_ID
) s ON u.CUSTOMER_ID=s.CUSTOMER_ID;

DELETE FROM SFX_D1110_AFTER.BILLING.INVOICE_LINE WHERE DESCRIPTION='Monthly storage';
INSERT INTO SFX_D1110_AFTER.BILLING.INVOICE_LINE
    (INVOICE_LINE_ID, INVOICE_ID, LINE_NO, DESCRIPTION, QUANTITY, UNIT_PRICE, LINE_AMOUNT)
SELECT 11000000000+u.CUSTOMER_ID, i.INVOICE_ID, 900, 'Monthly storage', 1,
    ROUND(CAST(u.UNITS AS DECIMAL(20,4))/1073741824*0.25, 2),
    ROUND(CAST(u.UNITS AS DECIMAL(20,4))/1073741824*0.25, 2)
FROM SFX_D1110_AFTER.BILLING.USAGE_DAILY u JOIN (
    SELECT CUSTOMER_ID, MIN(INVOICE_ID) AS INVOICE_ID
    FROM SFX_D1110_AFTER.BILLING.INVOICE_HDR GROUP BY CUSTOMER_ID
) i ON u.CUSTOMER_ID=i.CUSTOMER_ID WHERE UPPER(RTRIM(u.USAGE_TYPE))='STORAGE';
