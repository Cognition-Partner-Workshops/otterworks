CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.BILLING.M_SUBSCRIPTION_PLANS (P_DAY VARCHAR(8))
RETURNS TABLE (
)
LANGUAGE SQL
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
EXECUTE AS CALLER
AS
$$
BEGIN
LET res RESULTSET :=
(
SELECT
s.SUBSCRIPTION_ID,
s.CUSTOMER_ID,
s.PLAN_CODE,
p.MONTHLY_FEE
 FROM
__RUN_DATABASE__.BILLING.SUBSCRIPTION s
 JOIN
__RUN_DATABASE__.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
);
RETURN TABLE(res);
END;
$$;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.BILLING.M_CURRENCY_TOTALS (P_DAY VARCHAR(8))
RETURNS TABLE (
)
LANGUAGE SQL
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
EXECUTE AS CALLER
AS
$$
BEGIN
LET res RESULTSET :=
(
SELECT
MIN(RTRIM(CURRENCY_CD)) AS CURRENCY_CD,
COUNT(*) AS INVOICE_COUNT,
SUM(TOTAL_AMOUNT) AS TOTAL_AMOUNT
 FROM
__RUN_DATABASE__.BILLING.INVOICE_HDR
 GROUP BY UPPER(RTRIM(CURRENCY_CD))
);
RETURN TABLE(res);
END;
$$;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.BILLING.P_MONTHLY_INVOICE (P_DAY VARCHAR(8))
RETURNS BIGINT
LANGUAGE SQL
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
EXECUTE AS CALLER
AS
$$
DECLARE
run_day DATE;
n BIGINT;
BEGIN

run_day := TO_DATE(p_day, 'YYYYMMDD');
DELETE FROM
__RUN_DATABASE__.BILLING.INVOICE_LINE
WHERE
RTRIM(DESCRIPTION) IN ('Monthly subscription', 'Billing adjustment');
INSERT INTO __RUN_DATABASE__.BILLING.INVOICE_LINE
 (INVOICE_LINE_ID, INVOICE_ID, LINE_NO, DESCRIPTION, QUANTITY, UNIT_PRICE, LINE_AMOUNT) SELECT
300000000000+h.INVOICE_ID,
h.INVOICE_ID,
100,
'Monthly subscription',
1,
p.MONTHLY_FEE,
p.MONTHLY_FEE
 FROM
__RUN_DATABASE__.BILLING.INVOICE_HDR h
 JOIN
__RUN_DATABASE__.BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID = s.SUBSCRIPTION_ID
 JOIN
__RUN_DATABASE__.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
 WHERE h.INVOICE_DT <= :run_day;
INSERT INTO __RUN_DATABASE__.BILLING.INVOICE_LINE
 (INVOICE_LINE_ID, INVOICE_ID, LINE_NO, DESCRIPTION, QUANTITY, UNIT_PRICE, LINE_AMOUNT) SELECT
400000000000+a.ADJUSTMENT_ID,
a.INVOICE_ID,
200,
'Billing adjustment',
1,
a.AMOUNT,
a.AMOUNT
 FROM
__RUN_DATABASE__.BILLING.BILLING_ADJ a
 JOIN
__RUN_DATABASE__.BILLING.INVOICE_HDR h ON a.INVOICE_ID = h.INVOICE_ID
 JOIN
__RUN_DATABASE__.BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID = s.SUBSCRIPTION_ID
 JOIN
__RUN_DATABASE__.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
 WHERE h.INVOICE_DT <= :run_day;
 MERGE INTO __RUN_DATABASE__.BILLING.INVOICE_HDR i
 USING (
SELECT
h.INVOICE_ID,
ZEROIFNULL(SUM(l.LINE_AMOUNT)) AS SUBTOTAL_AMOUNT,
ROUND(ZEROIFNULL(SUM(l.LINE_AMOUNT))* MAX(t.RATE), 2) AS TAX_AMOUNT
 FROM
__RUN_DATABASE__.BILLING.INVOICE_HDR h
 JOIN
__RUN_DATABASE__.BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID = s.SUBSCRIPTION_ID
 JOIN
__RUN_DATABASE__.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
 JOIN
__RUN_DATABASE__.BILLING.TAX_RATE t ON h.TAX_RATE_ID = t.TAX_RATE_ID
 LEFT JOIN
__RUN_DATABASE__.BILLING.INVOICE_LINE l ON h.INVOICE_ID = l.INVOICE_ID
 WHERE h.INVOICE_DT <= :run_day
 GROUP BY h.INVOICE_ID
 ) x ON i.INVOICE_ID = x.INVOICE_ID
 WHEN MATCHED THEN UPDATE SET SUBTOTAL_AMOUNT=x.SUBTOTAL_AMOUNT, TAX_AMOUNT=x.TAX_AMOUNT,
 TOTAL_AMOUNT=x.SUBTOTAL_AMOUNT+x.TAX_AMOUNT;
n := SQLROWCOUNT;
 MERGE INTO __RUN_DATABASE__.BILLING.INVOICE_HDR i
 USING (
SELECT
INVOICE_ID,
SUM(TOTAL_AMOUNT) OVER (PARTITION BY UPPER(RTRIM(CURRENCY_CD))) AS CONTROL_TOTAL
 FROM
__RUN_DATABASE__.BILLING.INVOICE_HDR
 ) c ON i.INVOICE_ID = c.INVOICE_ID
 WHEN MATCHED THEN UPDATE SET CURRENCY_CONTROL_TOTAL=c.CONTROL_TOTAL;
RETURN n;
END;
$$;
