CREATE OR REPLACE PROCEDURE SFX_D1110_AFTER.BILLING.M_SUBSCRIPTION_PLANS (P_DAY VARCHAR(8))
RETURNS TABLE (
)
LANGUAGE SQL
COMMENT = 'run_token=sfx-d1110 expires=2026-11-24'
EXECUTE AS CALLER
AS
$$
BEGIN
LET res RESULTSET :=
(
SELECT
s.SUBSCRIPTION_ID,
s.CUSTOMER_ID,
s.PLAN_CODE,
p.MONTHLY_FEE
 FROM
SFX_D1110_AFTER.BILLING.SUBSCRIPTION s
 JOIN
SFX_D1110_AFTER.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
);
RETURN TABLE(res);
END;
$$;

CREATE OR REPLACE PROCEDURE SFX_D1110_AFTER.BILLING.M_CURRENCY_TOTALS (P_DAY VARCHAR(8))
RETURNS TABLE (
)
LANGUAGE SQL
COMMENT = 'run_token=sfx-d1110 expires=2026-11-24'
EXECUTE AS CALLER
AS
$$
BEGIN
LET res RESULTSET :=
(
SELECT
MIN(RTRIM(CURRENCY_CD)) AS CURRENCY_CD,
COUNT(*) AS INVOICE_COUNT,
SUM(TOTAL_AMOUNT) AS TOTAL_AMOUNT
 FROM
SFX_D1110_AFTER.BILLING.INVOICE_HDR
 GROUP BY UPPER(RTRIM(CURRENCY_CD))
);
RETURN TABLE(res);
END;
$$;

CREATE OR REPLACE PROCEDURE SFX_D1110_AFTER.BILLING.P_MONTHLY_INVOICE (P_DAY VARCHAR(8))
RETURNS BIGINT
LANGUAGE SQL
COMMENT = 'run_token=sfx-d1110 expires=2026-11-24'
EXECUTE AS CALLER
AS
$$
DECLARE
run_day DATE;
n BIGINT;
BEGIN

run_day := TO_DATE(p_day, 'YYYYMMDD');
DELETE FROM
SFX_D1110_AFTER.BILLING.GL_JOURNAL_LINE;
DELETE FROM
SFX_D1110_AFTER.BILLING.INVOICE_LINE
WHERE
RTRIM(DESCRIPTION) IN (RTRIM('Monthly subscription'), RTRIM('Billing adjustment'));
INSERT INTO SFX_D1110_AFTER.BILLING.INVOICE_LINE
 (INVOICE_LINE_ID, INVOICE_ID, LINE_NO, DESCRIPTION, QUANTITY, UNIT_PRICE, LINE_AMOUNT) SELECT
300000000000+h.INVOICE_ID,
h.INVOICE_ID,
100,
'Monthly subscription',
1,
p.MONTHLY_FEE,
p.MONTHLY_FEE
 FROM
SFX_D1110_AFTER.BILLING.INVOICE_HDR h
 JOIN
SFX_D1110_AFTER.BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID = s.SUBSCRIPTION_ID
 JOIN
SFX_D1110_AFTER.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
 WHERE h.INVOICE_DT <= :run_day;
INSERT INTO SFX_D1110_AFTER.BILLING.INVOICE_LINE
 (INVOICE_LINE_ID, INVOICE_ID, LINE_NO, DESCRIPTION, QUANTITY, UNIT_PRICE, LINE_AMOUNT) SELECT
400000000000+a.ADJUSTMENT_ID,
a.INVOICE_ID,
200,
'Billing adjustment',
1,
a.AMOUNT,
a.AMOUNT
 FROM
SFX_D1110_AFTER.BILLING.BILLING_ADJ a
 JOIN
SFX_D1110_AFTER.BILLING.INVOICE_HDR h ON a.INVOICE_ID = h.INVOICE_ID
 JOIN
SFX_D1110_AFTER.BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID = s.SUBSCRIPTION_ID
 JOIN
SFX_D1110_AFTER.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
 WHERE h.INVOICE_DT <= :run_day;
 MERGE INTO SFX_D1110_AFTER.BILLING.INVOICE_HDR i
 USING (
SELECT
h.INVOICE_ID,
ZEROIFNULL(SUM(l.LINE_AMOUNT)) AS SUBTOTAL_AMOUNT,
ROUND(ZEROIFNULL(SUM(l.LINE_AMOUNT))* MAX(t.RATE), 2) AS TAX_AMOUNT
 FROM
SFX_D1110_AFTER.BILLING.INVOICE_HDR h
 JOIN
SFX_D1110_AFTER.BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID = s.SUBSCRIPTION_ID
 JOIN
SFX_D1110_AFTER.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
 JOIN
SFX_D1110_AFTER.BILLING.TAX_RATE t ON h.TAX_RATE_ID = t.TAX_RATE_ID
 LEFT JOIN
SFX_D1110_AFTER.BILLING.INVOICE_LINE l ON h.INVOICE_ID = l.INVOICE_ID
 WHERE h.INVOICE_DT <= :run_day
 GROUP BY h.INVOICE_ID
 ) x ON i.INVOICE_ID = x.INVOICE_ID
 WHEN MATCHED THEN UPDATE SET SUBTOTAL_AMOUNT=x.SUBTOTAL_AMOUNT, TAX_AMOUNT=x.TAX_AMOUNT,
 TOTAL_AMOUNT=x.SUBTOTAL_AMOUNT+x.TAX_AMOUNT;
n := SQLROWCOUNT;
 MERGE INTO SFX_D1110_AFTER.BILLING.INVOICE_HDR i
 USING (
SELECT
INVOICE_ID,
SUM(TOTAL_AMOUNT) OVER (PARTITION BY UPPER(RTRIM(CURRENCY_CD))) AS CONTROL_TOTAL
 FROM
SFX_D1110_AFTER.BILLING.INVOICE_HDR
 ) c ON i.INVOICE_ID = c.INVOICE_ID
 WHEN MATCHED THEN UPDATE SET CURRENCY_CONTROL_TOTAL=c.CONTROL_TOTAL;
INSERT INTO SFX_D1110_AFTER.BILLING.GL_JOURNAL_LINE
 (JOURNAL_LINE_ID, INVOICE_ID, CREDIT_NOTE_ID, GL_ACCOUNT_ID, POSTING_DT, CURRENCY_CD, DEBIT_AMOUNT, CREDIT_AMOUNT, DESCRIPTION) SELECT
x.INVOICE_ID*10+x.LINE_NO,
x.INVOICE_ID,
CAST(NULL AS BIGINT),
x.GL_ACCOUNT_ID,
:run_day,
x.CURRENCY_CD,
CASE
WHEN x.SIGNED_AMOUNT >= 0
THEN x.SIGNED_AMOUNT ELSE 0
END,
CASE
WHEN x.SIGNED_AMOUNT < 0
THEN -x.SIGNED_AMOUNT ELSE 0
END,
'Monthly invoice posting'
 FROM (
SELECT
h.INVOICE_ID,
a.LINE_NO,
a.GL_ACCOUNT_ID,
c.CURRENCY_CD,
CASE
WHEN a.GL_ACCOUNT_ID = 1200
THEN h.TOTAL_AMOUNT
WHEN a.GL_ACCOUNT_ID = 4000
THEN -p.MONTHLY_FEE
WHEN a.GL_ACCOUNT_ID = 4100
THEN -(h.SUBTOTAL_AMOUNT-p.MONTHLY_FEE)
 ELSE -h.TAX_AMOUNT
END AS SIGNED_AMOUNT
 FROM
SFX_D1110_AFTER.BILLING.INVOICE_HDR h
 JOIN
SFX_D1110_AFTER.BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID = s.SUBSCRIPTION_ID
 JOIN
SFX_D1110_AFTER.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
 JOIN (
SELECT
MIN(RTRIM(CURRENCY_CD)) AS CURRENCY_CD FROM
SFX_D1110_AFTER.BILLING.INVOICE_HDR
GROUP BY UPPER(RTRIM(CURRENCY_CD))) c ON UPPER(RTRIM(h.CURRENCY_CD)) = UPPER(RTRIM(c.CURRENCY_CD))
 CROSS JOIN (
SELECT
1 AS LINE_NO,
1200 AS GL_ACCOUNT_ID UNION ALL
SELECT
2,
4000 UNION ALL
SELECT
3,
4100 UNION ALL
SELECT
4,
2200
 ) a WHERE h.INVOICE_DT <= :run_day
 ) x;
INSERT INTO SFX_D1110_AFTER.BILLING.GL_JOURNAL_LINE
 (JOURNAL_LINE_ID, INVOICE_ID, CREDIT_NOTE_ID, GL_ACCOUNT_ID, POSTING_DT, CURRENCY_CD, DEBIT_AMOUNT, CREDIT_AMOUNT, DESCRIPTION) SELECT
1000000000000+x.CREDIT_NOTE_ID*10+x.LINE_NO,
x.INVOICE_ID,
x.CREDIT_NOTE_ID,
x.GL_ACCOUNT_ID,
:run_day,
x.CURRENCY_CD,
CASE
WHEN x.SIGNED_AMOUNT >= 0
THEN x.SIGNED_AMOUNT ELSE 0
END,
CASE
WHEN x.SIGNED_AMOUNT < 0
THEN -x.SIGNED_AMOUNT ELSE 0
END,
'Credit note reversal'
 FROM (
SELECT
h.INVOICE_ID,
cr.CREDIT_NOTE_ID,
a.LINE_NO,
a.GL_ACCOUNT_ID,
c.CURRENCY_CD,
CASE
WHEN a.GL_ACCOUNT_ID = 1200
THEN -cr.AMOUNT
WHEN a.GL_ACCOUNT_ID = 4100
THEN ROUND(cr.AMOUNT/(1+t.RATE), 2)
 ELSE cr.AMOUNT- ROUND(cr.AMOUNT/(1+t.RATE), 2)
END AS SIGNED_AMOUNT
 FROM
SFX_D1110_AFTER.BILLING.CREDIT_NOTE cr
 JOIN
SFX_D1110_AFTER.BILLING.INVOICE_HDR h ON cr.INVOICE_ID = h.INVOICE_ID
 JOIN
SFX_D1110_AFTER.BILLING.SUBSCRIPTION s ON h.SUBSCRIPTION_ID = s.SUBSCRIPTION_ID
 JOIN
SFX_D1110_AFTER.BILLING.PLAN_CATALOG p ON UPPER(RTRIM(s.PLAN_CODE)) = UPPER(RTRIM(p.PLAN_CODE))
 JOIN
SFX_D1110_AFTER.BILLING.TAX_RATE t ON h.TAX_RATE_ID = t.TAX_RATE_ID
 JOIN (
SELECT
MIN(RTRIM(CURRENCY_CD)) AS CURRENCY_CD FROM
SFX_D1110_AFTER.BILLING.INVOICE_HDR
GROUP BY UPPER(RTRIM(CURRENCY_CD))) c ON UPPER(RTRIM(h.CURRENCY_CD)) = UPPER(RTRIM(c.CURRENCY_CD))
 CROSS JOIN (
SELECT
1 AS LINE_NO,
1200 AS GL_ACCOUNT_ID UNION ALL
SELECT
2,
4100 UNION ALL
SELECT
3,
2200
 ) a WHERE h.INVOICE_DT <= :run_day AND cr.CREDIT_DT <= :run_day
 ) x;
RETURN n;
END;
$$;
