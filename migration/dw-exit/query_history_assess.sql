SELECT PARSE_JSON(QUERY_TAG):step::VARCHAR AS STEP,
       EXECUTION_STATUS,
       COUNT(*) AS QUERY_COUNT
FROM TABLE(SFX_D1110_AFTER.INFORMATION_SCHEMA.QUERY_HISTORY(
    END_TIME_RANGE_START => DATEADD('day', -1, CURRENT_TIMESTAMP()),
    RESULT_LIMIT => 10000))
WHERE QUERY_TAG LIKE '%"act":"assess"%'
  AND PARSE_JSON(QUERY_TAG):run::VARCHAR = 'sfx-d1110'
GROUP BY STEP, EXECUTION_STATUS
ORDER BY STEP, EXECUTION_STATUS;
