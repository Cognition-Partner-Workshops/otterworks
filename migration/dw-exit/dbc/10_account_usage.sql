CREATE OR REPLACE VIEW COMPAT.DBC_QRYLOG AS
SELECT CAST(NULL AS INTEGER) AS ProcID, END_TIME AS CollectTimeStamp,
 QUERY_ID AS QueryID, USER_NAME AS UserName, DATABASE_NAME AS DefaultDatabase,
 QUERY_TAG AS AppID, CAST(NULL AS VARCHAR) AS ClientID,
 START_TIME AS StartTime, END_TIME AS FirstRespTime,
 QUERY_TYPE AS StatementType, QUERY_TYPE AS StatementGroup, QUERY_TEXT AS QueryText,
 ROWS_PRODUCED AS NumResultRows, CAST(NULL AS DECIMAL(14,6)) AS AMPCPUTime,
 CAST(NULL AS BIGINT) AS TotalIOCount, COALESCE(TRY_CAST(ERROR_CODE AS INTEGER), 0) AS ErrorCode
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY;

CREATE OR REPLACE VIEW COMPAT.DBC_QRYLOGOBJECTS AS
SELECT h.QUERY_ID AS QueryID,
 SPLIT_PART(f.value:objectName::VARCHAR, '.', 2) AS ObjectDatabaseName,
 SPLIT_PART(f.value:objectName::VARCHAR, '.', 3) AS ObjectTableName,
 CASE WHEN f.value:objectDomain::VARCHAR = 'View' THEN 'V' ELSE 'T' END AS ObjectType,
 'READ' AS UsageType
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY h,
 LATERAL FLATTEN(INPUT => h.DIRECT_OBJECTS_ACCESSED) f
UNION ALL
SELECT h.QUERY_ID AS QueryID,
 SPLIT_PART(f.value:objectName::VARCHAR, '.', 2) AS ObjectDatabaseName,
 SPLIT_PART(f.value:objectName::VARCHAR, '.', 3) AS ObjectTableName,
 CASE WHEN f.value:objectDomain::VARCHAR = 'View' THEN 'V' ELSE 'T' END AS ObjectType,
 'WRITE' AS UsageType
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY h,
 LATERAL FLATTEN(INPUT => h.OBJECTS_MODIFIED) f;

CREATE OR REPLACE VIEW COMPAT.DBC_TABLESV AS
WITH accesses AS (
 SELECT ObjectDatabaseName, ObjectTableName, COUNT(*) AS n, MAX(q.StartTime) AS last_access
 FROM COMPAT.DBC_QRYLOGOBJECTS o JOIN COMPAT.DBC_QRYLOG q ON o.QueryID=q.QueryID
 GROUP BY ObjectDatabaseName, ObjectTableName
)
SELECT t.TABLE_SCHEMA AS DatabaseName, t.TABLE_NAME AS TableName,
 CASE WHEN t.TABLE_TYPE='VIEW' THEN 'V' ELSE 'T' END AS TableKind,
 t.CREATED AS CreateTimeStamp, a.last_access AS LastAccessTimeStamp,
 COALESCE(a.n, 0) AS AccessCount
FROM SNOWFLAKE.ACCOUNT_USAGE.TABLES t LEFT JOIN accesses a
 ON t.TABLE_SCHEMA=a.ObjectDatabaseName AND t.TABLE_NAME=a.ObjectTableName
WHERE t.DELETED IS NULL;

CREATE OR REPLACE VIEW COMPAT.QRYLOGV AS SELECT * FROM COMPAT.DBC_QRYLOG;
CREATE OR REPLACE VIEW COMPAT.QRYLOGOBJECTSV AS SELECT * FROM COMPAT.DBC_QRYLOGOBJECTS;
CREATE OR REPLACE VIEW COMPAT.TABLESV AS SELECT * FROM COMPAT.DBC_TABLESV;
