CREATE OR REPLACE VIEW __RUN_DATABASE__.AUDIT.V_EVENT_ACTORS AS 
SELECT e.EVENT_ID, e.EVENT_TS, e.EVENT_TYPE, u.USER_ID, u.DISPLAY_NAME FROM __RUN_DATABASE__.AUDIT.AUDIT_EVENT e JOIN __RUN_DATABASE__.USERS.APP_USER u ON e.ACTOR_USER_ID=u.USER_ID;


CREATE OR REPLACE VIEW __RUN_DATABASE__.AUDIT.V_CUSTOMER_RECON AS 
SELECT CUSTOMER_ID, BUSINESS_DT, SOURCE_COUNT, TARGET_COUNT, DIFFERENCE_COUNT FROM __RUN_DATABASE__.AUDIT.AUDIT_RECON;
