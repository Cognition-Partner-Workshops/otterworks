CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.AUDIT.P_DAILY_SUMMARY(p_day VARCHAR)
RETURNS BIGINT
LANGUAGE SQL
AS $$
DECLARE
    run_day DATE;
    n BIGINT;
BEGIN
    run_day := TO_DATE(p_day, 'YYYYMMDD');
    DELETE FROM __RUN_DATABASE__.AUDIT.AUDIT_DAILY_SUMMARY WHERE SUMMARY_ID>=10000000000;
    INSERT INTO __RUN_DATABASE__.AUDIT.AUDIT_DAILY_SUMMARY
        (SUMMARY_ID, SUMMARY_DT, CUSTOMER_ID, EVENT_COUNT, EXPORT_COUNT)
    SELECT 10000000000+CUSTOMER_ID, :run_day, CUSTOMER_ID, COUNT(*), 0
    FROM __RUN_DATABASE__.AUDIT.AUDIT_EVENT
    WHERE CAST(EVENT_TS AS DATE)=:run_day GROUP BY CUSTOMER_ID;
    n := SQLROWCOUNT;
    RETURN n;
END;
$$;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.AUDIT.P_RECON_COUNTS(p_day VARCHAR)
RETURNS BIGINT
LANGUAGE SQL
AS $$
DECLARE
    run_day DATE;
    n BIGINT;
BEGIN
    run_day := TO_DATE(p_day, 'YYYYMMDD');
    UPDATE __RUN_DATABASE__.AUDIT.AUDIT_RECON
    SET DIFFERENCE_COUNT=SOURCE_COUNT-TARGET_COUNT WHERE BUSINESS_DT=:run_day;
    n := SQLROWCOUNT;
    RETURN n;
END;
$$;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.AUDIT.M_RECON_TOTALS(p_day VARCHAR)
RETURNS TABLE (RECON_ID BIGINT, SOURCE_COUNT BIGINT, TARGET_COUNT BIGINT, DIFFERENCE_COUNT BIGINT)
LANGUAGE SQL
AS $$
BEGIN
    LET res RESULTSET := (
        SELECT RECON_ID, SOURCE_COUNT, TARGET_COUNT, DIFFERENCE_COUNT
        FROM __RUN_DATABASE__.AUDIT.AUDIT_RECON
        WHERE BUSINESS_DT=TO_DATE(:p_day, 'YYYYMMDD') ORDER BY RECON_ID
    );
    RETURN TABLE(res);
END;
$$;
