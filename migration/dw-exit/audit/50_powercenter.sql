CREATE SCHEMA IF NOT EXISTS __RUN_DATABASE__.AUDIT;
CREATE SEQUENCE IF NOT EXISTS __RUN_DATABASE__.AUDIT.SUMMARY_SEQ START = 50001 INCREMENT = 1 ORDER;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.AUDIT.M_SFX_STG_AUDIT_EVENT()
RETURNS VARCHAR
LANGUAGE SQL
AS $$
BEGIN
    UPDATE __RUN_DATABASE__.AUDIT.STG_AUDIT_EVENT
    SET EVENT_TYPE = TRIM(EVENT_TYPE), DETAILS = TRIM(DETAILS);
    RETURN 'loaded';
END;
$$;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.AUDIT.M_SFX_AUDIT_EVENT()
RETURNS VARCHAR
LANGUAGE SQL
AS $$
BEGIN
    MERGE INTO __RUN_DATABASE__.AUDIT.AUDIT_EVENT t
    USING (
    SELECT EVENT_ID, ACTOR_USER_ID,
           CASE WHEN DOCUMENT_ID > 0 THEN DOCUMENT_ID END DOCUMENT_ID,
           CASE WHEN CUSTOMER_ID > 0 THEN CUSTOMER_ID END CUSTOMER_ID, EVENT_TS,
           UPPER(TRIM(EVENT_TYPE)) EVENT_TYPE,
           CASE WHEN DETAILS IS NULL OR TRIM(DETAILS) = ''
                THEN UPPER(TRIM(EVENT_TYPE)) || ' by user ' || TO_CHAR(ACTOR_USER_ID)
                ELSE TRIM(DETAILS) END DETAILS
    FROM __RUN_DATABASE__.AUDIT.STG_AUDIT_EVENT
    ) s ON t.EVENT_ID=s.EVENT_ID
    WHEN MATCHED THEN UPDATE SET ACTOR_USER_ID=s.ACTOR_USER_ID,
        DOCUMENT_ID=s.DOCUMENT_ID, CUSTOMER_ID=s.CUSTOMER_ID,
        EVENT_TS=s.EVENT_TS, EVENT_TYPE=s.EVENT_TYPE, DETAILS=s.DETAILS
    WHEN NOT MATCHED THEN INSERT (EVENT_ID,ACTOR_USER_ID,DOCUMENT_ID,CUSTOMER_ID,EVENT_TS,EVENT_TYPE,DETAILS)
        VALUES (s.EVENT_ID,s.ACTOR_USER_ID,s.DOCUMENT_ID,s.CUSTOMER_ID,s.EVENT_TS,s.EVENT_TYPE,s.DETAILS);
    RETURN 'loaded';
END;
$$;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.AUDIT.M_SFX_AUDIT_DAILY_SUMMARY()
RETURNS VARCHAR
LANGUAGE SQL
AS $$
BEGIN
    INSERT INTO __RUN_DATABASE__.AUDIT.AUDIT_DAILY_SUMMARY
    SELECT __RUN_DATABASE__.AUDIT.SUMMARY_SEQ.NEXTVAL, SUMMARY_DT, CUSTOMER_ID, EVENT_COUNT, EXPORT_COUNT
    FROM (
        SELECT CAST(EVENT_TS AS DATE) SUMMARY_DT, CUSTOMER_ID,
               COUNT(EVENT_ID) EVENT_COUNT,
               SUM(CASE WHEN EVENT_TYPE = 'DOC_EXPORT' THEN 1 ELSE 0 END) EXPORT_COUNT
        FROM __RUN_DATABASE__.AUDIT.AUDIT_EVENT
        GROUP BY CAST(EVENT_TS AS DATE), CUSTOMER_ID
    );
    RETURN 'loaded';
END;
$$;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.AUDIT.M_SFX_SECURITY_ALERT()
RETURNS VARCHAR
LANGUAGE SQL
AS $$
BEGIN
    MERGE INTO __RUN_DATABASE__.AUDIT.SECURITY_ALERT t
    USING (
        SELECT ALERT_ID, ACTOR_USER_ID, DOCUMENT_ID, ALERT_TS,
               UPPER(TRIM(SEVERITY_CD)) SEVERITY_CD,
               CASE WHEN UPPER(TRIM(SEVERITY_CD)) IN ('CRITICAL','HIGH')
                         AND UPPER(TRIM(STATUS_CD)) = 'OPEN' THEN 'ESCALATED'
                    ELSE UPPER(TRIM(STATUS_CD)) END STATUS_CD
        FROM __RUN_DATABASE__.AUDIT.STG_SECURITY_ALERT
        WHERE UPPER(TRIM(SEVERITY_CD)) IN ('CRITICAL','HIGH','MEDIUM','LOW')
    ) s ON t.ALERT_ID=s.ALERT_ID
    WHEN MATCHED THEN UPDATE SET ACTOR_USER_ID=s.ACTOR_USER_ID,
        DOCUMENT_ID=s.DOCUMENT_ID, ALERT_TS=s.ALERT_TS,
        SEVERITY_CD=s.SEVERITY_CD, STATUS_CD=s.STATUS_CD
    WHEN NOT MATCHED THEN INSERT (ALERT_ID,ACTOR_USER_ID,DOCUMENT_ID,ALERT_TS,SEVERITY_CD,STATUS_CD)
        VALUES (s.ALERT_ID,s.ACTOR_USER_ID,s.DOCUMENT_ID,s.ALERT_TS,s.SEVERITY_CD,s.STATUS_CD);
    RETURN 'loaded';
END;
$$;
