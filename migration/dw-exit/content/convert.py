"""Compile the owned dbt SELECTs into the content workflow's session writes."""
from pathlib import Path
import sys

from jinja2 import StrictUndefined
from jinja2.sandbox import SandboxedEnvironment
import sqlglot

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

STEPS = ('STG_APP_USER', 'APP_USER', 'ROLE_GRANT', 'LOGIN_EVENT',
         'STG_DOCUMENT', 'DOCUMENT', 'DOC_SHARE')
TRUNCATE = {'STG_APP_USER', 'ROLE_GRANT', 'STG_DOCUMENT'}
KEYS = {'APP_USER': 'USER_ID', 'LOGIN_EVENT': 'LOGIN_ID',
        'DOCUMENT': 'DOCUMENT_ID', 'DOC_SHARE': 'SHARE_ID', 'TEAM_MEMBER': 'TEAM_MEMBER_ID'}
DOCUMENTS = {'STG_DOCUMENT', 'DOCUMENT', 'DOC_SHARE'}


def relation(name):
    return '__RUN_DATABASE__.' + ('DOCUMENTS.' if name in DOCUMENTS else 'USERS.') + name


def select(name):
    env = SandboxedEnvironment(undefined=StrictUndefined, autoescape=False)
    context = dict(config=lambda **kw: '', source=lambda schema, table: '__RUN_DATABASE__.PC_SRC.' + table,
                   ref=lambda model: relation(model.split('__', 1)[1].upper()))
    macros = ROOT / 'warehouse/dbt/macros'
    text = '\n'.join(p.read_text() for p in sorted(macros.glob('pc_content*.sql')))
    text += '\n' + '\n'.join(p.read_text() for p in sorted(macros.glob('unt8*.sql')))
    model = ROOT / 'warehouse/dbt/models/pc/content' / ('pc_content__' + name.lower() + '.sql')
    return env.from_string(text+'\n'+model.read_text()).render(context).strip().rstrip(';')


def session_target(name):
    layer = 'STG' if name.startswith('STG_') else 'CORE'
    area = 'DOCUMENTS' if name in DOCUMENTS else 'USERS'
    return '__RUN_DATABASE__.OPS.' + layer + '_' + area + '__S_M_SFX_' + name


def generate_sessions(area):
    statements = []
    names = [name for name in (*STEPS, 'TEAM_MEMBER') if (name in DOCUMENTS) == (area == 'documents')]
    for name in names:
        target = relation(name)
        query = select(name)
        statements.append('CREATE OR REPLACE PROCEDURE '+session_target(name)+"()\nRETURNS VARCHAR\nLANGUAGE SQL\nEXECUTE AS CALLER\nAS\n$$\nBEGIN")
        if name in TRUNCATE:
            statements.extend([f'TRUNCATE TABLE {target};', f'INSERT INTO {target}\n{query};'])
        else:
            columns = [column.alias_or_name for column in sqlglot.parse_one(query, read='snowflake').selects]
            key = KEYS[name]
            update = ', '.join(f'{c} = s.{c}' for c in columns if c != key)
            statements.append(f'MERGE INTO {target} t USING (\n{query}\n) s ON t.{key} = s.{key}\n'
                              f'WHEN MATCHED THEN UPDATE SET {update}\n'
                              f'WHEN NOT MATCHED THEN INSERT ({", ".join(columns)}) VALUES '
                              f'({", ".join("s." + c for c in columns)});')
        statements.append("RETURN 'SUCCEEDED';\nEND;\n$$;\n")
    return '\n'.join(statements)


def generate():
    return ('-- Generated by content/convert.py; delegates to area-owned session targets.\n'
            '-- TEAM_MEMBER is disabled; its pre-workflow contents remain untouched.\n'
            '-- Sequential topological execution: DOC_SHARE follows both DOCUMENT and ROLE_GRANT.\n'
            '-- No exception handler: any session failure aborts and blocks downstream writes.\n'
            'CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.OPS.WF_SFX_CONTENT_DAILY()\n'
            'RETURNS VARCHAR\nLANGUAGE SQL\nEXECUTE AS CALLER\nAS\n$$\nBEGIN\n'
            + '\n'.join('CALL '+session_target(name)+'();' for name in STEPS)
            + "\nRETURN 'SUCCEEDED';\nEND;\n$$;\n")


if __name__ == '__main__':
    path = Path(__file__).with_name('workflow.sql')
    path.write_text(generate())
    for area in ('users', 'documents'):
        (path.parent.parent/area/'52_sessions.sql').write_text(generate_sessions(area))
    print(path.relative_to(ROOT))
