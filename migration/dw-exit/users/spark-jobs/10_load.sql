CREATE OR REPLACE TABLE __RUN_DATABASE__.USERS.USERS_ACTIVE_DAILY AS
SELECT ACTIVITY_DATE, COUNT(DISTINCT USER_ID) AS ACTIVE_USERS,
       SUM(LOGIN_COUNT) AS LOGINS, SUM(ACTION_COUNT) AS ACTIONS
FROM __RUN_DATABASE__.USERS.STG_USER_ACTIVITY_DAILY GROUP BY ACTIVITY_DATE;

CREATE OR REPLACE TABLE __RUN_DATABASE__.USERS.USERS_TEAM_ROLLUP AS
SELECT t.TEAM_ID, t.TEAM_NAME, COUNT(m.USER_ID) AS MEMBERS
FROM __RUN_DATABASE__.USERS.STG_TEAM t
LEFT JOIN __RUN_DATABASE__.USERS.STG_TEAM_MEMBER m ON t.TEAM_ID = m.TEAM_ID
LEFT JOIN __RUN_DATABASE__.USERS.STG_APP_USER u ON m.USER_ID = u.USER_ID
GROUP BY t.TEAM_ID, t.TEAM_NAME;
