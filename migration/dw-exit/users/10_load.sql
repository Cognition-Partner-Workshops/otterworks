-- m_SFX_APP_USER (SFX_CONTENT): SQ_STG_APP_USER -> LKP_APP_USER -> UPD_APP_USER -> APP_USER.
-- LKP_APP_USER probes the unique USER_ID, so IIF(ISNULL(lkp_USER_ID), DD_INSERT, DD_UPDATE)
-- is a keyed upsert; rows absent from staging are left as they are.
-- Target widths follow the Teradata columns: VARCHAR(60), VARCHAR(120) and blank-padded CHAR(12).
-- A NULL USER_ID is rejected by the NOT NULL key. Staging carries no arrival order, so a
-- repeated USER_ID keeps one row chosen by a fixed column order.
MERGE INTO __RUN_DATABASE__.USERS.APP_USER AS T
USING (
    SELECT USER_ID,
           LEFT(DISPLAY_NAME, 60) AS DISPLAY_NAME,
           LEFT(EMAIL, 120) AS EMAIL,
           RPAD(LEFT(STATUS_CD, 12), 12, ' ') AS STATUS_CD,
           CREATED_DT
    FROM __RUN_DATABASE__.USERS.STG_APP_USER
    WHERE USER_ID IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY USER_ID ORDER BY CREATED_DT, DISPLAY_NAME, EMAIL, STATUS_CD) = 1
) AS S
ON T.USER_ID = S.USER_ID
WHEN MATCHED THEN UPDATE SET
    DISPLAY_NAME = S.DISPLAY_NAME, EMAIL = S.EMAIL, STATUS_CD = S.STATUS_CD, CREATED_DT = S.CREATED_DT
WHEN NOT MATCHED THEN INSERT (USER_ID, DISPLAY_NAME, EMAIL, STATUS_CD, CREATED_DT)
    VALUES (S.USER_ID, S.DISPLAY_NAME, S.EMAIL, S.STATUS_CD, S.CREATED_DT);
