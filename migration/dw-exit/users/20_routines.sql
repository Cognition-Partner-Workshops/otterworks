CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.USERS.P_ACTIVITY_DAILY (P_DAY VARCHAR(8))
RETURNS BIGINT
LANGUAGE SQL
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
EXECUTE AS CALLER
AS
$$
DECLARE
    run_day DATE;
    n BIGINT;
BEGIN
    run_day := TO_DATE(p_day, 'YYYYMMDD');
    DELETE FROM __RUN_DATABASE__.USERS.USER_ACTIVITY_DAILY WHERE ACTIVITY_ID >= 10000000000;
    INSERT INTO __RUN_DATABASE__.USERS.USER_ACTIVITY_DAILY (ACTIVITY_ID, USER_ID, ACTIVITY_DT, LOGIN_COUNT, DOCUMENT_COUNT)
    SELECT 10000000000 + USER_ID, USER_ID, :run_day, COUNT(*), 0
    FROM __RUN_DATABASE__.USERS.LOGIN_EVENT WHERE CAST(LOGIN_TS AS DATE) = :run_day GROUP BY USER_ID;
    n := SQLROWCOUNT;
    RETURN n;
END;
$$;

CREATE OR REPLACE PROCEDURE __RUN_DATABASE__.USERS.M_TEAM_COUNTS (P_DAY VARCHAR(8))
RETURNS TABLE ()
LANGUAGE SQL
COMMENT = 'run_token=__RUN_TOKEN__ expires=2026-11-24'
EXECUTE AS CALLER
AS
$$
BEGIN
LET res RESULTSET :=
(
SELECT t.TEAM_ID, t.TEAM_NAME, COUNT(m.TEAM_MEMBER_ID) AS MEMBER_COUNT
FROM __RUN_DATABASE__.USERS.TEAM t LEFT JOIN __RUN_DATABASE__.USERS.TEAM_MEMBER m ON t.TEAM_ID = m.TEAM_ID
GROUP BY t.TEAM_ID, t.TEAM_NAME
);
RETURN TABLE(res);
END;
$$;
