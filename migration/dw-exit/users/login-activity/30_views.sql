-- P_ACTIVITY_DAILY input, filtered to the requested business day by the caller.
CREATE OR REPLACE VIEW __RUN_DATABASE__.USERS.V_ACTIVITY_DAILY AS
SELECT 10000000000 + USER_ID AS ACTIVITY_ID,
       USER_ID,
       CAST(LOGIN_TS AS DATE) AS ACTIVITY_DT,
       COUNT(*) AS LOGIN_COUNT,
       0 AS DOCUMENT_COUNT
FROM __RUN_DATABASE__.USERS.LOGIN_EVENT
GROUP BY USER_ID, CAST(LOGIN_TS AS DATE);
