-- Wave 4 compatibility view. Snowflake supplies statement-level read consistency.
CREATE OR REPLACE VIEW __RUN_DATABASE__.USERS.V_TEAM_MEMBERS AS
SELECT t.TEAM_ID, t.TEAM_NAME, u.USER_ID, u.DISPLAY_NAME
FROM __RUN_DATABASE__.USERS.TEAM t
JOIN __RUN_DATABASE__.USERS.TEAM_MEMBER m ON t.TEAM_ID = m.TEAM_ID
JOIN __RUN_DATABASE__.USERS.APP_USER u ON m.USER_ID = u.USER_ID;

-- Relational result shared by the macro replacement and local parity.
CREATE OR REPLACE VIEW __RUN_DATABASE__.USERS.V_TEAM_COUNTS AS
SELECT t.TEAM_ID, t.TEAM_NAME, COUNT(m.TEAM_MEMBER_ID) AS MEMBER_COUNT
FROM __RUN_DATABASE__.USERS.TEAM t
LEFT JOIN __RUN_DATABASE__.USERS.TEAM_MEMBER m ON t.TEAM_ID = m.TEAM_ID
GROUP BY t.TEAM_ID, t.TEAM_NAME;
