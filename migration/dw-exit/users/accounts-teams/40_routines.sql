CREATE SCHEMA IF NOT EXISTS __RUN_DATABASE__.OPS;

-- Preserve the original call signature; the Teradata macro does not read P_DAY.
CREATE OR REPLACE FUNCTION __RUN_DATABASE__.OPS.SFX_USERS_M_TEAM_COUNTS(P_DAY VARCHAR)
RETURNS TABLE (TEAM_ID BIGINT, TEAM_NAME VARCHAR, MEMBER_COUNT BIGINT)
LANGUAGE SQL
AS $$
    SELECT counts.TEAM_ID, counts.TEAM_NAME, counts.MEMBER_COUNT
    FROM __RUN_DATABASE__.USERS.V_TEAM_COUNTS AS counts
$$;
