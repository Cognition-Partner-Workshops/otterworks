-- Preserve the day's landing rows before the PowerCenter stage refresh.
CREATE OR REPLACE TEMPORARY TABLE PC_INPUT_APP_USER AS
SELECT USER_ID, DISPLAY_NAME, EMAIL, STATUS_CD, CREATED_DT
FROM __RUN_DATABASE__.USERS.STG_APP_USER;

-- Refuse an ambiguous merge or overwrite when the typed stage has duplicate keys.
SELECT CAST(CASE WHEN COUNT(USER_ID) = COUNT(DISTINCT USER_ID) THEN '0'
                 ELSE 'duplicate PowerCenter USER_ID' END AS INT)
FROM PC_INPUT_APP_USER;
SELECT CAST(CASE WHEN COUNT(GRANT_ID) = COUNT(DISTINCT GRANT_ID) THEN '0'
                 ELSE 'duplicate PowerCenter GRANT_ID' END AS INT)
FROM __RUN_DATABASE__.USERS.STG_ROLE_GRANT;

BEGIN TRANSACTION;
-- s_m_SFX_STG_APP_USER replaces the stage. Flat-file port widths apply before expressions.
DELETE FROM __RUN_DATABASE__.USERS.STG_APP_USER;
INSERT INTO __RUN_DATABASE__.USERS.STG_APP_USER
SELECT USER_ID,
       TRIM(LEFT(NULLIF(DISPLAY_NAME, ''), 60)),
       LOWER(TRIM(LEFT(NULLIF(EMAIL, ''), 120))),
       UPPER(TRIM(LEFT(NULLIF(STATUS_CD, ''), 12))),
       CREATED_DT
FROM PC_INPUT_APP_USER;

-- s_m_SFX_APP_USER uses lookup-driven insert or update by USER_ID.
MERGE INTO __RUN_DATABASE__.USERS.APP_USER AS target
USING (
    SELECT USER_ID, DISPLAY_NAME, EMAIL, RPAD(STATUS_CD, 12, ' ') AS STATUS_CD, CREATED_DT
    FROM __RUN_DATABASE__.USERS.STG_APP_USER
    WHERE USER_ID IS NOT NULL
) AS incoming
ON target.USER_ID = incoming.USER_ID
WHEN MATCHED THEN UPDATE SET
    DISPLAY_NAME = incoming.DISPLAY_NAME, EMAIL = incoming.EMAIL,
    STATUS_CD = incoming.STATUS_CD, CREATED_DT = incoming.CREATED_DT
WHEN NOT MATCHED THEN INSERT (USER_ID, DISPLAY_NAME, EMAIL, STATUS_CD, CREATED_DT)
VALUES (incoming.USER_ID, incoming.DISPLAY_NAME, incoming.EMAIL, incoming.STATUS_CD, incoming.CREATED_DT);

-- s_m_SFX_ROLE_GRANT uses insert mode and clears its target.
DELETE FROM __RUN_DATABASE__.USERS.ROLE_GRANT;
INSERT INTO __RUN_DATABASE__.USERS.ROLE_GRANT
SELECT GRANT_ID, USER_ID, RPAD(UPPER(TRIM(LEFT(NULLIF(ROLE_CD, ''), 12))), 12, ' '), GRANTED_DT
FROM __RUN_DATABASE__.USERS.STG_ROLE_GRANT
WHERE GRANT_ID IS NOT NULL;
COMMIT;
