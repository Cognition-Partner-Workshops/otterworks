-- Standalone session, disabled in wf_SFX_CONTENT_DAILY.
SELECT CAST(CASE WHEN COUNT(TEAM_MEMBER_ID) = COUNT(DISTINCT TEAM_MEMBER_ID) THEN '0'
                 ELSE 'duplicate PowerCenter TEAM_MEMBER_ID' END AS INT)
FROM __RUN_DATABASE__.USERS.STG_TEAM_MEMBER;

BEGIN TRANSACTION;
MERGE INTO __RUN_DATABASE__.USERS.TEAM_MEMBER AS target
USING (
    SELECT TEAM_MEMBER_ID, TEAM_ID, USER_ID,
           RPAD(UPPER(TRIM(LEFT(NULLIF(ROLE_CD, ''), 12))), 12, ' ') AS ROLE_CD, JOINED_DT
    FROM __RUN_DATABASE__.USERS.STG_TEAM_MEMBER
    WHERE TEAM_MEMBER_ID IS NOT NULL
) AS incoming
ON target.TEAM_MEMBER_ID = incoming.TEAM_MEMBER_ID
WHEN MATCHED THEN UPDATE SET
    TEAM_ID = incoming.TEAM_ID, USER_ID = incoming.USER_ID,
    ROLE_CD = incoming.ROLE_CD, JOINED_DT = incoming.JOINED_DT
WHEN NOT MATCHED THEN INSERT (TEAM_MEMBER_ID, TEAM_ID, USER_ID, ROLE_CD, JOINED_DT)
VALUES (incoming.TEAM_MEMBER_ID, incoming.TEAM_ID, incoming.USER_ID, incoming.ROLE_CD, incoming.JOINED_DT);
COMMIT;
