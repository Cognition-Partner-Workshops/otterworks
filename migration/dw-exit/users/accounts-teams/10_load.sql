-- 01_load_users.bteq
BEGIN TRANSACTION;
DELETE FROM __RUN_DATABASE__.USERS.APP_USER;
INSERT INTO __RUN_DATABASE__.USERS.APP_USER
SELECT USER_ID, LEFT(DISPLAY_NAME, 60), LEFT(EMAIL, 120),
       RPAD(STATUS_CD, 12, ' '),
       CREATED_DT
FROM __RUN_DATABASE__.USERS.STG_APP_USER;

DELETE FROM __RUN_DATABASE__.USERS.USER_PROFILE;
INSERT INTO __RUN_DATABASE__.USERS.USER_PROFILE
SELECT PROFILE_ID, USER_ID, LEFT(TITLE, 60), RPAD(COUNTRY_CD, 2, ' '), LEFT(TIMEZONE, 40)
FROM __RUN_DATABASE__.USERS.STG_USER_PROFILE;
COMMIT;

-- 02_load_teams.bteq
BEGIN TRANSACTION;
DELETE FROM __RUN_DATABASE__.USERS.TEAM;
INSERT INTO __RUN_DATABASE__.USERS.TEAM
SELECT TEAM_ID, OWNER_USER_ID, LEFT(TEAM_NAME, 80), CREATED_DT
FROM __RUN_DATABASE__.USERS.STG_TEAM;

DELETE FROM __RUN_DATABASE__.USERS.TEAM_MEMBER;
INSERT INTO __RUN_DATABASE__.USERS.TEAM_MEMBER
SELECT TEAM_MEMBER_ID, TEAM_ID, USER_ID, RPAD(ROLE_CD, 12, ' '), JOINED_DT
FROM __RUN_DATABASE__.USERS.STG_TEAM_MEMBER;

DELETE FROM __RUN_DATABASE__.USERS.ROLE_GRANT;
INSERT INTO __RUN_DATABASE__.USERS.ROLE_GRANT
SELECT GRANT_ID, USER_ID, RPAD(ROLE_CD, 12, ' '), GRANTED_DT
FROM __RUN_DATABASE__.USERS.STG_ROLE_GRANT;
COMMIT;
