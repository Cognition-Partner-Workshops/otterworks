CREATE SCHEMA IF NOT EXISTS __RUN_DATABASE__.USERS;

-- Keep the Teradata key declarations as metadata. Snowflake enforces NOT NULL.
CREATE TABLE IF NOT EXISTS __RUN_DATABASE__.USERS.APP_USER (
    USER_ID BIGINT PRIMARY KEY NOT NULL,
    DISPLAY_NAME VARCHAR(60),
    EMAIL VARCHAR(120),
    STATUS_CD VARCHAR(12),
    CREATED_DT DATE
);
CREATE TABLE IF NOT EXISTS __RUN_DATABASE__.USERS.STG_APP_USER (
    USER_ID BIGINT, DISPLAY_NAME VARCHAR(200), EMAIL VARCHAR(200),
    STATUS_CD VARCHAR(200), CREATED_DT DATE
);

CREATE TABLE IF NOT EXISTS __RUN_DATABASE__.USERS.USER_PROFILE (
    PROFILE_ID BIGINT PRIMARY KEY NOT NULL,
    USER_ID BIGINT,
    TITLE VARCHAR(60),
    COUNTRY_CD VARCHAR(2),
    TIMEZONE VARCHAR(40)
);
CREATE TABLE IF NOT EXISTS __RUN_DATABASE__.USERS.STG_USER_PROFILE (
    PROFILE_ID BIGINT, USER_ID BIGINT, TITLE VARCHAR(200),
    COUNTRY_CD VARCHAR(200), TIMEZONE VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS __RUN_DATABASE__.USERS.TEAM (
    TEAM_ID BIGINT PRIMARY KEY NOT NULL,
    OWNER_USER_ID BIGINT,
    TEAM_NAME VARCHAR(80),
    CREATED_DT DATE
);
CREATE TABLE IF NOT EXISTS __RUN_DATABASE__.USERS.STG_TEAM (
    TEAM_ID BIGINT, OWNER_USER_ID BIGINT, TEAM_NAME VARCHAR(200), CREATED_DT DATE
);

CREATE TABLE IF NOT EXISTS __RUN_DATABASE__.USERS.TEAM_MEMBER (
    TEAM_MEMBER_ID BIGINT PRIMARY KEY NOT NULL,
    TEAM_ID BIGINT,
    USER_ID BIGINT,
    ROLE_CD VARCHAR(12),
    JOINED_DT DATE
);
CREATE TABLE IF NOT EXISTS __RUN_DATABASE__.USERS.STG_TEAM_MEMBER (
    TEAM_MEMBER_ID BIGINT, TEAM_ID BIGINT, USER_ID BIGINT, ROLE_CD VARCHAR(200), JOINED_DT DATE
);

CREATE TABLE IF NOT EXISTS __RUN_DATABASE__.USERS.ROLE_GRANT (
    GRANT_ID BIGINT PRIMARY KEY NOT NULL,
    USER_ID BIGINT,
    ROLE_CD VARCHAR(12),
    GRANTED_DT DATE
);
CREATE TABLE IF NOT EXISTS __RUN_DATABASE__.USERS.STG_ROLE_GRANT (
    GRANT_ID BIGINT, USER_ID BIGINT, ROLE_CD VARCHAR(200), GRANTED_DT DATE
);
