-- Render __BUSINESS_DATE__ as an eight-digit YYYYMMDD date before running.
CREATE FILE FORMAT IF NOT EXISTS __RUN_DATABASE__.USERS.ACCOUNTS_TEAMS_PSV
    TYPE = CSV FIELD_DELIMITER = '|' FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    ESCAPE_UNENCLOSED_FIELD = NONE EMPTY_FIELD_AS_NULL = FALSE NULL_IF = ();

BEGIN TRANSACTION;
DELETE FROM __RUN_DATABASE__.USERS.STG_APP_USER;
COPY INTO __RUN_DATABASE__.USERS.STG_APP_USER (USER_ID, DISPLAY_NAME, EMAIL, STATUS_CD, CREATED_DT)
FROM (
    SELECT NULLIF($1, '')::BIGINT, $2, $3, $4, TO_DATE(NULLIF($5, ''), 'YYYY-MM-DD')
    FROM @__RUN_DATABASE__.LANDING.LANDING_STAGE/users/APP_USER/__BUSINESS_DATE__.psv
)
FILE_FORMAT = (FORMAT_NAME = '__RUN_DATABASE__.USERS.ACCOUNTS_TEAMS_PSV')
ON_ERROR = ABORT_STATEMENT FORCE = TRUE;

DELETE FROM __RUN_DATABASE__.USERS.STG_USER_PROFILE;
COPY INTO __RUN_DATABASE__.USERS.STG_USER_PROFILE (PROFILE_ID, USER_ID, TITLE, COUNTRY_CD, TIMEZONE)
FROM (
    SELECT NULLIF($1, '')::BIGINT, NULLIF($2, '')::BIGINT, $3, $4, $5
    FROM @__RUN_DATABASE__.LANDING.LANDING_STAGE/users/USER_PROFILE/__BUSINESS_DATE__.psv
)
FILE_FORMAT = (FORMAT_NAME = '__RUN_DATABASE__.USERS.ACCOUNTS_TEAMS_PSV')
ON_ERROR = ABORT_STATEMENT FORCE = TRUE;

DELETE FROM __RUN_DATABASE__.USERS.STG_TEAM;
COPY INTO __RUN_DATABASE__.USERS.STG_TEAM (TEAM_ID, OWNER_USER_ID, TEAM_NAME, CREATED_DT)
FROM (
    SELECT NULLIF($1, '')::BIGINT, NULLIF($2, '')::BIGINT, $3, TO_DATE(NULLIF($4, ''), 'YYYY-MM-DD')
    FROM @__RUN_DATABASE__.LANDING.LANDING_STAGE/users/TEAM/__BUSINESS_DATE__.psv
)
FILE_FORMAT = (FORMAT_NAME = '__RUN_DATABASE__.USERS.ACCOUNTS_TEAMS_PSV')
ON_ERROR = ABORT_STATEMENT FORCE = TRUE;

DELETE FROM __RUN_DATABASE__.USERS.STG_TEAM_MEMBER;
COPY INTO __RUN_DATABASE__.USERS.STG_TEAM_MEMBER (TEAM_MEMBER_ID, TEAM_ID, USER_ID, ROLE_CD, JOINED_DT)
FROM (
    SELECT NULLIF($1, '')::BIGINT, NULLIF($2, '')::BIGINT, NULLIF($3, '')::BIGINT, $4,
           TO_DATE(NULLIF($5, ''), 'YYYY-MM-DD')
    FROM @__RUN_DATABASE__.LANDING.LANDING_STAGE/users/TEAM_MEMBER/__BUSINESS_DATE__.psv
)
FILE_FORMAT = (FORMAT_NAME = '__RUN_DATABASE__.USERS.ACCOUNTS_TEAMS_PSV')
ON_ERROR = ABORT_STATEMENT FORCE = TRUE;

DELETE FROM __RUN_DATABASE__.USERS.STG_ROLE_GRANT;
COPY INTO __RUN_DATABASE__.USERS.STG_ROLE_GRANT (GRANT_ID, USER_ID, ROLE_CD, GRANTED_DT)
FROM (
    SELECT NULLIF($1, '')::BIGINT, NULLIF($2, '')::BIGINT, $3, TO_DATE(NULLIF($4, ''), 'YYYY-MM-DD')
    FROM @__RUN_DATABASE__.LANDING.LANDING_STAGE/users/ROLE_GRANT/__BUSINESS_DATE__.psv
)
FILE_FORMAT = (FORMAT_NAME = '__RUN_DATABASE__.USERS.ACCOUNTS_TEAMS_PSV')
ON_ERROR = ABORT_STATEMENT FORCE = TRUE;
COMMIT;
