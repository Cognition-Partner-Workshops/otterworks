CREATE TABLE ODL.CUSTMAST (
 CUST_NO CHAR(10) NOT NULL PRIMARY KEY,
 FULL_NAME VARCHAR(80) FOR BIT DATA NOT NULL,
 ADDRESS VARCHAR(160) NOT NULL,
 OPENED_ON DATE NOT NULL,
 OPENED_YMD DECIMAL(8,0) NOT NULL
);
CREATE TABLE ODL.ACCTHIST (
 HISTORY_ID BIGINT NOT NULL PRIMARY KEY,
 CUST_NO CHAR(10) NOT NULL,
 EVENT_ON DATE NOT NULL,
 AMOUNT DECIMAL(15,2) NOT NULL
);
CREATE TABLE ODL.SEED_VERSION (VERSION CHAR(64) NOT NULL PRIMARY KEY);
