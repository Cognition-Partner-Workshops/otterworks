def sq(text):
    return "'" + text.replace("'", "''") + "'"


def db2_ts(ts):
    return sq(f"{ts[0]}-{ts[1]}.{ts[2]}")


def pg_ts(ts):
    return sq(f"{ts[0]} {ts[1].replace('.', ':')}.{ts[2][:6]}"), int(ts[2][6:])


def cp037(text, length):
    raw = text.encode("cp037")
    raw = raw + b"\x40" * (length - len(raw))
    return "X'" + raw.hex().upper() + "'"


