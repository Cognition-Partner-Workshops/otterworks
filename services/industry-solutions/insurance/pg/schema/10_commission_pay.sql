-- Commission Pay OLTP schema, translated from db/oltp/01_tables.sql and the
-- object types in db/oltp/03_commission_pkg.sql.
--
-- Type mapping (Oracle -> PostgreSQL 16):
--   NUMBER identity / id columns  -> bigint
--   NUMBER(p, s)                  -> numeric(p, s)   (same precision and scale)
--   NUMBER (unconstrained)        -> numeric
--   VARCHAR2(n)                   -> varchar(n)
--   DATE                          -> timestamp(0)    (Oracle DATE carries a time to the second)
--   TIMESTAMP                     -> timestamp(6)
--   SYSDATE / SYSTIMESTAMP        -> LOCALTIMESTAMP(0) / LOCALTIMESTAMP
\set ON_ERROR_STOP on
SET ROLE commission_pay;
SET search_path = commission_pay;

-- Oracle: TYPE split_alloc_t AS OBJECT (agent_id NUMBER, split_pct NUMBER)
CREATE TYPE split_alloc_t AS (
    agent_id  numeric,
    split_pct numeric
);

-- Oracle: TYPE split_alloc_tab AS TABLE OF split_alloc_t
CREATE DOMAIN split_alloc_tab AS split_alloc_t[];

CREATE TABLE agents (
    agent_id      bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_code    varchar(16)   NOT NULL UNIQUE,
    full_name     varchar(120)  NOT NULL,
    license_no    varchar(32)   NOT NULL UNIQUE,
    status        varchar(12)   DEFAULT 'ACTIVE' NOT NULL
                  CONSTRAINT ck_agents_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'TERMINATED')),
    hired_date    timestamp(0)  DEFAULT LOCALTIMESTAMP(0) NOT NULL
);

CREATE TABLE products (
    product_code  varchar(16)   PRIMARY KEY,
    product_name  varchar(120)  NOT NULL,
    line_of_business varchar(24) NOT NULL
                  CONSTRAINT ck_products_lob CHECK (line_of_business IN ('AUTO', 'HOME', 'LIFE', 'COMMERCIAL'))
);

CREATE TABLE commission_rates (
    rate_id       bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code  varchar(16)   NOT NULL REFERENCES products (product_code),
    agent_id      bigint        REFERENCES agents (agent_id),
    rate_pct      numeric(5, 2) NOT NULL
                  CONSTRAINT ck_rates_range CHECK (rate_pct > 0 AND rate_pct <= 50),
    effective_from timestamp(0) NOT NULL,
    effective_to   timestamp(0),
    created_by    varchar(64)   NOT NULL,
    created_at    timestamp(6)  DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT ck_rates_dates CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

-- Oracle: UNIQUE INDEX ux_rates_open (product_code, NVL(agent_id, -1),
--         CASE WHEN effective_to IS NULL THEN 0 END)
-- Translated as is, legacy behaviour included: Oracle indexes a row whose
-- key is partly NULL, so closed rates of one scope collide with each other
-- and upsert_commission_rate can supersede a scope only once. NULLS NOT
-- DISTINCT makes PostgreSQL reject the second closed rate the same way.
-- This is the legacy behaviour reproduced, not a fix.
CREATE UNIQUE INDEX ux_rates_open ON commission_rates (
    product_code,
    COALESCE(agent_id, -1),
    (CASE WHEN effective_to IS NULL THEN 0 END)
) NULLS NOT DISTINCT;

CREATE TABLE policies (
    policy_id     bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_no     varchar(24)   NOT NULL UNIQUE,
    product_code  varchar(16)   NOT NULL REFERENCES products (product_code),
    holder_name   varchar(120)  NOT NULL,
    annual_premium numeric(12, 2) NOT NULL CHECK (annual_premium > 0),
    issued_date   timestamp(0)  NOT NULL,
    status        varchar(12)   DEFAULT 'IN_FORCE' NOT NULL
                  CONSTRAINT ck_policies_status CHECK (status IN ('IN_FORCE', 'LAPSED', 'CANCELLED'))
);

CREATE TABLE commission_splits (
    split_id      bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id     bigint        NOT NULL REFERENCES policies (policy_id),
    agent_id      bigint        NOT NULL REFERENCES agents (agent_id),
    split_pct     numeric(5, 2) NOT NULL
                  CONSTRAINT ck_splits_range CHECK (split_pct > 0 AND split_pct <= 100),
    CONSTRAINT ux_splits_policy_agent UNIQUE (policy_id, agent_id)
);

CREATE TABLE commission_ledger (
    ledger_id     bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id     bigint        NOT NULL REFERENCES policies (policy_id),
    agent_id      bigint        NOT NULL REFERENCES agents (agent_id),
    period_month  varchar(7)    NOT NULL,  -- YYYY-MM
    rate_id       bigint        NOT NULL REFERENCES commission_rates (rate_id),
    split_pct     numeric(5, 2) NOT NULL,
    base_premium  numeric(12, 2) NOT NULL,
    commission_amt numeric(12, 2) NOT NULL,
    calculated_at timestamp(6)  DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT ux_ledger_row UNIQUE (policy_id, agent_id, period_month)
);

-- Audit trail every management procedure writes to. No foreign keys, as in
-- Oracle: the log outlives the rows it describes.
CREATE TABLE rate_audit_log (
    audit_id      bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action        varchar(32)   NOT NULL,
    product_code  varchar(16),
    agent_id      bigint,
    policy_id     bigint,
    detail        varchar(400),
    actor         varchar(64)   NOT NULL,
    logged_at     timestamp(6)  DEFAULT LOCALTIMESTAMP NOT NULL
);

-- Fixture completion marker (created by db/startup/00_init.sh in Oracle).
CREATE TABLE fixture_meta (
    initialized_at timestamp(6) DEFAULT LOCALTIMESTAMP NOT NULL
);

-- Oracle NUMBER arithmetic, reproduced (decision D4 A). Oracle holds every
-- intermediate result of an expression in a NUMBER: a mantissa of 20 base-100
-- digits (38 to 40 significant decimal digits), rounded half up. PostgreSQL
-- numeric keeps a different number of digits, so the legacy formula
-- annual_premium / 12 * rate_pct / 100 * split_pct / 100 rounded to cents can
-- land on the other side of a half cent. ora_number rounds a value the way
-- Oracle stores it; commission_amount applies it after every operation in the
-- order COMMISSION_PKG.CALCULATE_POLICY_COMMISSION evaluates them.
CREATE FUNCTION ora_number(x numeric) RETURNS numeric
LANGUAGE plpgsql IMMUTABLE STRICT PARALLEL SAFE AS $$
DECLARE
    e10  integer;
    e100 integer;
BEGIN
    IF x = 0 THEN
        RETURN 0;
    END IF;
    e10 := floor(log(abs(x)));
    IF abs(x) >= power(10::numeric, e10 + 1) THEN
        e10 := e10 + 1;
    ELSIF abs(x) < power(10::numeric, e10) THEN
        e10 := e10 - 1;
    END IF;
    e100 := floor(e10 / 2.0);
    RETURN round(x, 2 * (19 - e100));
END;
$$;

CREATE FUNCTION commission_amount(annual_premium numeric, rate_pct numeric, split_pct numeric)
RETURNS numeric(12, 2)
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT round(
        commission_pay.ora_number(round(
            commission_pay.ora_number(commission_pay.ora_number(round(
                commission_pay.ora_number(commission_pay.ora_number(round(annual_premium, 80) / 12) * rate_pct), 80) / 100)
                * split_pct), 80) / 100),
        2)
$$;

