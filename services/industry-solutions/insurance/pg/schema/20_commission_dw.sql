-- Commission analytics star schema and summary materialized view, translated
-- from db/olap/01_star_schema.sql and db/olap/02_etl_pkg.sql. Type mapping as
-- in 10_commission_pay.sql.
\set ON_ERROR_STOP on
SET ROLE commission_dw;
SET search_path = commission_dw;

CREATE TABLE dim_agent (
    agent_key    bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id     bigint        NOT NULL UNIQUE,
    agent_code   varchar(16)   NOT NULL,
    full_name    varchar(120)  NOT NULL,
    status       varchar(12)   NOT NULL
);

CREATE TABLE dim_product (
    product_key      bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code     varchar(16)  NOT NULL UNIQUE,
    product_name     varchar(120) NOT NULL,
    line_of_business varchar(24)  NOT NULL
);

CREATE TABLE dim_period (
    period_key   bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_month varchar(7)   NOT NULL UNIQUE,  -- YYYY-MM
    year_num     numeric(4)   NOT NULL,
    month_num    numeric(2)   NOT NULL,
    quarter_num  numeric(1)   NOT NULL
);

CREATE TABLE fact_commission (
    fact_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_key      bigint NOT NULL REFERENCES dim_agent (agent_key),
    product_key    bigint NOT NULL REFERENCES dim_product (product_key),
    period_key     bigint NOT NULL REFERENCES dim_period (period_key),
    policy_id      bigint NOT NULL,
    split_pct      numeric(5, 2)  NOT NULL,
    base_premium   numeric(12, 2) NOT NULL,
    commission_amt numeric(12, 2) NOT NULL,
    loaded_at      timestamp(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT ux_fact_row UNIQUE (policy_id, agent_key, period_key)
);

-- Oracle: MATERIALIZED VIEW ... BUILD IMMEDIATE REFRESH COMPLETE ON DEMAND.
-- PostgreSQL materialized views are always complete-refresh on demand:
--   REFRESH MATERIALIZED VIEW commission_dw.mv_agent_commission_summary;
CREATE MATERIALIZED VIEW mv_agent_commission_summary AS
SELECT da.agent_code,
       da.full_name,
       dd.period_month,
       dp.line_of_business,
       COUNT(*)              AS policy_rows,
       SUM(f.commission_amt) AS total_commission
  FROM fact_commission f
  JOIN dim_agent   da ON da.agent_key   = f.agent_key
  JOIN dim_product dp ON dp.product_key = f.product_key
  JOIN dim_period  dd ON dd.period_key  = f.period_key
 GROUP BY da.agent_code, da.full_name, dd.period_month, dp.line_of_business
WITH DATA;

RESET ROLE;
