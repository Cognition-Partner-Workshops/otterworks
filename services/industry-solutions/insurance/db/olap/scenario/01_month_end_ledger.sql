-- Month-end scenario, step 1 of 3 (run as COMMISSION_PAY against FREEPDB1).
-- Computes the commission ledger for every eligible policy for each month-end
-- 2025-01..2025-12, through COMMISSION_PKG only. Eligible = status IN_FORCE,
-- issued on or before the month-end, and carrying a split allocation.
--
-- Scenario-only reference data (never added to oltp/02_seed.sql):
--   COMM-GL  (COMMERCIAL) product, default rate 12.00, agent 3 override 13.50
--   POL-2025-0101  COMM-GL 7500.00, 3-way split 33.34/33.33/33.33 (agents 1/2/3):
--                  monthly rows 25.005 -> 25.01 (half-up; half-even would give
--                  25.00), 24.9975 -> 25.00, 28.1221875 -> 28.12; the rows sum
--                  to 78.13 while the unrounded total rounds to 78.12
--   POL-2025-0102  TERM-20 (LIFE) 3000.00, 50/50 agents 2/3; split corrected to
--                  70/30 and 2025-12 re-run (ledger rows replaced)
--   HOME-PLUS default superseded 10.00 -> 12.00 from 2025-07-01 (policy 2)
-- The seeded agent override (agent 1, AUTO-STD 9.50) applies to policies 1 and 4.
--
-- Idempotent: every run resets the scenario inputs and recomputes all periods,
-- so a second run leaves identical ledger amounts. Refuses to run once the
-- OLTP test suite (actor 'tester') has changed the fixture.
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
SET FEEDBACK OFF

DECLARE
    l_count PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO l_count FROM rate_audit_log WHERE actor = 'tester';
    IF l_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20090,
            'The OLTP test suite has already run against this fixture (it re-allocates policy 3); '
            || 'the baseline needs a fresh one: make insurance-down, then make insurance-up');
    END IF;
END;
/

MERGE INTO products d
USING (SELECT 'COMM-GL' AS product_code,
              'Commercial General Liability' AS product_name,
              'COMMERCIAL' AS line_of_business
         FROM dual) s
   ON (d.product_code = s.product_code)
 WHEN MATCHED THEN UPDATE SET
      d.product_name = s.product_name,
      d.line_of_business = s.line_of_business
 WHEN NOT MATCHED THEN
      INSERT (product_code, product_name, line_of_business)
      VALUES (s.product_code, s.product_name, s.line_of_business);

MERGE INTO policies d
USING (SELECT 101 AS policy_id, 'POL-2025-0101' AS policy_no, 'COMM-GL' AS product_code,
              'Harbor Freight Services Inc' AS holder_name, 7500.00 AS annual_premium,
              DATE '2025-01-02' AS issued_date, 'IN_FORCE' AS status
         FROM dual
       UNION ALL
       SELECT 102, 'POL-2025-0102', 'TERM-20', 'A. Lindqvist', 3000.00,
              DATE '2025-01-15', 'IN_FORCE'
         FROM dual) s
   ON (d.policy_id = s.policy_id)
 WHEN MATCHED THEN UPDATE SET
      d.policy_no = s.policy_no,
      d.product_code = s.product_code,
      d.holder_name = s.holder_name,
      d.annual_premium = s.annual_premium,
      d.issued_date = s.issued_date,
      d.status = s.status
 WHEN NOT MATCHED THEN
      INSERT (policy_id, policy_no, product_code, holder_name, annual_premium, issued_date, status)
      VALUES (s.policy_id, s.policy_no, s.product_code, s.holder_name, s.annual_premium,
              s.issued_date, s.status);
COMMIT;

ALTER TABLE policies MODIFY policy_id GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE);

DECLARE
    l_rate_id NUMBER;
BEGIN
    -- A same-day upsert amends the open rate in place, so re-runs reuse these rate rows.
    commission_pkg.upsert_commission_rate('COMM-GL', NULL, 12.00, DATE '2025-01-01', 'scenario', l_rate_id);
    commission_pkg.upsert_commission_rate('COMM-GL', 3, 13.50, DATE '2025-01-01', 'scenario', l_rate_id);
    commission_pkg.upsert_commission_rate('HOME-PLUS', NULL, 12.00, DATE '2025-07-01', 'scenario', l_rate_id);

    commission_pkg.set_commission_splits(101,
        split_alloc_tab(split_alloc_t(1, 33.34), split_alloc_t(2, 33.33), split_alloc_t(3, 33.33)),
        'scenario');
    commission_pkg.set_commission_splits(102,
        split_alloc_tab(split_alloc_t(2, 50), split_alloc_t(3, 50)), 'scenario');
END;
