DECLARE
    g_failures PLS_INTEGER := 0;
    l_first_id NUMBER;
    l_num      NUMBER;
    l_num2     NUMBER;

    PROCEDURE check_case (p_name IN VARCHAR2, p_ok IN BOOLEAN, p_detail IN VARCHAR2 DEFAULT NULL) IS
    BEGIN
        IF p_ok THEN
            DBMS_OUTPUT.PUT_LINE('PASS ' || p_name);
        ELSE
            g_failures := g_failures + 1;
            DBMS_OUTPUT.PUT_LINE('FAIL ' || p_name
                || CASE WHEN p_detail IS NOT NULL THEN ' -- ' || p_detail END);
        END IF;
    END check_case;

    FUNCTION amt (p_policy NUMBER, p_agent NUMBER, p_period VARCHAR2) RETURN NUMBER IS
        l_amt NUMBER;
    BEGIN
        SELECT commission_amt INTO l_amt FROM commission_ledger
         WHERE policy_id = p_policy AND agent_id = p_agent AND period_month = p_period;
        RETURN l_amt;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN NULL;
    END amt;

    FUNCTION pct (p_policy NUMBER, p_agent NUMBER, p_period VARCHAR2) RETURN NUMBER IS
        l_pct NUMBER;
    BEGIN
        SELECT r.rate_pct INTO l_pct
          FROM commission_ledger l JOIN commission_rates r ON r.rate_id = l.rate_id
         WHERE l.policy_id = p_policy AND l.agent_id = p_agent AND l.period_month = p_period;
        RETURN l_pct;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN NULL;
    END pct;
BEGIN
    -- Period re-run: correct policy 102's split to 70/30 and re-run 2025-12.
    SELECT MIN(ledger_id) INTO l_first_id FROM commission_ledger
     WHERE policy_id = 102 AND period_month = '2025-12';
    commission_pkg.set_commission_splits(102,
        split_alloc_tab(split_alloc_t(2, 70), split_alloc_t(3, 30)), 'scenario');
    commission_pkg.calculate_policy_commission(102, '2025-12', 'scenario');

    check_case('S1 3-way split rounds per agent row half-up',
               amt(101, 1, '2025-01') = 25.01 AND amt(101, 2, '2025-01') = 25.00
               AND amt(101, 3, '2025-01') = 28.12,
               amt(101, 1, '2025-01') || '/' || amt(101, 2, '2025-01') || '/' || amt(101, 3, '2025-01'));
    SELECT SUM(commission_amt) INTO l_num FROM commission_ledger
     WHERE policy_id = 101 AND period_month = '2025-01';
    check_case('S1a 3-way rows sum to 78.13 (unrounded total 78.1246875)', l_num = 78.13, 'sum=' || l_num);

    check_case('S2 agent override beats product default',
               pct(101, 3, '2025-01') = 13.50 AND pct(101, 2, '2025-01') = 12.00
               AND pct(1, 1, '2025-02') = 9.50 AND pct(4, 2, '2025-05') = 8.00,
               pct(101, 3, '2025-01') || '/' || pct(101, 2, '2025-01') || '/'
               || pct(1, 1, '2025-02') || '/' || pct(4, 2, '2025-05'));

    check_case('S3 HOME-PLUS rate superseded from 2025-07',
               pct(2, 1, '2025-06') = 10.00 AND amt(2, 1, '2025-06') = 12.00
               AND pct(2, 1, '2025-07') = 12.00 AND amt(2, 1, '2025-07') = 14.40,
               pct(2, 1, '2025-06') || ':' || amt(2, 1, '2025-06') || ' -> '
               || pct(2, 1, '2025-07') || ':' || amt(2, 1, '2025-07'));

    SELECT COUNT(*), MIN(ledger_id) INTO l_num, l_num2 FROM commission_ledger
     WHERE policy_id = 102 AND period_month = '2025-12';
    check_case('S4 period re-run replaces ledger rows',
               l_num = 2 AND l_num2 > l_first_id
               AND amt(102, 2, '2025-12') = 26.25 AND amt(102, 3, '2025-12') = 11.25
               AND amt(102, 2, '2025-11') = 18.75 AND amt(102, 3, '2025-11') = 18.75,
               'rows=' || l_num || ' ' || amt(102, 2, '2025-12') || '/' || amt(102, 3, '2025-12'));

    SELECT COUNT(DISTINCT pr.line_of_business) INTO l_num
      FROM commission_ledger l
      JOIN policies po ON po.policy_id = l.policy_id
      JOIN products pr ON pr.product_code = po.product_code;
    check_case('S5 every line of business has ledger rows', l_num = 4, 'lobs=' || l_num);

    SELECT COUNT(*) INTO l_num FROM commission_ledger l JOIN policies po ON po.policy_id = l.policy_id
     WHERE l.policy_id IN (3, 5)
        OR l.period_month < TO_CHAR(po.issued_date, 'YYYY-MM')
        OR l.period_month NOT BETWEEN '2025-01' AND '2025-12';
    check_case('S6 no rows for ineligible policy-periods', l_num = 0, 'rows=' || l_num);

    -- policy 1: 11 x 1, policy 2: 10 x 2, policy 4: 8 x 3, policy 101: 12 x 3, policy 102: 12 x 2
    SELECT COUNT(*), SUM(commission_amt) INTO l_num, l_num2 FROM commission_ledger;
    check_case('S7 ledger has 115 rows', l_num = 115, 'rows=' || l_num || ' total=' || l_num2);

    DBMS_OUTPUT.PUT_LINE('----');
    IF g_failures = 0 THEN
        DBMS_OUTPUT.PUT_LINE('SCENARIO LEDGER: ALL PASS (rows=' || l_num || ' total=' || l_num2 || ')');
    ELSE
        DBMS_OUTPUT.PUT_LINE('SCENARIO LEDGER: ' || g_failures || ' FAILURE(S)');
        RAISE_APPLICATION_ERROR(-20099, g_failures || ' scenario check failure(s)');
    END IF;
END;
/

EXIT;
