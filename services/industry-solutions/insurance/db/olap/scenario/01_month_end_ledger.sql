DECLARE
    l_policies PLS_INTEGER;
BEGIN
    FOR p IN (SELECT TO_CHAR(ADD_MONTHS(DATE '2025-01-01', LEVEL - 1), 'YYYY-MM') AS period_month
                FROM dual
             CONNECT BY LEVEL <= 12
               ORDER BY 1) LOOP
        l_policies := 0;
        FOR pol IN (SELECT po.policy_id
                      FROM policies po
                     WHERE po.status = 'IN_FORCE'
                       AND po.issued_date <= LAST_DAY(TO_DATE(p.period_month, 'YYYY-MM'))
                       AND EXISTS (SELECT 1 FROM commission_splits s WHERE s.policy_id = po.policy_id)
                     ORDER BY po.policy_id) LOOP
            commission_pkg.calculate_policy_commission(pol.policy_id, p.period_month, 'scenario');
            l_policies := l_policies + 1;
        END LOOP;
        DBMS_OUTPUT.PUT_LINE('calculated ' || p.period_month || ': ' || l_policies || ' policies');
    END LOOP;
END;
