-- unt19-20261030 slice-0, Lakebase track: schema and the two tables later slices WRITE
-- (TENANTS via PKG_DUNNING.SP_SUSPEND_OVERDUE and the app's ensure_tenant; BILLING_AUDIT_LOG via
-- PKG_OW_UTIL.LOG_MSG). CODES and PLANS are reference data: synced tables from the Delta mirror
-- (synced_tables/*.json) when the branch database is registered in UC, otherwise plain tables
-- loaded from the same mirror by load_lakebase.py. Hand-converted from
-- services/legacy-billing/db/oracle/schema/01_tables.sql (Lakebridge could not be installed on
-- this VM: GitHub 403 from `databricks labs install lakebridge`); type choices follow
-- .migration/recon/slice-0/inputs/mapping.json.
CREATE SCHEMA IF NOT EXISTS mig_unt19_20261030_slice_0;

-- CHAR(1) -> text (mapping: rstrip_spaces + empty_string_is_null); NUMBER(4) -> numeric(4,0).
CREATE TABLE IF NOT EXISTS mig_unt19_20261030_slice_0.tenants (
    id            text         NOT NULL,
    name          text         NOT NULL,
    tax_exempt_yn text         NOT NULL DEFAULT 'N',
    status_cd     numeric(4,0) NOT NULL,   -- CODES('TENANT_STATUS')
    CONSTRAINT pk_tenants PRIMARY KEY (id),
    CONSTRAINT uq_tenants_name UNIQUE (name)
);

-- SEQ_BILLING_AUDIT_LOG + TRG_BILLING_AUDIT_LOG_ID become an identity column
-- (d-sequences-become-identity, dialect trap 10). Oracle DATE DEFAULT SYSDATE carries seconds in
-- the server zone; the branch runs in UTC, so the default is the UTC wall clock at second grain.
CREATE TABLE IF NOT EXISTS mig_unt19_20261030_slice_0.billing_audit_log (
    log_id    bigint    GENERATED BY DEFAULT AS IDENTITY,
    logged_at timestamp NOT NULL DEFAULT date_trunc('second', (now() AT TIME ZONE 'UTC')),
    module    text,
    message   text,
    CONSTRAINT pk_billing_audit_log PRIMARY KEY (log_id)
);

-- Reference tables. load_lakebase.py creates them from the Delta mirror only when no synced
-- table of that name exists (a synced table is created by `databricks postgres
-- create-synced-table` and is read-only in Postgres).
CREATE TABLE IF NOT EXISTS mig_unt19_20261030_slice_0.codes (
    code_type text         NOT NULL,
    code_val  numeric(4,0) NOT NULL,
    code_desc text         NOT NULL,
    CONSTRAINT pk_codes PRIMARY KEY (code_type, code_val)
);

CREATE TABLE IF NOT EXISTS mig_unt19_20261030_slice_0.plans (
    id             text          NOT NULL,
    code           text          NOT NULL,
    tier_cd        numeric(4,0)  NOT NULL,   -- CODES('PLAN_TIER')
    monthly_fee    numeric(12,2) NOT NULL,
    included_units numeric(10,0) NOT NULL,
    overage_rate   numeric(12,6) NOT NULL,
    active_yn      text          NOT NULL DEFAULT 'Y',
    CONSTRAINT pk_plans PRIMARY KEY (id),
    CONSTRAINT uq_plans_code UNIQUE (code)
);
